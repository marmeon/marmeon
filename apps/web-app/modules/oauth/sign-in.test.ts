// Generated by `marmeon make:oauth` — signing in at a provider, with the provider side answered by `fakeOAuth()`, so nothing leaves the
// process and the state, the PKCE verifier and the checks of the answer still run. Runs on SQLite and Postgres.

/** Starts a flow for any intent, as a page that links or confirms an account would: for the signed-in user when there is one. */
class StartFlowController extends Controller {
  readonly #oauth: OAuth;
  readonly #auth: Auth;
  constructor(oauth: OAuth, auth: Auth) {
    super();
    this.#oauth = oauth;
    this.#auth = auth;
  }
  async handle(ctx: { params: { provider: string; intent: string } }) {
    const userId = await this.#auth.id();
    const started = await this.#oauth.redirect(ctx.params.provider, { intent: ctx.params.intent, ...(userId === undefined ? {} : { userId }) } as never);
    return this.redirect(started.ok ? started.value.href : '/');
  }
}

const fixtures = defineModule({
  name: 'oauth-fixtures',
  routes: defineRoutes((Route) => {
    Route.authorize(everyone).post('/fixtures/oauth/:provider/:intent', StartFlowController as never);
  }),
});

let app: TestApp;
let SESSION: string;
const boot = async (env: Record<string, string> = {}) => {
  app = await createTestApp({ ...application, modules: [...application.modules!, fixtures] }, { database: 'refresh', env });
  ({ session: SESSION } = cookieNames(app));
};
afterEach(() => app.close());

type Browser = ReturnType<TestApp['keepingCookies']>;

/** The start of a sign-in at `provider`: a POST from the page, answered with the provider's authorization page. */
const start = (browser: Browser, provider = 'github') => browser.post(`/auth/${provider}/redirect`).assertStatus(303);
/** A whole sign-in in one browser: the start, then the provider sends the browser back with what the fake queued. */
const signIn = async (browser: Browser, oauth: OAuthFake, provider = 'github') => browser.get(oauth.callbackUrl(await start(browser, provider)));
const users = () => app.make(Connections).get<any>().selectFrom('users').selectAll().execute() as Promise<User[]>;
/** The ids of the users with no password: the column is secret, so it is filtered on, never read. */
const withoutPassword = async () => (await app.make(Connections).get<any>().selectFrom('users').select('id').where('password', 'is', null).execute()).map((row: { id: number }) => row.id);
const linked = () => app.make(Connections).get<any>().selectFrom('social_accounts').select(['user_id', 'provider', 'provider_id']).execute();

/** A provider account of `user`, as an earlier sign-in or the settings page would have linked it. */
async function link(user: User, provider: string, id: string) {
  const now = new Date().toISOString();
  await app.make(Connections).get<any>().insertInto('social_accounts').values({ user_id: user.id, provider, provider_id: id, email: user.email, created_at: now, updated_at: now }).execute();
}

/** Turns the authenticator on for `user`, as the settings page does. */
async function enableTwoFactor(user: User) {
  const login = await app.post('/login', { form: { email: user.email, password: 'password' } }).assertRedirect('/users/me');
  const cookie = login.cookie(SESSION)!;
  await app.withCookie(SESSION, cookie).post('/settings/two-factor/setup').assertRedirect('/settings/two-factor');
  const page = await app.withCookie(SESSION, cookie).navigating().get('/settings/two-factor').assertPage('auth/TwoFactor');
  const setup = page.page()!.props.setup as { secret: string };
  await app.withCookie(SESSION, cookie).layering().post('/settings/two-factor/confirm', { form: { code: twoFactorCode(setup.secret), password: 'password' } }).assertLayer('auth/RecoveryCodes');
}

describe('signing in at a provider', { timeout: 30_000 }, () => {
  // Every test boots the app on a refreshed database — seconds on a busy machine, so its hook and tests get 30 s.
  beforeEach(() => boot(), 30_000);

  it('signs in with a provider through redirect and callback', async () => {
    const oauth = fakeOAuth(app).user('github', { id: '42', email: 'Ada@Example.com', emailVerified: true, name: 'Ada Lovelace' });
    const browser = app.keepingCookies();
    await signIn(browser, oauth).then((back) => back.assertRedirect('/users/me').assertAuthenticated());
    await browser.get('/dashboard').assertOk();
    // A new account without a password, its address confirmed because the provider vouched for it, and the provider account linked to it.
    const [ada] = await users();
    expect(ada).toMatchObject({ email: 'ada@example.com', name: 'Ada Lovelace' });
    expect(await withoutPassword()).toEqual([ada!.id]);
    expect(ada!.email_verified_at).not.toBeNull();
    expect(await linked()).toEqual([{ user_id: ada!.id, provider: 'github', provider_id: '42' }]);
    // The same provider account signs in the same user again.
    await signIn(app.keepingCookies(), fakeOAuth(app).user('github', { id: '42', email: 'other@example.com', emailVerified: true })).then((back) => back.assertRedirect('/users/me'));
    expect(await users()).toHaveLength(1);
  });

  it('starts the flow by POST only: a GET is not a route', async () => {
    fakeOAuth(app);
    const browser = app.keepingCookies();
    const get = await browser.get('/auth/github/redirect');
    expect(get.status).toBe(404);
    // Nothing was opened: no flow in the session, no redirect to the provider.
    expect(get.headers.get('location')).toBeNull();
    const post = await browser.post('/auth/github/redirect').assertStatus(303);
    // The state is 32 random bytes in base64url.
    expect(new URL(post.headers.get('location')!).searchParams.get('state')).toMatch(/^[A-Za-z0-9_-]{43}$/);
  });

  it('says so when the provider account cannot be stored, and signs nobody in', async () => {
    // An address of 255 characters passes the callback (its limit is 255) and fails the store (254): nothing is kept, not even the user.
    const long = `${'a'.repeat(243)}@example.com`;
    expect(long).toHaveLength(255);
    const oauth = fakeOAuth(app).user('github', { id: '42', email: long, emailVerified: true });
    const back = await signIn(app.keepingCookies(), oauth);
    back.assertRedirect('/login').assertFlashed('toast', { kind: 'error', message: 'The sign-in did not work. Try again, or sign in another way.' });
    back.assertGuest();
    expect(await users()).toHaveLength(0);
    expect(await linked()).toEqual([]);
  });

  it('answers 404 for an unknown or unconfigured provider', async () => {
    fakeOAuth(app, { only: ['github'] });
    const browser = app.keepingCookies();
    await browser.post('/auth/google/redirect').assertStatus(404);
    await browser.post('/auth/nowhere/redirect').assertStatus(404);
    await browser.get('/auth/google/callback?code=x&state=y').assertStatus(404);
    await browser.get('/auth/NOWHERE/callback').assertStatus(404);
  });

  it('sends a known provider account with a second factor to the challenge', async () => {
    const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
    await link(ada, 'github', '42');
    await enableTwoFactor(ada);
    const oauth = fakeOAuth(app).user('github', { id: '42', email: 'ada@example.com', emailVerified: true });
    const back = await signIn(app.keepingCookies(), oauth);
    // Nobody is signed in until the code is proven, exactly as after a password.
    back.assertRedirect('/two-factor-challenge').assertGuest();
  });

  it('refuses to link automatically when the account has a second factor', async () => {
    const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
    await enableTwoFactor(ada);
    const oauth = fakeOAuth(app).user('github', { id: '42', email: 'ada@example.com', emailVerified: true });
    const back = await signIn(app.keepingCookies(), oauth);
    back.assertRedirect('/login').assertGuest().assertFlashed('toast', { kind: 'error', message: 'An account with this address exists already. Sign in the usual way, then connect the provider from your account settings.' });
    expect(await linked()).toEqual([]);
  });

  it('with private registration, an unverified taken address and a new one get the same answer', async () => {
    await app.factory(UserFactory).create({ email: 'ada@example.com' });
    const answer = async (email: string) => {
      const oauth = fakeOAuth(app).user('github', { id: email, email, emailVerified: false });
      const back = await signIn(app.keepingCookies(), oauth).then((response) => response.assertRedirect('/login').assertGuest());
      return { status: back.status, location: back.headers.get('location'), flashed: back.flashed().map((message) => message.data) };
    };
    const taken = await answer('ada@example.com');
    const fresh = await answer('new@example.com');
    expect(fresh).toEqual(taken);
    expect(taken.flashed).toHaveLength(1);
    // Nothing was made or linked for either.
    await app.assertDatabaseCount('users', 1);
    expect(await linked()).toEqual([]);
  });

  it('mails the owner of a taken address', async () => {
    const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
    for (const email of ['ada@example.com', 'new@example.com']) {
      await signIn(app.keepingCookies(), fakeOAuth(app).user('github', { id: email, email, emailVerified: false })).then((back) => back.assertRedirect('/login'));
    }
    // Both requests queue the job and are answered alike; a worker decides, and nothing is rendered in the request.
    app.queue.assertDispatched(SendSocialAccountExistsMailJob, { email: 'ada@example.com' });
    app.queue.assertDispatched(SendSocialAccountExistsMailJob, { email: 'new@example.com' });
    app.mail.assertNothingQueued();
    await app.queue.work();
    app.mail.assertQueuedCount(SocialAccountExistsMail, 1);
    app.mail.assertQueued(SocialAccountExistsMail, (_mail, message) => message.to[0]!.address === ada.email && message.text.includes('GitHub'));
  });

  it('a callback with a foreign state signs nobody in', async () => {
    const oauth = fakeOAuth(app).user('github', { id: '42', email: 'ada@example.com', emailVerified: true });
    const browser = app.keepingCookies();
    const opened = await start(browser);
    await browser.get(oauth.callbackUrl(opened, { state: 'forged' })).assertRedirect('/login').assertGuest();
    await app.assertDatabaseCount('users', 0);
    await app.assertDatabaseCount('social_accounts', 0);
  });

  it('a cancelled sign-in returns to the login page with its message', async () => {
    const oauth = fakeOAuth(app).deny('github');
    const back = await signIn(app.keepingCookies(), oauth);
    back.assertRedirect('/login').assertGuest().assertFlashed('toast', { kind: 'error', message: 'The sign-in was cancelled. Nothing has changed.' });
    await app.assertDatabaseCount('users', 0);
  });

  it('the sign-in island lists the active providers only', async () => {
    fakeOAuth(app, { only: ['github', 'discord'] });
    await app
      .islanding()
      .get('/oauth/sign-in')
      .assertIsland<ShowSignInButtonsController>('oauth/SignInButtons', (props) => {
        expect(props.providers.map((provider) => provider.name).sort()).toEqual(['discord', 'github']);
        expect(props.providers.find((provider) => provider.name === 'github')).toEqual({ name: 'github', label: 'GitHub' });
      });
  });

  it('the callback path is the one the package derives', async () => {
    fakeOAuth(app);
    const opened = await start(app.keepingCookies());
    const sent = new URL(new URL(opened.headers.get('location')!).searchParams.get('redirect_uri')!);
    // The provider is sent exactly the path the callback route has: the two cannot drift apart.
    expect(sent.pathname).toBe(app.make(Router).url('oauth.callback', { provider: 'github' }));
  });

  it('signs in the owner of an address both sides confirmed, and links the account', async () => {
    const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
    const oauth = fakeOAuth(app).user('github', { id: '42', email: 'ada@example.com', emailVerified: true });
    const back = await signIn(app.keepingCookies(), oauth);
    back.assertRedirect('/users/me').assertAuthenticated(ada);
    await app.assertDatabaseCount('users', 1);
    expect(await linked()).toEqual([{ user_id: ada.id, provider: 'github', provider_id: '42' }]);
  });

  it('finds the user of an address however the provider writes it: trimmed, in any case', async () => {
    const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
    // The package normalizes what it can; the bridge does it for itself too, so it never depends on that.
    const users = app.container.createScope().make(SocialUsers);
    expect((await users.findByEmail('  ADA@Example.COM ')) ?? null).toEqual({ user: expect.objectContaining({ id: ada.id }), emailVerified: true });
    expect(await users.findByEmail('nobody@example.com')).toBeUndefined();
  });

  it('answers a state that was spent already like any other: nobody is signed in by a replay', async () => {
    const oauth = fakeOAuth(app).user('github', { id: '42', email: 'ada@example.com', emailVerified: true });
    const opened = await app.post('/auth/github/redirect').assertStatus(303);
    const cookie = opened.cookie(SESSION)!;
    const url = oauth.callbackUrl(opened);
    const first = await app.withCookie(SESSION, cookie).get(url).assertRedirect('/users/me').assertAuthenticated();
    expect(first.cookie(SESSION)).toBeDefined();
    await app.withCookie(SESSION, cookie).get(url).assertRedirect('/login').assertGuest().assertFlashed('toast', { kind: 'error', message: 'The sign-in did not work. Try again, or sign in another way.' });
    await app.assertDatabaseCount('users', 1);
  });

  it('refuses a flow that was started for another intent: only a sign-in signs in here', async () => {
    const oauth = fakeOAuth(app).user('github', { id: '42', email: 'ada@example.com', emailVerified: true });
    const browser = app.keepingCookies();
    const opened = await browser.post('/fixtures/oauth/github/link').assertStatus(303);
    await browser.get(oauth.callbackUrl(opened)).assertRedirect('/login').assertGuest().assertFlashed('toast', { kind: 'error', message: 'The sign-in did not work. Try again, or sign in another way.' });
    await app.assertDatabaseCount('users', 0);
    await app.assertDatabaseCount('social_accounts', 0);
  });

  it('binds the flow to the user it was started for: a guest flow does not serve somebody who signed in meanwhile', async () => {
    const ada = await app.factory(UserFactory).create();
    const oauth = fakeOAuth(app).user('github', { id: '42', email: 'other@example.com', emailVerified: true });
    const browser = app.keepingCookies();
    const opened = await start(browser);
    await browser.post('/login', { form: { email: ada.email, password: 'password' } }).assertRedirect('/users/me');
    // The callback finds ada signed in and a flow of a guest: the flow is refused, not served as a sign-in of somebody else.
    // A signed-in person goes back with the message (the sign-in page would turn them away and the message with it); a guest ends on the sign-in page.
    await browser.get(oauth.callbackUrl(opened)).assertRedirect('/users/me').assertFlashed('toast', { kind: 'error', message: 'That did not work. Try again.' });
    await app.assertDatabaseCount('users', 1);
    await app.assertDatabaseCount('social_accounts', 0);
  });

  it('says so when the person who started a sign-in is signed in already', async () => {
    const ada = await app.factory(UserFactory).create();
    const oauth = fakeOAuth(app).user('github', { id: '42', email: 'other@example.com', emailVerified: true });
    const browser = app.keepingCookies();
    await browser.post('/login', { form: { email: ada.email, password: 'password' } }).assertRedirect('/users/me');
    const opened = await browser.post('/fixtures/oauth/github/sign-in').assertStatus(303);
    // Back with the message, not to the sign-in page, which would turn a signed-in person away and the message with it.
    await browser.get(oauth.callbackUrl(opened)).assertRedirect('/users/me').assertFlashed('toast', { kind: 'error', message: 'You are signed in already.' });
    await app.assertDatabaseCount('users', 1);
  });

  it('sends a signed-in person whose flow has another intent back with the message, and a guest to the sign-in page', async () => {
    const ada = await app.factory(UserFactory).create();
    const oauth = fakeOAuth(app).user('github', { id: '42', email: 'other@example.com', emailVerified: true });
    const signedIn = app.keepingCookies();
    await signedIn.post('/login', { form: { email: ada.email, password: 'password' } }).assertRedirect('/users/me');
    const opened = await signedIn.post('/fixtures/oauth/github/delete').assertStatus(303);
    await signedIn.get(oauth.callbackUrl(opened)).assertRedirect('/users/me').assertFlashed('toast', { kind: 'error', message: 'That did not work. Try again.' });
    const guest = app.keepingCookies();
    const other = await guest.post('/fixtures/oauth/github/delete').assertStatus(303);
    await guest.get(fakeOAuth(app).user('github', { id: '43', email: 'x@example.com', emailVerified: true }).callbackUrl(other)).assertRedirect('/login').assertGuest().assertFlashed('toast', { kind: 'error', message: 'The sign-in did not work. Try again, or sign in another way.' });
    await app.assertDatabaseCount('social_accounts', 0);
  });

  it('turns away a signed-in person at the start and at the island: signing in is for guests', async () => {
    const ada = await app.factory(UserFactory).create();
    fakeOAuth(app);
    const start = await app.actingAs(ada).post('/auth/github/redirect');
    expect(start.headers.get('location') ?? '').not.toContain('oauth.fake.invalid');
    start.assertRedirect('/users/me');
    const island = await app.actingAs(ada).islanding().get('/oauth/sign-in');
    // The guest middleware turns the island request away (a 204, which `<Island unauthorized>` shows its own content for), not with an island.
    island.assertStatus(204);
    expect(island.island()).toBeUndefined();
  });

  it('limits the starts of one client to ten a minute', async () => {
    fakeOAuth(app);
    const browser = app.withIp('203.0.113.50');
    const statuses: number[] = [];
    for (let i = 0; i < 11; i++) statuses.push((await browser.post('/auth/github/redirect')).status);
    expect(statuses.slice(0, 10)).toEqual(Array(10).fill(303));
    expect(statuses[10]).toBe(429);
    expect((await app.withIp('203.0.113.51').post('/auth/github/redirect')).status).toBe(303);
  });

  it('declares one callback per session at a time (block())', async () => {
    const route = app.make(Router).findByName('oauth.callback')!;
    expect(route.blocking).toEqual({ lockSeconds: 60, waitSeconds: 10 });
  });

  it('counts a callback against its own session: strangers cannot use up the limit of somebody who is signing in', async () => {
    const oauth = fakeOAuth(app).user('github', { id: '42', email: 'ada@example.com', emailVerified: true });
    const address = '203.0.113.60';
    const opened = await app.withIp(address).post('/auth/github/redirect').assertStatus(303);
    const url = oauth.callbackUrl(opened);
    // Twenty requests without a session from the same address: the limit of that client is used up for them.
    for (let i = 0; i < 20; i++) await app.withIp(address).get('/auth/github/callback?code=x&state=y');
    expect((await app.withIp(address).get('/auth/github/callback?code=x&state=y')).status).toBe(429);
    // The browser that holds the flow is counted on its own and still completes its sign-in.
    await app.withIp(address).withCookie(SESSION, opened.cookie(SESSION)!).get(url).assertRedirect('/users/me').assertAuthenticated();
  });

  it('still stops one browser after twenty callbacks a minute', async () => {
    fakeOAuth(app);
    const browser = app.withIp('203.0.113.61').withCookie(SESSION, (await app.withIp('203.0.113.61').post('/auth/github/redirect')).cookie(SESSION)!);
    const statuses: number[] = [];
    for (let i = 0; i < 21; i++) statuses.push((await browser.get('/auth/github/callback?code=x&state=y')).status);
    expect(statuses.slice(0, 20)).not.toContain(429);
    expect(statuses[20]).toBe(429);
  });

  it('mails the owner of a taken address at most once an hour', async () => {
    await app.factory(UserFactory).create({ email: 'ada@example.com' });
    for (let i = 0; i < 3; i++) {
      await signIn(app.keepingCookies(), fakeOAuth(app).user('github', { id: String(i), email: 'ada@example.com', emailVerified: false })).then((back) => back.assertRedirect('/login'));
    }
    await app.queue.work();
    app.mail.assertQueuedCount(SocialAccountExistsMail, 1);
    app.travel({ minutes: 61 });
    await signIn(app.keepingCookies(), fakeOAuth(app).user('github', { id: '9', email: 'ada@example.com', emailVerified: false })).then((back) => back.assertRedirect('/login'));
    await app.queue.work();
    app.mail.assertQueuedCount(SocialAccountExistsMail, 2);
  });

  it('says so when the provider shares no address, and makes nobody', async () => {
    const oauth = fakeOAuth(app).user('github', { id: '42', email: null });
    (await signIn(app.keepingCookies(), oauth)).assertRedirect('/login').assertGuest().assertFlashed('toast', { kind: 'error', message: 'The provider shared no e-mail address, and this app needs one. Sign in another way.' });
    await app.assertDatabaseCount('users', 0);
  });
});

describe('with OAUTH_REGISTRATION=false', { timeout: 30_000 }, () => {
  beforeEach(() => boot({ OAUTH_REGISTRATION: 'false' }), 30_000);

  it('makes no new user, and says so; a linked account still signs in', async () => {
    const oauth = fakeOAuth(app).user('github', { id: '42', email: 'ada@example.com', emailVerified: true });
    (await signIn(app.keepingCookies(), oauth)).assertRedirect('/login').assertGuest().assertFlashed('toast', { kind: 'error', message: 'New accounts cannot be created with a provider here. Sign in with an account you have.' });
    await app.assertDatabaseCount('users', 0);
    const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
    await link(ada, 'github', '42');
    (await signIn(app.keepingCookies(), fakeOAuth(app).user('github', { id: '42', email: 'ada@example.com', emailVerified: true }))).assertRedirect('/users/me').assertAuthenticated(ada);
  });
});
