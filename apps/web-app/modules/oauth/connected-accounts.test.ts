const rows = () => app.make(Connections).get<any>().selectFrom('social_accounts').select(['user_id', 'provider', 'provider_id']).orderBy('id').execute();
/** An account of `user` at `provider`, as an earlier link would have made it. */
async function seed(user: User, provider: string, id: string, lastUsedAt: string | null = null) {
  const now = new Date().toISOString();
  await app.make(Connections).get<any>().insertInto('social_accounts').values({ user_id: user.id, provider, provider_id: id, email: user.email, last_used_at: lastUsedAt, created_at: now, updated_at: now }).execute();
}
/** What `SocialAccounts` answers in a request, scripted: for the refusals that only a race produces (the session ending inside the link, a window refused by the guard). */
function scripted(answers: Partial<Record<'link' | 'unlink' | 'confirm', unknown>>) {
  app.container.instance(SocialAccounts, Object.fromEntries(Object.entries(answers).map(([name, answer]) => [name, async () => answer])) as never);
}
const refused = (kind: string) => err({ kind });
/** A person signed in with the password, in one browser. */
async function signedIn(user: User): Promise<Browser> {
  const browser = app.keepingCookies();
  await browser.post('/login', { form: { email: user.email, password: 'password' } }).assertRedirect('/users/me');
  return browser;
}
/** The confirmation window, opened by typing the password. */
const confirm = (browser: Browser) => browser.post('/confirm-password', { form: { password: 'password' } }).assertRedirect();
/** Starts linking `provider` and lets the provider send the browser back. */
async function link(browser: Browser, provider: string, profile: { id: string; email?: string | null }) {
  const oauth = fakeOAuth(app).user(provider, { emailVerified: true, ...profile });
  return browser.get(oauth.callbackUrl(await browser.post(`/oauth/accounts/${provider}`).assertStatus(303)));
}
