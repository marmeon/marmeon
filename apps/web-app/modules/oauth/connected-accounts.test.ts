// answered by `fakeOAuth()`. Runs on SQLite and Postgres.

/** Starts a link flow of the signed-in user of the request, or — with `:user` — of another user: what a mixed-up session would hold. */
class StartFlowController extends Controller {
  readonly #oauth: OAuth;
  readonly #auth: Auth;
  constructor(oauth: OAuth, auth: Auth) {
    super();
    this.#oauth = oauth;
    this.#auth = auth;
  }
  async handle(ctx: { params: { provider: string; user?: string } }) {
    const userId = ctx.params.user === undefined ? await this.#auth.id() : Number(ctx.params.user);
    const started = await this.#oauth.redirect(ctx.params.provider, { intent: 'link', userId });
    return this.redirect(started.ok ? started.value.href : '/');
  }
}

