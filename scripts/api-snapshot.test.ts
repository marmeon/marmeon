import { describe, expect, it } from 'vitest';
import { compareSnapshots, parseSnapshot, renderSnapshot, type ApiItem, type ApiSection } from './api-snapshot.ts';

const item = (name: string, text: string, section: ApiSection = 'stable', entry = '@marmeon/demo'): ApiItem => ({ entry, section, name, text });
const none = new Map<string, readonly string[]>();

describe('api.md format', () => {
  it('reads back what it writes, loss-free', () => {
    const items = [
      item('b', 'export declare const b: 1;'),
      item('a', 'export interface a {\n    x: string;\n}\nexport declare function a(): void;'),
      item('Hidden', 'interface Hidden {}', 'referenced'),
      item('old', '// @deprecated\nexport declare function old(): void;'),
      item('@marmeon/core.ApplicationDefinition', 'interface ApplicationDefinition {\n    x?: 1;\n}', 'augments'),
      item('Probe', 'export declare class Probe {}', 'experimental'),
      item('page', 'export declare const page: 1;', 'stable', '@marmeon/demo/page'),
      item('APP_URL', 'string, default http://localhost', 'environment', ''),
      item('demo:run', 'Runs the demo.', 'commands', ''),
    ];
    const markdown = renderSnapshot('@marmeon/demo', items, new Map([['@marmeon/demo', ['valibot']], ['@marmeon/demo/page', []]]));
    const parsed = parseSnapshot(markdown);
    expect(parsed).toHaveLength(items.length);
    for (const original of items) expect(parsed).toContainEqual(original);
    expect(markdown).toContain('Types from other packages: `valibot`');
    expect(markdown).toContain('Types from other packages: none');
  });

  it('tells the package-wide Experimental section from the one of an entry point', () => {
    const items = [
      item('Probe', 'export declare class Probe {}', 'experimental'),
      item('Options.pages', 'pages?: boolean;', 'experimental'),
      item('DEMO_FLAG', '`DEMO_FLAG` — optional', 'experimental', ''),
      item('demo:probe', 'marmeon demo:probe', 'experimental', ''),
    ];
    const markdown = renderSnapshot('@marmeon/demo', items, new Map([['@marmeon/demo', []]]));
    expect(markdown).toContain('\n### Experimental\n');
    expect(markdown).toContain('\n## Experimental\n');
    const parsed = parseSnapshot(markdown);
    expect(parsed).toHaveLength(items.length);
    for (const original of items) expect(parsed).toContainEqual(original);
  });

  it('sorts by name, so the order of the source does not matter', () => {
    const items = [item('b', 'export declare const b: 1;'), item('a', 'export declare const a: 1;')];
    expect(renderSnapshot('@marmeon/demo', items, none)).toBe(renderSnapshot('@marmeon/demo', [...items].reverse(), none));
    expect(renderSnapshot('@marmeon/demo', items, none).indexOf('// a')).toBeLessThan(renderSnapshot('@marmeon/demo', items, none).indexOf('// b'));
  });

  it('is deterministic LF text that ends in one newline', () => {
    const markdown = renderSnapshot('@marmeon/demo', [item('a', 'export declare const a: 1;')], none);
    expect(markdown).not.toContain('\r');
    expect(markdown.endsWith('```\n')).toBe(true);
    expect(markdown.startsWith('<!-- Generated by pnpm api:update')).toBe(true);
  });
});

describe('comparing two snapshots', () => {
  const before = [item('a', 'export declare function a(x: number): void;'), item('b', 'export declare const b: 1;'), item('c', 'export declare const c: 1;')];

  it('names what was removed, changed and added', () => {
    const after = [item('a', 'export declare function a(x: string): void;'), item('b', 'export declare const b: 1;'), item('d', 'export declare const d: 1;')];
    const changes = compareSnapshots(before, after);
    expect(changes.removed.map((entry) => entry.name)).toEqual(['c']);
    expect(changes.changed.map(({ before: was, after: is }) => [was.name, was.text, is.text])).toEqual([
      ['a', 'export declare function a(x: number): void;', 'export declare function a(x: string): void;'],
    ]);
    expect(changes.added.map((entry) => entry.name)).toEqual(['d']);
  });

  it('finds nothing when only the order differs', () => {
    expect(compareSnapshots(before, [...before].reverse())).toEqual({ removed: [], changed: [], added: [] });
  });

  it('counts a name that moves from referenced to stable as added, not as changed or removed', () => {
    const was = [item('Shape', 'interface Shape {}', 'referenced')];
    const is = [item('Shape', 'export interface Shape {}', 'stable')];
    const changes = compareSnapshots(was, is);
    expect(changes.added.map((entry) => entry.name)).toEqual(['Shape']);
    expect(changes.changed).toEqual([]);
    expect(changes.removed).toEqual([]);
  });

  it('counts a stable name that becomes only referenced as removed', () => {
    const changes = compareSnapshots([item('Shape', 'export interface Shape {}')], [item('Shape', 'interface Shape {}', 'referenced')]);
    expect(changes.removed.map((entry) => entry.name)).toEqual(['Shape']);
  });

  it('tells experimental from stable, so a move between them shows', () => {
    const changes = compareSnapshots([item('Probe', 'export declare class Probe {}', 'experimental')], [item('Probe', 'export declare class Probe {}', 'stable')]);
    expect(changes.added.map((entry) => entry.section)).toEqual(['stable']);
    expect(changes.removed.map((entry) => entry.section)).toEqual(['experimental']);
  });

  it('keeps the same name of two entry points apart', () => {
    const changes = compareSnapshots([item('x', 'a', 'stable', 'one')], [item('x', 'a', 'stable', 'one'), item('x', 'a', 'stable', 'two')]);
    expect(changes.added.map((entry) => entry.entry)).toEqual(['two']);
  });
});
