/**
 * The release rules the guard, the preparation and the checks share: the pull-request categories (and `.github/release.yml`,
 * generated from them), version, line and dist-tag arithmetic, the release commit and the changelog format.
 *
 * Imports nothing but `node:*` and `./packages.ts`: the release guard runs it before `pnpm install`, when no dependency of the
 * repository may run yet. See CONTRIBUTING.md, "Pull requests and releases".
 *
 *   node scripts/release-rules.ts            # write .github/release.yml
 *   node scripts/release-rules.ts --check    # exit 1 when the file is not what releaseConfig() makes (check-release runs this)
 */
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { frameworkPackages } from './packages.ts';

const root = fileURLToPath(new URL('..', import.meta.url));

/** The pull-request labels, in the order the notes list them; a label without a title (`internal`) never appears in the notes. */
export const CATEGORIES = [
  { label: 'breaking', title: 'Breaking changes' },
  { label: 'feature', title: 'Features' },
  { label: 'fix', title: 'Fixes' },
  { label: 'docs', title: 'Documentation' },
  { label: 'internal', title: undefined },
] as const;

export type Label = (typeof CATEGORIES)[number]['label'];

/** The catch-all category: GitHub leaves a pull request without a matching category out of the notes, so this one catches it. */
export const UNLABELLED = 'Without a release label';

export const RELEASE_CONFIG = '.github/release.yml';

/** The text of `.github/release.yml`: what GitHub's generated release notes sort the merged pull requests by. */
export function releaseConfig(): string {
  const titled = CATEGORIES.filter((category) => category.title !== undefined);
  return [
    '# Generated by `node scripts/release-rules.ts` — do not edit. It tells GitHub how to sort the merged pull requests into release',
    '# notes by their labels; the last category catches a pull request that has none, so the release preparation can refuse it.',
    'changelog:',
    '  exclude:',
    `    labels: [${CATEGORIES.filter((category) => category.title === undefined).map((category) => category.label).join(', ')}]`,
    '  categories:',
    ...titled.flatMap((category) => [`    - title: ${category.title}`, `      labels: [${category.label}]`]),
    `    - title: ${UNLABELLED}`,
    "      labels: ['*']",
    '',
  ].join('\n');
}

/** Whether `.github/release.yml` in `repository` is what `releaseConfig()` makes. */
export function releaseConfigCurrent(repository: string = root): boolean {
  const file = join(repository, RELEASE_CONFIG);
  return existsSync(file) && readFileSync(file, 'utf8') === releaseConfig();
}

/** `rc` is set for a release candidate, `x.y.z-rc.N`. */
export type Version = readonly [major: number, minor: number, patch: number, rc?: number];

/** `x.y.z` or the release candidate `x.y.z-rc.N` (N from 1) and nothing else: no leading zeros, no other prerelease, no build metadata, no `v`. */
export function parseVersion(text: string): Version | undefined {
  const match = /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-rc\.([1-9]\d*))?$/.exec(text);
  if (!match) return undefined;
  const base = [Number(match[1]), Number(match[2]), Number(match[3])] as const;
  return match[4] === undefined ? base : [...base, Number(match[4])];
}

/** Whether `text` is a plain `x.y.z`: what may be published as a release (a release candidate is not). */
export function isPlainVersion(text: string): boolean {
  const version = parseVersion(text);
  return version !== undefined && version[3] === undefined;
}

function mustParse(text: string): Version {
  const version = parseVersion(text);
  if (!version) throw new Error(`"${text}" is not an x.y.z or x.y.z-rc.N version.`);
  return version;
}

/** The release candidate number of `version`, `undefined` for a release. */
export function rcOf(version: string): number | undefined {
  return mustParse(version)[3];
}

/** The release a candidate leads to: `1.0.0-rc.2` → `1.0.0`; a release stays as it is. */
export function releaseOf(version: string): string {
  const [major, minor, patch] = mustParse(version);
  return `${major}.${minor}.${patch}`;
}

/** The release candidate `rc` of the release `version`: `withRc('1.0.0', 2)` is `1.0.0-rc.2`. */
export function withRc(version: string, rc: number): string {
  if (rcOf(version) !== undefined) throw new Error(`${version} is a release candidate already.`);
  if (!Number.isInteger(rc) || rc < 1) throw new Error(`${rc} is not a release candidate number.`);
  return `${version}-rc.${rc}`;
}

/** Negative when `a` is lower than `b`, positive when higher, 0 when equal. A candidate is lower than its release and higher than the candidates before it. */
export function compareVersions(a: string, b: string): number {
  const [left, right] = [mustParse(a), mustParse(b)];
  return left[0] - right[0] || left[1] - right[1] || left[2] - right[2] || (left[3] ?? Infinity) - (right[3] ?? Infinity) || 0;
}

export type Bump = 'major' | 'minor' | 'patch';

/** The bump the labels of the merged pull requests ask for: below 1.0 a breaking change is a minor, from 1.0 on a major. */
export function bumpFor(current: string, labels: { breaking: boolean; feature: boolean }): Bump {
  if (mustParse(current)[0] === 0) return labels.breaking ? 'minor' : 'patch';
  return labels.breaking ? 'major' : labels.feature ? 'minor' : 'patch';
}

/** The release `bump` above the release `current`; a candidate has none (it leads to {@link releaseOf}). */
export function bumpVersion(current: string, bump: Bump): string {
  const [major, minor, patch, rc] = mustParse(current);
  if (rc !== undefined) throw new Error(`${current} is a release candidate: it has no next version, its release is ${releaseOf(current)}.`);
  if (bump === 'major') return `${major + 1}.0.0`;
  if (bump === 'minor') return `${major}.${minor + 1}.0`;
  return `${major}.${minor}.${patch + 1}`;
}

/**
 * Whether `version` is the first of a breaking line: `0.y.0` (y >= 2; 0.1.0 was the first release) or `x.0.0` (x >= 1). A release
 * candidate is none: the upgrade guide belongs to its release.
 */
export function isBreakingRelease(version: string): boolean {
  const [major, minor, patch, rc] = mustParse(version);
  if (patch !== 0 || rc !== undefined) return false;
  return major === 0 ? minor >= 2 : minor === 0;
}

/** The line a version belongs to: `0.<minor>` below 1.0, `<major>` from 1.0 on (`0.1.4` → `0.1`, `2.3.0` → `2`). */
export function lineOf(version: string): string {
  const [major, minor] = mustParse(version);
  return major === 0 ? `0.${minor}` : `${major}`;
}

export const MAIN = 'main';

/** The line a maintenance branch releases: its name is a line plus `.x` (`0.1.x` → `0.1`, `2.x` → `2`); anything else is none. */
export function maintenanceLine(branch: string): string | undefined {
  const match = /^(?:(0\.(?:0|[1-9]\d*))|([1-9]\d*))\.x$/.exec(branch);
  return match?.[1] ?? match?.[2];
}

/** Whether `from` is a release of the line right below the breaking release `version` (what an upgrade guide section covers). */
export function upgradesFrom(version: string, from: string): boolean {
  if (!isBreakingRelease(version) || !parseVersion(from)) return false;
  const [major, minor] = mustParse(version);
  if (major === 0) return lineOf(from) === `0.${minor - 1}`;
  if (major === 1) return mustParse(from)[0] === 0;
  return lineOf(from) === `${major - 1}`;
}

/** The versions an upgrade guide to the breaking release `version` starts from, for messages: `0.1.x`, `0.x`, `1.x`. */
export function fromLine(version: string): string {
  if (!isBreakingRelease(version)) throw new Error(`${version} is not a breaking release.`);
  const [major, minor] = mustParse(version);
  if (major === 0) return `0.${minor - 1}.x`;
  return major === 1 ? '0.x' : `${major - 1}.x`;
}

export type ReleaseTarget = { ok: true; distTag: string; markLatest: boolean } | { ok: false; problem: string };

/**
 * The one place that picks the npm dist-tag and whether the draft GitHub Release is marked latest, from the branch the workflow
 * was started on, the version and npm's current `latest` (`undefined`: never published). No npm access: the guard supplies the facts.
 * A release candidate is refused here: it would need a prerelease dist-tag, never `latest`.
 */
export function releaseTarget({ branch, version, latest }: { branch: string; version: string; latest: string | undefined }): ReleaseTarget {
  const refuse = (problem: string): ReleaseTarget => ({ ok: false, problem });
  if (!isPlainVersion(version)) return refuse(`"${version}" is not a plain x.y.z version (branch ${branch}); prereleases are not released.`);
  const line = lineOf(version);
  const branchLine = maintenanceLine(branch);
  if (branch !== MAIN && branchLine === undefined) {
    return refuse(`Branch ${branch} cannot release ${version}: start the workflow from main or from a maintenance branch such as ${line}.x.`);
  }
  if (branchLine !== undefined && branchLine !== line) {
    return refuse(`${branch} releases ${branchLine} versions only; ${version} belongs to ${line}.x.`);
  }
  if (latest === undefined) {
    // npm's not-found also answers "no permission", so a wrong registry or login must not turn a backport into `latest`; a
    // maintenance line only exists after a newer release.
    if (branch !== MAIN) return refuse(`npm has no latest for ${branch} to sit below: a maintenance release needs a newer release on main first; check the registry and login.`);
    return { ok: true, distTag: 'latest', markLatest: true };
  }
  if (!isPlainVersion(latest)) return refuse(`npm's latest "${latest}" is not a plain x.y.z version (branch ${branch}, version ${version}).`);
  const order = compareVersions(version, latest);
  if (order === 0) return refuse(`${version} is already published as latest (branch ${branch}).`);
  if (order > 0) return { ok: true, distTag: 'latest', markLatest: true };
  if (branch === MAIN) {
    return refuse(`main releases above latest ${latest}; ${version} is below it, so a fix for ${line} goes out from ${line}.x.`);
  }
  return { ok: true, distTag: `latest-${line}`, markLatest: false };
}

/** Runs a command in a fixed directory (no shell); shared by the guard and the preparation so both can be tested with a fake. */
export type Runner = (command: string, args: readonly string[]) => { status: number | null; stdout: string; stderr: string };

export function spawnRunner(cwd: string): Runner {
  return (command, args) => {
    const result = spawnSync(command, args, { cwd, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
    return { status: result.status, stdout: result.stdout ?? '', stderr: result.stderr ?? '' };
  };
}

/**
 * Where the release preparation records what it prepared from: one line, `<version> <commit>` — the head of the branch whose merged
 * pull requests the notes cover. The release commit's first parent must be that commit, or a pull request merged since is in the
 * release but in no notes.
 */
export const RELEASE_BASE = '.github/release-base';

export function formatReleaseBase(version: string, commit: string): string {
  return `${version} ${commit}\n`;
}

/** `undefined` when the text is not what `formatReleaseBase` makes. */
export function parseReleaseBase(text: string): { version: string; commit: string } | undefined {
  const match = /^(\S+) ([0-9a-f]{40}(?:[0-9a-f]{24})?)\n$/.exec(text);
  return match && parseVersion(match[1]!) ? { version: match[1]!, commit: match[2]! } : undefined;
}

/**
 * What only the release preparation writes: the changelogs (`:(glob)`: in a plain pathspec `*` also matches `/`, so a nested
 * `CHANGELOG.md`, a template's, would count as a release) and the release base.
 */
export const RELEASE_PATHSPECS = [':(glob)packages/*/CHANGELOG.md', RELEASE_BASE] as const;

/**
 * Whether a release pull request may change `path`: the versions, changelogs, upgrade guide and release base the preparation writes,
 * and the file that lists the guide's anchors (`check-release.ts`). Code belongs in
 * its own pull request, merged before the preparation, so the release commit holds nothing the notes do not cover.
 */
export function isReleaseFile(path: string): boolean {
  return (
    /^packages\/[^/]+\/(?:package\.json|CHANGELOG\.md)$/.test(path) ||
    path === 'UPGRADING.md' ||
    path === RELEASE_BASE ||
    path === 'scripts/check-release.ts'
  );
}

/**
 * The commit a release ships: the last first-parent commit that changed a changelog or the release base. Only the release preparation writes them,
 * so a pull request merged after the release belongs to the next release, however soon the workflow is started.
 */
export function releaseCommit(run: Runner): string {
  const result = run('git', ['log', '-1', '--first-parent', '--format=%H', '--', ...RELEASE_PATHSPECS]);
  const commit = result.stdout.trim();
  if (result.status !== 0 || commit === '') {
    throw new Error(`No release commit: no commit on this branch changed ${RELEASE_PATHSPECS.join(' or ')}.${result.stderr ? ` ${result.stderr.trim()}` : ''}`);
  }
  return commit;
}

export interface Changelog {
  /** Everything before the first `## ` heading. */
  readonly title: string;
  /** In file order; `body` is the raw text after the heading line, up to the next heading. */
  readonly sections: readonly { version: string; ending: string; body: string }[];
}

/**
 * Splits a changelog at its `## ` headings, each of which must be `## x.y.z` or `## x.y.z-rc.N`. Code fences are not recognised: a `## ` line inside
 * one throws.
 */
export function parseChangelog(text: string): Changelog {
  const lines = text.split(/(?<=\n)/);
  let title = '';
  const sections: { version: string; ending: string; body: string }[] = [];
  for (const [index, line] of lines.entries()) {
    if (line.startsWith('## ')) {
      const ending = /\r?\n$/.exec(line)?.[0] ?? '';
      const version = line.slice(3, line.length - ending.length);
      if (!parseVersion(version)) throw new Error(`CHANGELOG line ${index + 1}: ${JSON.stringify(line.slice(0, line.length - ending.length))} is not "## x.y.z" or "## x.y.z-rc.N".`);
      sections.push({ version, ending, body: '' });
    } else if (sections.length === 0) title += line;
    else sections[sections.length - 1]!.body += line;
  }
  return { title, sections };
}

/** The text of a parsed changelog; `formatChangelog(parseChangelog(text)) === text`. */
export function formatChangelog(changelog: Changelog): string {
  return changelog.title + changelog.sections.map((section) => `## ${section.version}${section.ending}${section.body}`).join('');
}

/** The trimmed body of `## <version>` — the same in every published package's changelog; throws naming the packages that differ. */
export function releaseSection(repository: string, version: string): string {
  const bodies = frameworkPackages(repository).map((pkg) => {
    const file = join(pkg.dir, 'CHANGELOG.md');
    const section = existsSync(file) ? parseChangelog(readFileSync(file, 'utf8')).sections.find((candidate) => candidate.version === version) : undefined;
    return { name: pkg.name, body: section?.body.trim() };
  });
  const missing = bodies.filter((entry) => entry.body === undefined).map((entry) => entry.name);
  if (missing.length > 0) throw new Error(`No "## ${version}" section in the CHANGELOG of ${missing.join(', ')}.`);
  const reference = bodies.find((entry) => entry.name === '@marmeon/core') ?? bodies[0];
  if (!reference) throw new Error('No published package found.');
  const differing = bodies.filter((entry) => entry.body !== reference.body).map((entry) => entry.name);
  if (differing.length > 0) throw new Error(`The "## ${version}" section of ${differing.join(', ')} differs from ${reference.name}'s.`);
  return reference.body!;
}

if (import.meta.main) {
  if (process.argv.includes('--check')) {
    if (!releaseConfigCurrent()) {
      console.error(`release-rules: ${RELEASE_CONFIG} is missing or out of date — run node scripts/release-rules.ts.`);
      process.exitCode = 1;
    } else console.log(`release-rules: ${RELEASE_CONFIG} is current.`);
  } else {
    writeFileSync(join(root, RELEASE_CONFIG), releaseConfig());
    console.log(`release-rules: wrote ${RELEASE_CONFIG}.`);
  }
}
