/**
 * `node scripts/npm-trust.ts` — writes `scripts/npm-trust.sh`: the `npm trust github` call for every published package, which a
 * maintainer runs ONCE after the first manual publish (a package must exist on npm before it can trust a workflow). Nobody
 * runs it from CI.
 *
 *   node scripts/npm-trust.ts            # write scripts/npm-trust.sh
 *   node scripts/npm-trust.ts --check    # exit 1 when the file is not what the package list makes (check-release runs this)
 *
 * Each package trusts `.github/workflows/release.yml` of `marmeon/marmeon` for **staged** publishing only
 * (`--allow-stage-publish`, never `--allow-publish`) and only from the `npm-release` environment (`--environment`): the workflow can stage
 * a version, a maintainer approves it with 2FA. npm keeps one configuration per package, so an older one without the environment is
 * revoked first (`npm trust list`, `npm trust revoke --id`) — CONTRIBUTING.md › Releasing.
 */
import { readFileSync, writeFileSync, chmodSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { frameworkPackages } from './packages.ts';

const root = fileURLToPath(new URL('..', import.meta.url));
export const TRUST_SCRIPT = 'scripts/npm-trust.sh';
export const REPOSITORY = 'marmeon/marmeon';
export const WORKFLOW = 'release.yml';
/** The environment of the staging job: npm accepts the OIDC token only from a run that entered it (its branch policy is `main` and `*.x`). */
export const ENVIRONMENT = 'npm-release';

/** The script's text for the packages of `repository`. */
export function trustScript(repository: string = root): string {
  const names = frameworkPackages(repository).map((pkg) => pkg.name);
  return [
    '#!/usr/bin/env bash',
    '# Generated by `node scripts/npm-trust.ts` — do not edit. Run it ONCE, by hand, after the first publish (npm needs the packages',
    `# to exist): every package trusts the release workflow, run in the environment ${ENVIRONMENT}, for STAGED publishing only — a staged version goes live when a`,
    '# maintainer approves it with 2FA on npmjs.com. Needs npm >= 11.15 and an `npm login` with 2FA. The first call asks',
    '# for the one-time password; tick "skip two-factor authentication for the next 5 minutes" there, and the rest runs through.',
    '# npm keeps one trust configuration per package: under `set -e` this stops at the first package that still has an old one, so',
    '# revoke the old ones first (`npm trust list <package>`, `npm trust revoke --id <id> <package>`).',
    'set -euo pipefail',
    '',
    `packages=(\n${names.map((name) => `  ${name}`).join('\n')}\n)`,
    '',
    'for package in "${packages[@]}"; do',
    `  npm trust github "$package" --repository ${REPOSITORY} --file ${WORKFLOW} --environment ${ENVIRONMENT} --allow-stage-publish --yes`,
    '  sleep 2 # npm asks for a pause between calls (rate limit)',
    'done',
    '',
    `echo "Trusted ${WORKFLOW} of ${REPOSITORY} (staged publishing) for \${#packages[@]} packages. Check one: npm trust list ${names[0]}"`,
    '',
  ].join('\n');
}

/** Whether `scripts/npm-trust.sh` is what the package list makes. */
export function trustScriptCurrent(repository: string = root): boolean {
  const file = join(repository, TRUST_SCRIPT);
  return existsSync(file) && readFileSync(file, 'utf8') === trustScript(repository);
}

if (import.meta.main) {
  if (process.argv.includes('--check')) {
    if (!trustScriptCurrent()) {
      console.error(`npm-trust: ${TRUST_SCRIPT} is missing or out of date — run node scripts/npm-trust.ts.`);
      process.exitCode = 1;
    } else console.log(`npm-trust: ${TRUST_SCRIPT} names every package.`);
  } else {
    const file = join(root, TRUST_SCRIPT);
    writeFileSync(file, trustScript());
    chmodSync(file, 0o755);
    console.log(`npm-trust: wrote ${TRUST_SCRIPT} (run it once, by hand, after the first publish).`);
  }
}
