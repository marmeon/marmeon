/**
 * The format of `packages/<name>/api.md` — what `pnpm api:check` compares and what a pull request's diff shows. Only `node:*`
 * (and nothing from the repository's dependencies): a workflow may load this file without installing anything.
 *
 * One file per package: the header, then a section per entry point (its types from other packages, then the `Stable`,
 * `Referenced, not exported`, `Augments`, `Experimental` and `Experimental, referenced (not exported)` declarations), then the package's `Environment`, `Commands` and `Experimental` (the experimental variables and commands; the `##` heading tells it
 * from the `###` one of an entry point).
 * Every section is one `ts` block; each item starts with a `// <name>` line in column 0, followed by its declaration without
 * comments. Items are sorted by name, so the file does not depend on the order of the source.
 */

export type ApiSection = 'stable' | 'referenced' | 'augments' | 'experimental' | 'experimentalReferenced' | 'environment' | 'commands';

export interface ApiItem {
  /** The import specifier of the entry point (`@marmeon/http/page`); empty for the package-wide sections `environment`, `commands` and `experimental`. */
  readonly entry: string;
  readonly section: ApiSection;
  readonly name: string;
  /** The declaration as emitted, without comments. */
  readonly text: string;
}

export interface ApiChanges {
  readonly removed: ApiItem[];
  readonly changed: { before: ApiItem; after: ApiItem }[];
  readonly added: ApiItem[];
}

export const SNAPSHOT_HEADER = '<!-- Generated by pnpm api:update from the built declarations. Do not edit. -->';

/** The headings of the sections of an entry point, in the order they are written. */
const ENTRY_SECTIONS: readonly [ApiSection, string][] = [
  ['stable', 'Stable'],
  ['referenced', 'Referenced, not exported'],
  ['augments', 'Augments'],
  ['experimental', 'Experimental'],
  ['experimentalReferenced', 'Experimental, referenced (not exported)'],
];
/** The package-wide sections: a `##` heading of their own, after the entry points. */
const PACKAGE_SECTIONS: readonly [ApiSection, string][] = [
  ['environment', 'Environment'],
  ['commands', 'Commands'],
  ['experimental', 'Experimental'],
];

const FOREIGN_PREFIX = 'Types from other packages: ';
/** The lines in column 0 that start with `// ` but belong to an item's text, not to a new item. */
const MARKER_LINES = new Set(['@deprecated', 'type-only']);

const byName = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);

/** The markdown of a package's `api.md`. `foreign` maps each entry point to the packages whose types its declarations name. */
export function renderSnapshot(pkg: string, items: readonly ApiItem[], foreign: ReadonlyMap<string, readonly string[]>): string {
  const entries = new Set<string>(foreign.keys());
  for (const item of items) if (item.entry !== '') entries.add(item.entry);

  const lines: string[] = [SNAPSHOT_HEADER, '', `# ${pkg}`];
  for (const entry of [...entries].sort(byName)) {
    lines.push('', `## \`${entry}\``, '');
    const packages = [...(foreign.get(entry) ?? [])].sort(byName);
    lines.push(packages.length === 0 ? `${FOREIGN_PREFIX}none` : `${FOREIGN_PREFIX}${packages.map((name) => `\`${name}\``).join(', ')}`);
    for (const [section, heading] of ENTRY_SECTIONS) {
      const block = items.filter((item) => item.entry === entry && item.section === section);
      if (block.length > 0) lines.push('', `### ${heading}`, '', ...renderBlock(block));
    }
  }
  for (const [section, heading] of PACKAGE_SECTIONS) {
    const block = items.filter((item) => item.section === section && item.entry === '');
    if (block.length > 0) lines.push('', `## ${heading}`, '', ...renderBlock(block));
  }
  return `${lines.join('\n')}\n`;
}

function renderBlock(block: readonly ApiItem[]): string[] {
  const out = ['```ts'];
  for (const item of [...block].sort((a, b) => byName(a.name, b.name))) out.push(`// ${item.name}`, ...item.text.split('\n'));
  out.push('```');
  return out;
}

/** The items of a snapshot — the inverse of `renderSnapshot` (the packages named in "Types from other packages" are not items). */
export function parseSnapshot(markdown: string): ApiItem[] {
  const items: ApiItem[] = [];
  let entry = '';
  let section: ApiSection | undefined;
  let block: string[] | undefined;

  for (const line of markdown.split('\n')) {
    if (block !== undefined) {
      if (line === '```') {
        if (section !== undefined) items.push(...parseBlock(entry, section, block));
        block = undefined;
      } else {
        block.push(line);
      }
      continue;
    }
    const entryHeading = /^## `(.+)`$/.exec(line);
    const heading = /^(#{2,3}) (.+)$/.exec(line);
    if (entryHeading) {
      entry = entryHeading[1]!;
      section = undefined;
    } else if (heading) {
      const table = heading[1] === '###' ? ENTRY_SECTIONS : PACKAGE_SECTIONS;
      section = table.find(([, title]) => title === heading[2])?.[0];
      if (heading[1] === '##') entry = '';
    } else if (line === '```ts') {
      block = [];
    }
  }
  return items;
}

function parseBlock(entry: string, section: ApiSection, lines: readonly string[]): ApiItem[] {
  const items: ApiItem[] = [];
  let current: { name: string; text: string[] } | undefined;
  const finish = () => {
    if (current) items.push({ entry, section, name: current.name, text: current.text.join('\n') });
  };
  for (const line of lines) {
    const header = /^\/\/ (.+)$/.exec(line);
    if (header && !MARKER_LINES.has(header[1]!)) {
      finish();
      current = { name: header[1]!, text: [] };
    } else {
      current?.text.push(line);
    }
  }
  finish();
  return items;
}

const keyOf = (item: ApiItem) => `${item.entry}\0${item.section}\0${item.name}`;
const byKey = (items: readonly ApiItem[]) => new Map(items.map((item) => [keyOf(item), item]));

/**
 * What differs between two snapshots. An item is the same item when entry point, section and name agree — a name that moves
 * from `Referenced` to `Stable` is added, not changed, and its old entry is not a removal.
 */
export function compareSnapshots(before: readonly ApiItem[], after: readonly ApiItem[]): ApiChanges {
  const was = byKey(before);
  const is = byKey(after);
  const stableNow = new Set(after.filter((item) => item.section === 'stable').map((item) => `${item.entry}\0${item.name}`));

  const removed = before.filter(
    (item) => !is.has(keyOf(item)) && !(item.section === 'referenced' && stableNow.has(`${item.entry}\0${item.name}`)),
  );
  const added = after.filter((item) => !was.has(keyOf(item)));
  const changed: ApiChanges['changed'] = [];
  for (const item of after) {
    const earlier = was.get(keyOf(item));
    if (earlier && earlier.text !== item.text) changed.push({ before: earlier, after: item });
  }
  const order = (a: ApiItem, b: ApiItem) => byName(a.entry, b.entry) || byName(a.name, b.name);
  return {
    removed: removed.sort(order),
    changed: changed.sort((a, b) => order(a.after, b.after)),
    added: added.sort(order),
  };
}
