import { Connections } from '@marmeon/database';
import { err } from '@marmeon/core';
import { SocialAccounts } from '@marmeon/oauth/accounts';
import { fakeOAuth } from '@marmeon/oauth/testing';
import { createTestApp, type TestApp } from '@marmeon/testing';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import application from '../../bootstrap/app.ts';
import { UserFactory } from '#modules/auth';
import type { ShowConfirmButtonsController } from './controllers/ShowConfirmButtonsController.ts';
import type { ShowConnectedAccountsController } from './controllers/ShowConnectedAccountsController.ts';

// Generated by `marmeon make:oauth` — confirming with a linked provider account instead of a password, with the provider side answered by
// `fakeOAuth()`. Microsoft is the built-in provider that can prove a fresh sign-in. Runs on SQLite and Postgres.

let app: TestApp;
const boot = async () => {
  app = await createTestApp(application, { database: 'refresh' });
};
afterEach(() => app.close());

type Browser = ReturnType<TestApp['keepingCookies']>;

const db = () => app.make(Connections).get<any>();
const rows = () => db().selectFrom('social_accounts').select(['user_id', 'provider']).orderBy('id').execute();
const toast = (kind: 'success' | 'error', message: string) => ({ kind, message });

/**
 * A person whose only way in is a Microsoft account: linked while they still had a password (a link is made by a signed-in person), then
 * the password goes. Returns the person and the id the provider knows them by.
 */
async function microsoftOnly() {
  const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
  const browser = app.keepingCookies();
  await browser.post('/login', { form: { email: ada.email, password: 'password' } }).assertRedirect('/dashboard');
  const oauth = fakeOAuth(app).user('microsoft', { id: 'ms-ada', email: 'ada@example.com' });
  await browser.get(oauth.callbackUrl(await browser.post('/oauth/accounts/microsoft').assertStatus(303))).assertRedirect('/dashboard');
  await db().updateTable('users').set({ password: null }).where('id', '=', ada.id).execute();
  return ada;
}
/** A sign-in at Microsoft, as a person without a password does it. */
async function signInAtMicrosoft(): Promise<Browser> {
  const browser = app.keepingCookies();
  const oauth = fakeOAuth(app).user('microsoft', { id: 'ms-ada', email: 'ada@example.com' });
  await browser.get(oauth.callbackUrl(await browser.post('/auth/microsoft/redirect').assertStatus(303))).assertRedirect('/dashboard').assertAuthenticated();
  return browser;
}
/** What the panel reports: whether the confirmation window is open, and whether the account has a password. */
async function panel(browser: Browser) {
  let seen: { confirmed: boolean; hasPassword: boolean } | undefined;
  await browser.islanding().get('/oauth/accounts').assertIsland<ShowConnectedAccountsController>('oauth/ConnectedAccounts', (props) => {
    seen = { confirmed: props.confirmed, hasPassword: props.hasPassword };
  });
  return seen!;
}
const confirmed = async (browser: Browser) => (await panel(browser)).confirmed;
/** What `SocialAccounts.confirm()` answers, scripted: for the refusals that only the guard or the clock produce. */
const scripted = (kind: string) => app.container.instance(SocialAccounts, { confirm: async () => err({ kind }) } as never);
const FAILED = toast('error', 'That did not work. Try again.');
/** The start of a confirmation: a POST, answered with the provider's authorization page. */
const startConfirm = (browser: Browser, provider = 'microsoft') => browser.post(`/oauth/confirm/${provider}`).assertStatus(303);

describe('confirming with a provider', { timeout: 60_000 }, () => {
  // Every test boots the app on a refreshed database — seconds on a busy machine, so its hook and tests get 30 s.
  beforeEach(() => boot(), 30_000);

  it('an account with only a Microsoft login confirms with Microsoft, then links GitHub and unlinks it', async () => {
    await microsoftOnly();
    const browser = await signInAtMicrosoft();
    expect(await panel(browser)).toEqual({ confirmed: false, hasPassword: false });
    // Without the window neither a link nor a removal goes through, and the account has no password to type.
    app.travel({ minutes: 16 });
    const oauthGithub = fakeOAuth(app).user('github', { id: '42', email: 'ada@example.com', emailVerified: true });
    (await browser.get(oauthGithub.callbackUrl(await browser.post('/oauth/accounts/github').assertStatus(303)))).assertFlashed('toast', toast('error', 'Confirm it is you first, then connect the account again.'));
    expect(await rows()).toHaveLength(1);

    // The panel offers Microsoft; the round trip opens the window, and the page the guard sent the person from is where they land.
    const oauth = fakeOAuth(app).user('microsoft', { id: 'ms-ada', email: 'ada@example.com' }).reauthenticated('microsoft');
    const back = await browser.get(oauth.callbackUrl(await startConfirm(browser)));
    back.assertRedirect('/dashboard').assertFlashed('toast', toast('success', 'Confirmed.'));
    expect(await confirmed(browser)).toBe(true);

    const github = fakeOAuth(app).user('github', { id: '42', email: 'ada@example.com', emailVerified: true });
    (await browser.get(github.callbackUrl(await browser.post('/oauth/accounts/github').assertStatus(303)))).assertRedirect('/dashboard').assertFlashed('toast', toast('success', 'The account is connected.'));
    expect((await rows()).map((row: { provider: string }) => row.provider)).toEqual(['microsoft', 'github']);
    (await browser.post('/oauth/accounts/github/remove')).assertRedirect('/dashboard').assertFlashed('toast', toast('success', 'The account is removed.'));
    expect((await rows()).map((row: { provider: string }) => row.provider)).toEqual(['microsoft']);
    // Microsoft is the last way in now: it stays.
    (await browser.post('/oauth/accounts/microsoft/remove')).assertRedirect('/dashboard').assertFlashed('toast', toast('error', 'That is the only way you can sign in. Set a password or add another way first.'));
    expect(await rows()).toHaveLength(1);
  });

  it('a confirmation returns to the page that asked for it', async () => {
    await microsoftOnly();
    const browser = await signInAtMicrosoft();
    app.travel({ minutes: 16 });
    // The security page wants a recent confirmation and sends the person to the confirmation page, remembering where they were going.
    await browser.get('/settings/security', { headers: { accept: 'text/html' } }).then((response) => response.assertRedirect('/confirm-password'));
    const oauth = fakeOAuth(app).user('microsoft', { id: 'ms-ada', email: 'ada@example.com' }).reauthenticated('microsoft');
    (await browser.get(oauth.callbackUrl(await startConfirm(browser)))).assertRedirect('/settings/security');
  });

  it('a confirmation without auth_time leaves the window closed', async () => {
    await microsoftOnly();
    const browser = await signInAtMicrosoft();
    app.travel({ minutes: 16 });
    // The provider answers without `auth_time`: no proof of a fresh sign-in.
    const oauth = fakeOAuth(app).user('microsoft', { id: 'ms-ada', email: 'ada@example.com' });
    const back = await browser.get(oauth.callbackUrl(await startConfirm(browser)));
    back.assertRedirect('/dashboard').assertFlashed('toast', FAILED);
    expect(await confirmed(browser)).toBe(false);
  });

  it('a confirmation with an old auth_time leaves the window closed', async () => {
    await microsoftOnly();
    const browser = await signInAtMicrosoft();
    app.travel({ minutes: 16 });
    // The person signed in at the provider an hour ago: the fresh sign-in the redirect asked for did not happen.
    const oauth = fakeOAuth(app).user('microsoft', { id: 'ms-ada', email: 'ada@example.com' }).staleAuthentication('microsoft', 3600);
    const back = await browser.get(oauth.callbackUrl(await startConfirm(browser)));
    back.assertRedirect('/dashboard').assertFlashed('toast', FAILED);
    expect(await confirmed(browser)).toBe(false);
  });

  it('a confirmation through a provider account that is not linked to this user leaves the window closed', async () => {
    await microsoftOnly();
    const browser = await signInAtMicrosoft();
    app.travel({ minutes: 16 });
    // The person signs in at Microsoft as somebody else: the account that answers is not the one linked.
    const oauth = fakeOAuth(app).user('microsoft', { id: 'ms-other', email: 'other@example.com' }).reauthenticated('microsoft');
    const back = await browser.get(oauth.callbackUrl(await startConfirm(browser)));
    back.assertRedirect('/dashboard').assertFlashed('toast', FAILED);
    expect(await confirmed(browser)).toBe(false);
    // A Microsoft account linked to another user opens nothing either.
    const bob = await app.factory(UserFactory).create({ email: 'bob@example.com' });
    const now = new Date().toISOString();
    await db().insertInto('social_accounts').values({ user_id: bob.id, provider: 'microsoft', provider_id: 'ms-other', created_at: now, updated_at: now }).execute();
    const again = fakeOAuth(app).user('microsoft', { id: 'ms-other', email: 'other@example.com' }).reauthenticated('microsoft');
    (await browser.get(again.callbackUrl(await startConfirm(browser)))).assertRedirect('/dashboard').assertFlashed('toast', FAILED);
    expect(await confirmed(browser)).toBe(false);
  });

  it('a reused callback URL leaves the window closed', async () => {
    await microsoftOnly();
    const browser = await signInAtMicrosoft();
    app.travel({ minutes: 16 });
    const oauth = fakeOAuth(app).user('microsoft', { id: 'ms-ada', email: 'ada@example.com' }).reauthenticated('microsoft');
    const url = oauth.callbackUrl(await startConfirm(browser));
    (await browser.get(url)).assertRedirect('/dashboard');
    expect(await confirmed(browser)).toBe(true);
    // The window lapses; the same address comes back (a page restored from history): the flow is spent, nothing opens it again.
    app.travel({ minutes: 16 });
    (await browser.get(url)).assertRedirect('/dashboard').assertFlashed('toast', FAILED);
    expect(await confirmed(browser)).toBe(false);
  });

  it('a confirmation whose account was unlinked meanwhile is refused, and the window stays closed', async () => {
    await microsoftOnly();
    const browser = await signInAtMicrosoft();
    app.travel({ minutes: 16 });
    const oauth = fakeOAuth(app).user('microsoft', { id: 'ms-ada', email: 'ada@example.com' }).reauthenticated('microsoft');
    const opened = await startConfirm(browser);
    // The provider's answer is fine; the account it vouches for is not linked to this user any more.
    await db().deleteFrom('social_accounts').execute();
    (await browser.get(oauth.callbackUrl(opened))).assertRedirect('/dashboard').assertFlashed('toast', toast('error', 'That is not an account connected to you. Confirm with one that is, or another way.'));
    expect(await confirmed(browser)).toBe(false);
  });

  // The two refusals below depend on a race or the clock inside `SocialAccounts.confirm()`: its answer is scripted, the way back is what is under test.
  it.each([
    ['not-reauthenticated', 'The provider did not confirm a fresh sign-in. Try again, or confirm another way.'],
    ['expired', 'The confirmation could not be used. Try again, or confirm another way.'],
  ])('a confirmation refused as %s leaves the window closed and says why', async (kind, message) => {
    await microsoftOnly();
    const browser = await signInAtMicrosoft();
    app.travel({ minutes: 16 });
    const url = fakeOAuth(app).user('microsoft', { id: 'ms-ada', email: 'ada@example.com' }).reauthenticated('microsoft').callbackUrl(await startConfirm(browser));
    scripted(kind);
    (await browser.get(url)).assertRedirect('/dashboard').assertFlashed('toast', toast('error', message));
  });

  it('sends a person whose session ended inside the confirmation to the sign-in page', async () => {
    await microsoftOnly();
    const browser = await signInAtMicrosoft();
    app.travel({ minutes: 16 });
    const url = fakeOAuth(app).user('microsoft', { id: 'ms-ada', email: 'ada@example.com' }).reauthenticated('microsoft').callbackUrl(await startConfirm(browser));
    scripted('signed-out');
    (await browser.get(url)).assertRedirect('/login').assertFlashed('toast', toast('error', 'You were signed out meanwhile. Sign in and try again.'));
  });

  it('GitHub offers no confirmation', async () => {
    const ada = await app.factory(UserFactory).create();
    const now = new Date().toISOString();
    await db().insertInto('social_accounts').values({ user_id: ada.id, provider: 'github', provider_id: '42', created_at: now, updated_at: now }).execute();
    fakeOAuth(app);
    const browser = app.keepingCookies();
    await browser.post('/login', { form: { email: ada.email, password: 'password' } }).assertRedirect('/dashboard');
    // Back to the page with a message, and never to the provider.
    const start = await browser.post('/oauth/confirm/github');
    start.assertRedirect('/dashboard').assertFlashed('toast', toast('error', 'This provider cannot confirm that it is you. Confirm another way.'));
    // A provider the person has not linked is no start either, however capable it is.
    const other = await browser.post('/oauth/confirm/microsoft');
    other.assertRedirect('/dashboard').assertFlashed('toast', toast('error', 'That is not an account connected to you. Confirm with one that is, or another way.'));
  });

  it('says so when the provider cannot be reached to start a confirmation', async () => {
    await microsoftOnly();
    const browser = await signInAtMicrosoft();
    fakeOAuth(app);
    app.http.failNext('network');
    (await browser.post('/oauth/confirm/microsoft')).assertRedirect('/dashboard').assertFlashed('toast', toast('error', 'That provider cannot be reached right now. Try again in a moment, or confirm another way.'));
    expect(await confirmed(browser)).toBe(false);
  });

  it('the confirm-options island lists confirmable providers only', async () => {
    const ada = await app.factory(UserFactory).create();
    const now = new Date().toISOString();
    for (const [provider, id] of [['github', '42'], ['google', 'g-1'], ['microsoft', 'tenant|m-1']] as const) {
      await db().insertInto('social_accounts').values({ user_id: ada.id, provider, provider_id: id, created_at: now, updated_at: now }).execute();
    }
    fakeOAuth(app, { only: ['github', 'google', 'microsoft'] });
    await app
      .actingAs(ada)
      .islanding()
      .get('/oauth/confirm')
      .assertIsland<ShowConfirmButtonsController>('oauth/ConfirmButtons', (props) => {
        expect(props.providers).toEqual([{ name: 'microsoft', label: 'Microsoft' }]);
      });
    // An island of a signed-in person: a guest gets no island.
    const guest = await app.islanding().get('/oauth/confirm');
    expect(guest.island()).toBeUndefined();
  });

  it('limits the starts of one user to ten a minute', async () => {
    const ada = await app.factory(UserFactory).create();
    const bob = await app.factory(UserFactory).create();
    fakeOAuth(app);
    const statuses: number[] = [];
    for (let i = 0; i < 11; i++) statuses.push((await app.withIp('203.0.113.80').actingAs(ada).post('/oauth/confirm/github')).status);
    // Each is answered with a refusal (the provider is not linked) until the eleventh.
    expect(statuses.slice(0, 10)).toEqual(Array(10).fill(303));
    expect(statuses[10]).toBe(429);
    expect((await app.withIp('203.0.113.80').actingAs(bob).post('/oauth/confirm/github')).status).toBe(303);
  });
});
