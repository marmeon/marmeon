/**
 * The app's page components — generated by `marmeon route:types` from the pages glob into `bootstrap/routes.ts`,
 * merged in by declaration (`'user-profile/Show': true`). `view(name, …)` and `assertPage(name)` check names
 * against it; until something is generated, any string is a view name.
 */
export interface Views {}

/** A page component name: `user-profile/Show` for `modules/user-profile/views/Show.tsx`. */
export type ViewName = [keyof Views] extends [never] ? string : keyof Views & string;

/** `V` when it is a view; otherwise a message naming the file that is missing. */
export type CheckViewName<V extends string> = string extends V
  ? ViewName
  : V extends ViewName
    ? V
    : V extends `${infer Module}/${infer Rest}`
      ? `'${V}' is not a view: there is no modules/${Module}/views/${Rest}.tsx${Suggest<V, ViewName, '/'>}`
      : `'${V}' is not a view — view names are '<module>/<Page>' (modules/<module>/views/<Page>.tsx)`;

/** The routes the browser knows — `routes` of `virtual:marmeon/routes` (the `marmeon()` Vite plugin). */
export type RouteManifest = Readonly<Record<string, { readonly method: string; readonly path: string; readonly view?: string }>>;

/**
 * Props every page receives next to its controller's own — the signed-in user, flash messages, validation errors. Declared
 * with `declare module '@marmeon/http/page'` by whoever shares them; `PageProps<Controller>` includes them, and the server fills
 * them in (`SharedData`). See docs/responses.md#shared-props.
 */
export interface SharedProps {}

/**
 * The app's flash messages — what a controller hands the next page to show once, declared by the app with
 * `declare module '@marmeon/http/page'`. Until the app declares any, every key is allowed and its data is `unknown`.
 * See docs/responses.md#flash-data-and-flash-messages.
 */
export interface FlashData {}

/** A flash key of the app (any string while `FlashData` declares none). */
export type FlashKey = [keyof FlashData] extends [never] ? string : keyof FlashData & string;

/** What flash key `K` carries — as the server flashes it. */
export type FlashValue<K extends string> = K extends keyof FlashData ? FlashData[K] : unknown;

/** `K` when it is a flash key of the app — otherwise a message naming the keys `FlashData` declares. */
export type CheckFlashKey<K extends string> = string extends K
  ? FlashKey
  : K extends FlashKey
    ? K
    : `'${K}' is not a flash key — the app declares ${JoinNames<FlashKey>} (interface FlashData of @marmeon/http/page)`;

/**
 * One flash message as the browser gets it: its key, its data (as JSON made it, `Serialize`), and an id of its own —
 * so it fires exactly once: never again for a partial reload, Back/Forward or a page shown from memory, and twice for the
 * same message flashed twice (two saves, two toasts).
 */
export type FlashMessage<K extends FlashKey = FlashKey> = K extends unknown ? { readonly id: string; readonly key: K; readonly data: Serialize<FlashValue<K>> } : never;

/**
 * What a page knows about itself — the app's view of the page object, as `usePage()` returns it: the protocol fields of the
 * wire format stay with the adapter. See docs/pages.md#reading-the-page.
 */
export interface PageInfo<TProps = ViewProps> {
  /** The view's name: `user-profile/Show`. */
  readonly component: string;
  /** The controller's props and the shared ones. */
  readonly props: TProps;
  /** The page's URL, path and query. */
  readonly url: string;
  /** The name of the route that answered — absent for an error page and for a route the browser does not know. */
  readonly route?: string;
  /** The page's language, one of the app's supported locales. */
  readonly locale?: string;
  /** The page's parsed query — absent for a route without a query schema. */
  readonly query?: Readonly<Record<string, unknown>>;
  /** The flash messages this page delivered. */
  readonly flash?: readonly FlashMessage[];
}

/** What a view's placeholder gets (instant visits): what its controller declares (`declare readonly instant: { name: string }`). */
export type InstantProps<C> = C extends { readonly instant: infer P } ? (P extends object ? P : never) : never;

/** The token of an upload (`tu_<id>.<signature>`): what an upload field sends — and what a test gets from `app.upload(…)`. */
export type UploadToken = string & { readonly '~uploadToken': true };

/**
 * A file uploaded ahead — the value of a form field with an `upload()` rule, made by `<FileInput>` (or `upload(…)`): its
 * state and progress, a preview, and `cancel()`. It goes to the server as its token (`toJSON`), which only the client core
 * holds — in memory, emptied when the document is left (signed out, a new build); never kept by remember or in history.state.
 */
export interface Upload {
  readonly '~upload': true;
  /** The file's name as the browser has it — for showing; the server stores the file under a name of its own. */
  readonly name: string;
  readonly size: number;
  /** The type the browser claims (`image/png`) — the server goes by the file's bytes. */
  readonly type: string;
  /** `uploading`, `uploaded` (the token is ready), `failed` (see `error`). */
  readonly status: 'uploading' | 'uploaded' | 'failed';
  readonly uploading: boolean;
  /** How far: 0 … 1. */
  readonly progress: number;
  /** A `blob:` URL of the chosen file (images), for a preview — revoked when the upload is replaced, cancelled or the field unmounts. */
  readonly preview: string | undefined;
  /** Why it failed — a message for the user (the server's, or a network error). */
  readonly error: string | undefined;
  /** Stops the upload (or forgets the uploaded file): the field goes back to empty. */
  cancel(): void;
  /** The token when uploaded — else an empty string (the server says "choose it again"). */
  toJSON(): string;
}

/** The fields of form data `F` an `upload()` rule takes (their input is an {@link Upload}). */
export type UploadField<F> = keyof { [K in keyof F & string as [Extract<F[K], Upload>] extends [never] ? never : K]: true } & string;

/** `K` when it is an upload field of form data `F`; otherwise the message the compiler shows as the expected type. */
export type CheckUploadField<F, K extends string> = string extends K
  ? UploadField<F>
  : string extends keyof F
    ? K // an untyped form (no generated routes yet): any field
    : K extends UploadField<F>
    ? K
    : [UploadField<F>] extends [never]
      ? `'${K}' is no upload field — this form has none (give a field upload({ maxBytes, mime }) in its request schema)`
      : `'${K}' is no upload field of this form — its upload fields: ${JoinNames<UploadField<F>>}`;

/** What a password field's name looks like to live validation (`/password/i`): it is never sent for a check. */
type PasswordLike<K extends string> = Lowercase<K> extends `${string}password${string}` ? true : false;

/** The fields of form data `F` that live validation may check: every top-level field but passwords. */
export type LiveField<F> = keyof { [K in keyof F & string as PasswordLike<K> extends true ? never : K]: true } & string;

/** The explanation when a password field is named for a live validation — shown by the compiler as the expected type. */
export type PasswordNeverLive = 'password fields are never validated live — they are checked when the form is sent';

/**
 * `K` when live validation may check it in form data `F`; otherwise the message the compiler shows: a password field, or a
 * field the form does not have (with the ones it has).
 */
export type CheckLiveField<F, K extends string> = K extends LiveField<F>
  ? K
  : K extends keyof F
    ? `'${K}' — ${PasswordNeverLive}`
    : `'${K}' is not a field of this form — it has ${JoinNames<LiveField<F>>}`;

/**
 * What the server resolved of an island while rendering the page — streamed into the document inside the island's
 * Suspense boundary, so the browser shows it without a request. The outcomes are a region request's: its region
 * object, or `unauthorized`/`forbidden` (no data), or `exception`. `browser`: not resolved on the server — the browser
 * loads it as on a client-side visit (a `409` of the island route: the document is out of date, the browser's request
 * reloads the page).
 */
export type RegionResult =
  | { readonly status: 'ready'; readonly region: RegionObject }
  | { readonly status: 'unauthorized' | 'forbidden' }
  | { readonly status: 'exception'; readonly failure: { readonly status?: number; readonly message?: string } }
  | { readonly status: 'browser' };

/** A deferred group as the server streams it: its props, and how they merge — what a partial reload would answer. */
export type DeferredResult = Pick<PageObject, 'props' | 'mergeProps' | 'deepMergeProps' | 'matchPropsOn'>;

/** What an SSR entry renders of a page. */
export interface SsrResult {
  /**
   * The page's markup: a string, or a stream of it (streaming SSR — the shell first, Suspense boundaries as they
   * finish). Empty: the server renders no markup for this page (`Page.ssr = false`), the browser renders it.
   */
  html: string | ReadableStream<Uint8Array>;
  /** Tags for the document head (`<Head>` in the shell): the title and meta tags. */
  head?: string;
  /** The deferred groups this render streams (`resolveDeferred`) — the server lists them in the page object (`streamedProps`). */
  streamedProps?: string[];
}

export interface SsrRenderOptions {
  /**
   * Resolve only once the whole page has rendered, every Suspense boundary included — for bots, which read the HTML
   * without running scripts. Otherwise the shell is enough to start sending.
   */
  complete?: boolean;
  /**
   * An error after the shell, while the response is already on its way: the Suspense boundary it happened in is
   * rendered by the browser instead. Errors in the shell reject the render (the server sends the page without markup).
   */
  onError?: (error: unknown) => void;
  /** Hints for the developer, development only — e.g. a `<Head>` that rendered after the document head was sent. */
  onWarning?: (message: string) => void;
  /** Stops rendering, e.g. when the client went away. */
  signal?: AbortSignal;
  /**
   * Per request: resolves an island in-process while the page renders — `url` is its route's (with its query), run
   * through that route's own middleware and authorization, read-only, with the page request's session and cookies. The
   * adapter renders it behind a Suspense boundary and streams it with its data; the shell never waits for it. Without
   * it, islands load in the browser.
   */
  resolveIsland?: (url: string) => Promise<RegionResult>;
  /**
   * Per request: computes a deferred group of the page while it streams — read-only, once the response's headers
   * are sent. `null`: not streamed (it failed or took too long) — the browser loads it as before. Without it, the
   * browser loads every group after showing the page.
   */
  resolveDeferred?: (group: string) => Promise<DeferredResult | null>;
  /**
   * The response's CSP nonce, when the app sends a policy: the adapter puts it on everything inline it streams —
   * React's scripts that reveal Suspense boundaries, its `<style>` tags — and on the `<Head>`'s scripts and styles.
   */
  nonce?: string;
}

/**
 * Contract of an app's SSR entry (`export const render: SsrRender`). It receives the page as the browser does — JSON
 * values only (`Serialize<T>`: a Date is its ISO string), so the markup hydrates. Rejects when the page cannot render
 * on the server at all; the server then sends it without markup and the browser renders it.
 */
export type SsrRender = (page: PageObject, options?: SsrRenderOptions) => Promise<SsrResult>;

/**
 * Where a paginated list stands — what `paginate()` in @marmeon/database returns as `meta`, and what
 * `<Pagination>` renders. (Declared here too, so browser code never imports the database package.)
 */
export interface PaginationMeta {
  readonly page: number;
  readonly perPage: number;
  readonly total: number;
  readonly lastPage: number;
  readonly from: number | null;
  readonly to: number | null;
}
