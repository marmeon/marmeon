/**
 * The app's page components — generated by `bespoke route:types` from the pages glob into `bootstrap/routes.ts`,
 * merged in by declaration (`'user-profile/Show': true`). `view(name, …)` and `assertPage(name)` check names
 * against it; until something is generated, any string is a view name.
 */
export interface Views {}

/** A page component name: `user-profile/Show` for `modules/user-profile/views/Show.tsx`. */
export type ViewName = [keyof Views] extends [never] ? string : keyof Views & string;

/** `V` when it is a view; otherwise a message naming the file that is missing. */
export type CheckViewName<V extends string> = string extends V
  ? ViewName
  : V extends ViewName
    ? V
    : V extends `${infer Module}/${infer Rest}`
      ? `'${V}' is not a view: there is no modules/${Module}/views/${Rest}.tsx${Suggest<V, ViewName, '/'>}`
      : `'${V}' is not a view — view names are '<module>/<Page>' (modules/<module>/views/<Page>.tsx)`;

/** The routes the browser knows — `routes` of `virtual:bespoke/routes` (the `bespoke()` Vite plugin). */
export type RouteManifest = Readonly<Record<string, { readonly method: string; readonly path: string }>>;

/** `modules/user-profile/views/Show.tsx` → `user-profile/Show` (the page naming convention), or undefined. */
export function pageName(path: string): string | undefined {
  const match = /(?:^|\/)modules\/([^/]+)\/views\/(.+)\.[jt]sx$/.exec(path.replaceAll('\\', '/'));
  return match ? `${match[1]}/${match[2]}` : undefined;
}

/**
 * Props every page receives, next to its controller's own — the signed-in user,
 * flash messages, validation errors. Declared by whoever shares them:
 *
 * ```ts
 * declare module '@bespokecore/http/page' {
 *   interface SharedProps { auth: { user: { id: string; name: string } | null } }
 * }
 * ```
 *
 * `PageProps<Controller>` includes them, and the server fills them in (`SharedData`).
 */
export interface SharedProps {}

/**
 * The app's flash messages (E60) — what a controller hands the next page to show once: a toast, a notice. Declared by the
 * app, checked where it flashes (`redirect().flash('toast', { kind: 'success', message })`) and where it shows them
 * (`useFlash('toast', (toast) => …)`):
 *
 * ```ts
 * declare module '@bespokecore/http/page' {
 *   interface FlashData { toast: { kind: 'success' | 'error' | 'info'; message: string } }
 * }
 * ```
 *
 * Until the app declares any, every key is allowed and its data is `unknown`.
 */
export interface FlashData {}

/** A flash key of the app (any string while `FlashData` declares none). */
export type FlashKey = [keyof FlashData] extends [never] ? string : keyof FlashData & string;

/** What flash key `K` carries — as the server flashes it. */
export type FlashValue<K extends string> = K extends keyof FlashData ? FlashData[K] : unknown;

/** `K` when it is a flash key of the app — otherwise a message naming the keys `FlashData` declares. */
export type CheckFlashKey<K extends string> = string extends K
  ? FlashKey
  : K extends FlashKey
    ? K
    : `'${K}' is not a flash key — the app declares ${JoinNames<FlashKey>} (interface FlashData of @bespokecore/http/page)`;

/**
 * One flash message as the browser gets it (E60): its key, its data (as JSON made it, `Serialize`), and an id of its own —
 * so it fires exactly once: never again for a partial reload, Back/Forward or a page shown from memory, and twice for the
 * same message flashed twice (two saves, two toasts).
 */
export type FlashMessage<K extends FlashKey = FlashKey> = K extends unknown ? { readonly id: string; readonly key: K; readonly data: Serialize<FlashValue<K>> } : never;

/**
 * With an action's answer (E59, E60): the flash messages it delivers — JSON, URI-encoded (header values are ASCII). An action
 * is shown to the user (`useAction`), so it takes the messages its controller flashed instead of leaving them for later.
 */
export const FLASH_HEADER = 'x-bespoke-flash';

/**
 * With a prefetch's answer (E60): flash messages wait for the page the user is shown — the prefetch took none. The client does
 * not show that prefetched page then: the visit asks the server, whose answer delivers them (the toast is not lost).
 */
export const FLASH_WAITING_HEADER = 'x-bespoke-flash-waiting';

/** The wire format of a page — shared by the server and every UI adapter. */
export interface PageObject {
  component: string;
  props: ViewProps;
  url: string;
  /** Build version of the assets (null in development). A client with another version reloads fully. */
  version?: string | null;
  /**
   * The language of the page (the request's locale, from @bespokecore/i18n) — one of the app's supported locales.
   * The browser loads only this locale's messages (`virtual:bespoke/lang`), never the messages themselves from here.
   */
  locale?: string;
  /**
   * Where messages missing in `locale` come from (`APP_FALLBACK_LOCALE`) — sent with `locale`, so the browser's language
   * files fall back the way the server's do, configured once.
   */
  fallbackLocale?: string;
  /**
   * Props the response left out to load next (`defer()`), by group: the client fetches each group with a partial
   * reload right after showing the page. Only in full responses.
   */
  deferredProps?: Record<string, string[]>;
  /** Props a partial reload merges into the client's (`merge()`): arrays appended, objects merged one level deep. */
  mergeProps?: string[];
  /** Props a partial reload merges all the way down (`deepMerge()`). */
  deepMergeProps?: string[];
  /**
   * Where merged arrays identify their items (`matchOn()`): `<prop>.<key>` or `<prop>.<path>.<key>` — an item with a
   * key already shown replaces it instead of appearing twice.
   */
  matchPropsOn?: string[];
  /**
   * The page's query, parsed by its request's `query` schema (E55) — only the fields the URL set validly, without
   * defaults (the canonical query). The browser never parses a URL itself: `useQueryState` reads this. Absent for a
   * route without a query schema.
   */
  query?: Record<string, unknown>;
  /** What an empty query parses to (the schema's defaults) — left out of the URLs the browser builds for this page. */
  queryDefaults?: Record<string, unknown>;
  /**
   * Deferred groups the server streams with this document (E49) — computed while the page streams and sent in it, so the
   * browser does not ask for them again. Only on a server-rendered document's page object.
   */
  streamedProps?: string[];
  /**
   * The page object is a layer's (E53): the view of a route whose controller answered `this.view(…).layer({ base })` — shown
   * over the page (or the layers) on screen, with a history entry of its own. Absent for pages.
   */
  layer?: LayerInfo;
  /**
   * The layers over this page, bottom first — only on a server-rendered document's page object, for a deep link (or a reload)
   * of a layer's URL: this page is the layer's declared base (resolved in-process), or the neutral surface ({@link LAYER_BACKDROP})
   * when the base turned the user away (E54). Never in a client-side navigation's answer.
   */
  layers?: PageObject[];
  /**
   * The flash messages this response delivers (E60) — a protocol field, not a prop: sent once, only with an answer that is
   * shown (a page, a layer, a partial reload — never a prefetch or an island), and no answer sends them again. The client
   * core fires each once (`navigator.on('flash')`, `useFlash`) and keeps none of them: not in memory with the page, never in
   * `history.state`. On the server, an adapter may render them for browsers without JavaScript (`<noscript>`).
   */
  flash?: FlashMessage[];
  /**
   * The name of the route that answered (E64) — what `<Link activeMatch="user-profile.*">` compares against. Only for a named
   * route the browser may know (never an `.internal()` one), and only on its own answer (an error page names none).
   */
  route?: string;
}

/** What a layer's page object says about it (E53). */
export interface LayerInfo {
  /**
   * Its identity in a stack: an answer of the layer with the same key replaces it in place (a form that failed validation,
   * the next step of a wizard) — another key stacks on top. Default: the view's name.
   */
  readonly key: string;
  /** The URL of its declared base — the page a deep link or a reload shows under it. */
  readonly base: string;
  /**
   * The answer of an action (a POST, …), not of a GET: shown once — when it leaves the screen it is gone from memory (its URL
   * asked again with GET is something else), and what is beneath it is reloaded (the action changed it). A new API token's
   * plain text, say.
   */
  readonly once?: true;
}

/** How deep layers stack (E53): an answer that would open an eleventh is shown as a page instead. */
export const MAX_LAYER_DEPTH = 10;

/**
 * The neutral surface under a layer whose base the user may not see (E54) — a deep link to the layer renders it alone over
 * this page, and the base's data is never loaded. Apps override it with `modules/layers/views/Backdrop.tsx`.
 */
export const LAYER_BACKDROP = 'layers/Backdrop';

/**
 * The answer of `closeLayer()` to a layer's request (E53): JSON {@link LayerClose} — the client closes that many layers and
 * reloads what is beneath them. (Without a layer — no JavaScript — the same result is a redirect.)
 */
export const LAYER_CLOSE_HEADER = 'x-bespoke-layer-close';

/** What the server tells a layer's client to do instead of showing a page: close. */
export interface LayerClose {
  /** How many layers close, from the one that asked down (default 1). */
  readonly layers: number;
  /** Then reload what is beneath them — the page and the layers that stay: some props (a partial reload of each), or `true` all. */
  readonly reload?: readonly string[] | true;
}

/** Client-side navigations send this header and receive the page object as JSON. */
export const PAGE_HEADER = 'x-bespoke';

/**
 * Sent with an action (E59, `useAction`): a request that does not navigate — answered with data (`this.json(…)`), never with
 * a page. Its redirect is not followed: the server answers `204` with {@link ACTION_REDIRECT_HEADER} instead. Its answer
 * is never cached (`Cache-Control: no-store`): it is about who asked, at that moment.
 */
export const ACTION_HEADER = 'x-bespoke-action';

/** With an action's `204`: where its controller redirected to — the client says so (`{ kind: 'redirect' }`), it does not go there. */
export const ACTION_REDIRECT_HEADER = 'x-bespoke-redirect';

/** Whether `request` is an action's (`x-bespoke-action`, E59). */
export function isActionRequest(request: Request): boolean {
  return request.headers.get(ACTION_HEADER) === 'true';
}

/** The asset version the client was built with; a mismatch answers 409 (Inertia's `X-Inertia-Version`). */
export const VERSION_HEADER = 'x-bespoke-version';

/**
 * With a 409: where the client loads fully (Inertia's `X-Inertia-Location`) — after a deployment (asset version)
 * and after signing in or out (`ClientHistory`), so no page kept in memory outlives either.
 */
export const LOCATION_HEADER = 'x-bespoke-location';

/**
 * A partial reload (E7, Inertia's `X-Inertia-Partial-Component`): the component the client shows. The server
 * answers with only some props when it renders this component — and with all of them for any other.
 */
export const PARTIAL_COMPONENT_HEADER = 'x-bespoke-partial-component';

/** With a partial reload: the props to send, comma-separated (`only`). `always()` props come anyway. */
export const PARTIAL_DATA_HEADER = 'x-bespoke-partial-data';

/** With a partial reload: the props to leave out, comma-separated (`except`). */
export const PARTIAL_EXCEPT_HEADER = 'x-bespoke-partial-except';

/**
 * Sent with a prefetch (`<Link prefetch>`, `router.prefetch()`) — `Purpose: prefetch`, as browsers do for their own
 * prefetches (`Sec-Purpose`, which scripts may not set). The user has not asked for the page yet: a GET that does
 * something besides showing (marks notifications read, remembers where a guest wanted to go) skips that for a
 * prefetch — see {@link isPrefetch}.
 */
export const PURPOSE_HEADER = 'purpose';

/**
 * Whether `request` is a prefetch — ours (`Purpose: prefetch`) or the browser's (`Sec-Purpose: prefetch`). Answer it
 * like the real request, minus side effects: the client shows the prefetched page when the link is clicked (within
 * its `cacheFor`), without asking again. A page whose visit must do something should not be prefetched.
 */
export function isPrefetch(request: Request): boolean {
  const purpose = `${request.headers.get(PURPOSE_HEADER) ?? ''},${request.headers.get('sec-purpose') ?? ''}`;
  return /(^|[\s,;])prefetch($|[\s,;])/i.test(purpose);
}

/**
 * Sent with the request of a region — `island` for an `<Island route>` (E48–E52): the server answers with the island's
 * region object (a page object of the island route, without the page's locale), never with a page. A request without it
 * never gets an island: a direct hit is a 404, and so is a page's prefetch or visit of the island's URL. Answered with it
 * too, on the island's own JSON (so a cache can tell the two apart: `Vary`).
 */
export const REGION_HEADER = 'x-bespoke-region';

/**
 * The kinds of region a request may ask for: `island` — an `<Island route>`; `layer` — a layer's request (opening it, or a visit
 * or a form inside it, E53): a layer route answers with its page object (`layer`), a page route with its page as usual.
 */
export type RegionKind = 'island' | 'layer';

/**
 * How a region request ended when it brought no region object — the server answers `204` with this header instead of
 * following a redirect, a 401 or a 403 of the island route (E52: they become the island's fallback, never a navigation
 * of the page). Failures (4xx, 5xx) keep their status and say `exception`.
 */
export const REGION_STATUS_HEADER = 'x-bespoke-region-status';

/** What a region request can end in besides its region object (see {@link REGION_STATUS_HEADER}). */
export type RegionOutcomeStatus = 'unauthorized' | 'forbidden' | 'exception';

/** The region `request` asks for (`x-bespoke-region`, with `x-bespoke`), or undefined for any other request. */
export function regionOf(request: Request): RegionKind | undefined {
  const { headers } = request;
  if (headers.get(PAGE_HEADER) !== 'true') return undefined;
  const region = headers.get(REGION_HEADER);
  return region === 'island' || region === 'layer' ? region : undefined;
}

/**
 * The wire format of a region (an island): the page object of the route it shows — its component, props, URL and query,
 * deferred and merged props — without the page's language (`locale`, `fallbackLocale`): it renders in the page's.
 */
export type RegionObject = Omit<PageObject, 'locale' | 'fallbackLocale' | 'streamedProps' | 'layer' | 'layers' | 'flash'>;

/**
 * What the server resolved of an island while rendering the page (E49) — streamed into the document inside the island's
 * Suspense boundary, so the browser shows it without a request. The outcomes are a region request's (E52): its region
 * object, or `unauthorized`/`forbidden` (no data), or `exception`. `browser`: not resolved on the server — the browser
 * loads it as on a client-side visit (a `409` of the island route: the document is out of date, the browser's request
 * reloads the page).
 */
export type RegionResult =
  | { readonly status: 'ready'; readonly region: RegionObject }
  | { readonly status: 'unauthorized' | 'forbidden' }
  | { readonly status: 'exception'; readonly failure: { readonly status?: number; readonly message?: string } }
  | { readonly status: 'browser' };

/** A deferred group as the server streams it (E49): its props, and how they merge — what a partial reload would answer. */
export type DeferredResult = Pick<PageObject, 'props' | 'mergeProps' | 'deepMergeProps' | 'matchPropsOn'>;

/** Id of the `<script type="application/json">` that carries the initial page. */
export const PAGE_SCRIPT_ID = 'bespoke-page';

/**
 * JSON for a `<script type="application/json">` in HTML: `<` is escaped (`<`), so a value can never close the script
 * element early (`</script>`) or open a comment — the page object, islands and deferred props streamed into the document.
 */
export function scriptJson(value: unknown): string {
  return JSON.stringify(value).replaceAll('<', '\\u003c');
}

/** What an SSR entry renders of a page. */
export interface SsrResult {
  /**
   * The page's markup: a string, or a stream of it (streaming SSR — the shell first, Suspense boundaries as they
   * finish). Empty: the server renders no markup for this page (`Page.ssr = false`), the browser renders it.
   */
  html: string | ReadableStream<Uint8Array>;
  /** Tags for the document head (`<Head>` in the shell): the title and meta tags. */
  head?: string;
  /** The deferred groups this render streams (`resolveDeferred`) — the server lists them in the page object (`streamedProps`). */
  streamedProps?: string[];
}

export interface SsrRenderOptions {
  /**
   * Resolve only once the whole page has rendered, every Suspense boundary included — for bots, which read the HTML
   * without running scripts. Otherwise the shell is enough to start sending.
   */
  complete?: boolean;
  /**
   * An error after the shell, while the response is already on its way: the Suspense boundary it happened in is
   * rendered by the browser instead. Errors in the shell reject the render (the server sends the page without markup).
   */
  onError?: (error: unknown) => void;
  /** Hints for the developer, development only — e.g. a `<Head>` that rendered after the document head was sent. */
  onWarning?: (message: string) => void;
  /** Stops rendering, e.g. when the client went away. */
  signal?: AbortSignal;
  /**
   * Per request (E49): resolves an island in-process while the page renders — `url` is its route's (with its query), run
   * through that route's own middleware and authorization, read-only, with the page request's session and cookies. The
   * adapter renders it behind a Suspense boundary and streams it with its data; the shell never waits for it. Without
   * it, islands load in the browser.
   */
  resolveIsland?: (url: string) => Promise<RegionResult>;
  /**
   * Per request (E49): computes a deferred group of the page while it streams — read-only, once the response's headers
   * are sent. `null`: not streamed (it failed or took too long) — the browser loads it as before. Without it, the
   * browser loads every group after showing the page.
   */
  resolveDeferred?: (group: string) => Promise<DeferredResult | null>;
}

/**
 * Contract of an app's SSR entry (`export const render: SsrRender`). It receives the page as the browser does — JSON
 * values only (`Serialize<T>`: a Date is its ISO string), so the markup hydrates. Rejects when the page cannot render
 * on the server at all; the server then sends it without markup and the browser renders it.
 */
export type SsrRender = (page: PageObject, options?: SsrRenderOptions) => Promise<SsrResult>;

export function isPageObject(value: unknown): value is PageObject {
  return typeof value === 'object' && value !== null && 'component' in value && 'props' in value && 'url' in value;
}

