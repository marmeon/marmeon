import { existsSync, globSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { pathToFileURL } from 'node:url';
import { Application } from '@marmeon/core';
import { browserRoutes, type BrowserRoutes } from '@marmeon/http';
import { BROWSER_ROUTES_FILE, ERROR_PAGE, matchesRoutePatterns, pageName, writeBrowserRoutes } from '@marmeon/http/internal';
import { Router, type RouteDefinition } from '@marmeon/router';
import { isControllerClass } from '@marmeon/router/internal';

/** Where the generated routes and views live, relative to the app root. Committed, like `bootstrap/database.d.ts`. */
export const ROUTES_FILE = 'bootstrap/routes.ts';

/** The page components — the default of `marmeon({ pages })` in @marmeon/vite and of `resolveModulePages`. */
export const PAGES_GLOB = 'modules/*/views/**/*.tsx';

interface Located {
  readonly file: string;
  readonly exportName: string;
}

/**
 * Generates `bootstrap/routes.ts` from the booted app: `interface Routes` for the type checker — every
 * named route with its method, path and controller class — and the page components as `interface Views`. Types
 * only: the routes the browser may learn go to `.marmeon/routes.json` (not committed), from which the `marmeon()`
 * Vite plugin builds `virtual:marmeon/routes` with just the names client code writes out. So the committed
 * file depends on routes and views alone (`--check`), and no importable table of every route sits in the repo.
 * Both are written only when something changed, so watchers stay calm.
 */
export class RouteTypes {
  readonly #app: Application;
  readonly #router: Router;

  constructor(app: Application, router: Router) {
    this.#app = app;
    this.#router = router;
  }

  get path(): string {
    return join(this.#app.root, ROUTES_FILE);
  }

  async render(): Promise<{ source: string; warnings: string[] }> {
    const warnings: string[] = [];
    const named = this.#router.routes.filter((route): route is RouteDefinition & { routeName: string } => route.routeName !== undefined);
    named.sort((a, b) => (a.routeName < b.routeName ? -1 : 1));

    const controllers = await this.#locateControllers(named);
    const imports = new Map<Function, string>();
    const aliases = new Set<string>();
    const importLines: string[] = [];
    for (const route of named) {
      const action = route.action;
      if (!isControllerClass(action) || imports.has(action)) continue;
      const located = controllers.get(action);
      if (!located) {
        warnings.push(`Route [${route.routeName}]: ${action.name || 'its controller'} is not exported by any file of the app — useForm('${route.routeName}', …) has no fields.`);
        continue;
      }
      let alias = located.exportName === 'default' ? action.name || 'Controller' : located.exportName;
      for (let n = 2; aliases.has(alias); n++) alias = `${located.exportName === 'default' ? action.name : located.exportName}${n}`;
      aliases.add(alias);
      imports.set(action, alias);
      const specifier = relativeImport(join(this.#app.root, 'bootstrap'), located.file);
      importLines.push(
        located.exportName === alias
          ? `import type { ${alias} } from ${quote(specifier)};`
          : `import type { ${located.exportName} as ${alias} } from ${quote(specifier)};`,
      );
    }
    importLines.sort((a, b) => (a < b ? -1 : 1));

    const clientRoutes = this.#app.definition.clientRoutes ?? {};
    const browser = this.browserRoutes();
    for (const [option, patterns] of [['include', clientRoutes.include ?? []], ['except', clientRoutes.except ?? []]] as const) {
      for (const pattern of patterns) {
        if (!named.some((route) => matchesRoutePatterns(route.routeName, [pattern]))) warnings.push(`clientRoutes.${option}: '${pattern}' matches no named route.`);
      }
    }

    const entries = named.map((route) => {
      const methods = [...new Set(route.methods.map((method) => method.toLowerCase()))];
      const controller = isControllerClass(route.action) ? imports.get(route.action) : undefined;
      const fields = [
        `method: ${methods.map(quote).join(' | ')}`,
        `path: ${quote(route.path)}`,
        ...(controller ? [`controller: typeof ${controller}`] : []),
        ...(Object.hasOwn(browser.routes, route.routeName) ? [] : ['browser: false']),
      ];
      return `    ${quote(route.routeName)}: { ${fields.join('; ')} };`;
    });

    const views = [...new Set([...this.#views(), ERROR_PAGE])].sort();

    const source = [
      '// Generated by `marmeon route:types` from the routes and views of the app — do not edit.',
      '// `marmeon dev` and `marmeon build` keep it current; CI checks it with `marmeon route:types --check`.',
      '',
      ...(importLines.length ? [...importLines, ''] : []),
      "declare module '@marmeon/router' {",
      ...(entries.length ? ['  interface Routes {', ...entries, '  }'] : ['  interface Routes {}']),
      '}',
      '',
      "declare module '@marmeon/http/page' {",
      '  interface Views {',
      ...views.map((view) => `    ${quote(view)}: true;`),
      '  }',
      '}',
      '',
    ].join('\n');
    return { source, warnings };
  }

  /** The routes the browser may learn and those it never does — the content of `.marmeon/routes.json`. */
  browserRoutes(): BrowserRoutes {
    return browserRoutes(this.#router.routes, this.#app.definition.clientRoutes);
  }

  /** Where `.marmeon/routes.json` lives. */
  get browserRoutesPath(): string {
    return join(this.#app.root, BROWSER_ROUTES_FILE);
  }

  /** Writes `bootstrap/routes.ts` and `.marmeon/routes.json`; `changed` says whether the committed file changed. */
  async write(): Promise<{ changed: boolean; warnings: string[] }> {
    const { source, warnings } = await this.render();
    const changed = !existsSync(this.path) || readFileSync(this.path, 'utf8') !== source;
    if (changed) {
      mkdirSync(dirname(this.path), { recursive: true });
      writeFileSync(this.path, source);
    }
    writeBrowserRoutes(this.#app.root, this.browserRoutes());
    return { changed, warnings };
  }

  /** Whether the committed file matches the app (`.marmeon/routes.json` is not committed: not compared). */
  async isCurrent(): Promise<boolean> {
    return existsSync(this.path) && readFileSync(this.path, 'utf8') === (await this.render()).source;
  }

  #views(): string[] {
    const files = globSync(PAGES_GLOB, { cwd: this.#app.root }).map((file) => ({ file: file.replaceAll('\\', '/'), name: pageName(file) }));
    // `::` separates a package from its page (`package::Page`): an app page must not take such a name.
    const reserved = files.filter(({ name }) => name?.includes('::')).map(({ file }) => file);
    if (reserved.length > 0) {
      throw new Error(reserved.map((file) => `${file}: "::" is reserved for the pages of packages (package::Page) — rename the file or its folder.`).join('\n'));
    }
    return files.map(({ name }) => name).filter((name): name is string => name !== undefined);
  }

  /**
   * Which file exports each controller class. The router only holds the class objects, so: find the app's files
   * that declare a class of that name, import them (already loaded — the routes imported them) and compare
   * identities. Two modules with a `ShowController` each are told apart.
   */
  async #locateControllers(routes: readonly RouteDefinition[]): Promise<Map<Function, Located>> {
    const wanted = new Map<string, Function[]>();
    for (const { action } of routes) {
      if (!isControllerClass(action) || !action.name) continue;
      const list = wanted.get(action.name) ?? [];
      if (!list.includes(action)) list.push(action);
      wanted.set(action.name, list);
    }
    const located = new Map<Function, Located>();
    if (wanted.size === 0) return located;

    const files = globSync('**/*.ts', { cwd: this.#app.root, exclude: (path: string) => IGNORED.test(path) })
      .filter((file) => !file.endsWith('.d.ts') && !file.endsWith('.test.ts'))
      .map((file) => join(this.#app.root, file));
    for (const file of files) {
      const text = readFileSync(file, 'utf8');
      const names = [...wanted.keys()].filter((name) => new RegExp(`\\bclass\\s+${name}\\b`).test(text) && /\bexport\b/.test(text));
      if (names.length === 0) continue;
      const exports = (await import(pathToFileURL(file).href)) as Record<string, unknown>;
      for (const [exportName, value] of Object.entries(exports)) {
        if (typeof value === 'function' && wanted.get(value.name)?.includes(value) && !located.has(value)) located.set(value, { file, exportName });
      }
    }
    return located;
  }
}

const IGNORED = /(^|[/\\])(node_modules|dist|\.marmeon|storage|\.git)$/;

function relativeImport(from: string, file: string): string {
  const path = relative(from, file).split(sep).join('/');
  return path.startsWith('.') ? path : `./${path}`;
}

function quote(text: string): string {
  return `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}
