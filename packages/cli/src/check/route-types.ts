import { relative, resolve } from 'node:path';
import { Application, Redactor, errorCodeOf } from '@marmeon/core';
import { withoutCode } from '@marmeon/core/internal';
import { Router } from '@marmeon/router';
import { describeMiddlewareProblem } from '@marmeon/router/internal';
import { RouteTypes } from '../route-types.ts';
import type { AppCheck } from './registry.ts';
import type { CheckProblem } from './report.ts';

/** `file` and `line` of a route's `site` (`modules/blog/routes.ts:12`), when it is inside the app. */
export function placeOf(site: string | undefined, root: string): { file?: string; line?: number } {
  const match = site === undefined ? null : /^(.*):(\d+)$/.exec(site);
  if (!match) return {};
  const file = relative(resolve(root), resolve(root, match[1]!)).split('\\').join('/');
  return file.startsWith('..') || file === '' ? {} : { file, line: Number(match[2]) };
}

/**
 * The generated route types are current and every route says who may call it. Reads routes and views only: the app is
 * registered, not booted. See docs/check.md#the-checks.
 */
export class RouteTypesCheck implements AppCheck {
  static check = 'route-types';
  static phase = 'build' as const;

  readonly #types: RouteTypes;
  readonly #router: Router;
  readonly #app: Application;

  constructor(types: RouteTypes, router: Router, app: Application) {
    this.#types = types;
    this.#router = router;
    this.#app = app;
  }

  async handle(): Promise<readonly CheckProblem[]> {
    const redactor = this.#app.container.has(Redactor) ? this.#app.container.make(Redactor) : new Redactor();
    const file = relative(this.#app.root, this.#types.path).split('\\').join('/');
    const problems: CheckProblem[] = [];
    const format = this.#types.fileFormat();
    if (format === undefined) {
      problems.push({ severity: 'error', message: `${file} does not exist`, file, fix: 'marmeon route:types' });
    } else if (format === 'newer') {
      problems.push({ severity: 'error', message: `${file} was generated by a newer version of Marmeon — update @marmeon/*`, file, code: 'H2' });
    } else if (format === 'other') {
      problems.push({ severity: 'error', message: `${file} was generated by another version of Marmeon`, file, code: 'H2', fix: 'marmeon route:types' });
    } else {
      try {
        if (!(await this.#types.isCurrent())) problems.push({ severity: 'error', message: `${file} is out of date`, file, fix: 'marmeon route:types' });
      } catch (error) {
        const code = errorCodeOf(error); // a refusal that has a code (an error page in its former place) shows it as the problem's code
        const text = redactor.text(error instanceof Error ? error.message : String(error)).split(resolve(this.#app.root)).join('.');
        problems.push({ severity: 'error', message: `${file} cannot be compared with the routes and views: ${code ? withoutCode(text) : text}`, file, ...(code && { code }) });
      }
    }
    for (const problem of this.#router.accessProblems()) problems.push(accessFinding(problem, redactor, this.#app.root));
    for (const problem of this.#router.middlewareProblems()) {
      const { route } = problem;
      problems.push({
        severity: 'error',
        message: describeMiddlewareProblem(problem, (r) => redactor.path(r.path, r.path)),
        ...placeOf(route.site, this.#app.root),
        code: 'H8',
        docs: 'docs/middleware.md#listed-twice',
      });
    }
    return problems;
  }
}

type AccessProblem = ReturnType<Router['accessProblems']>[number];

/** One route that does not say who may call it, or that lets everyone call it and binds a record by its key. */
function accessFinding(problem: AccessProblem, redactor: Redactor, root: string): CheckProblem {
  const { route } = problem;
  const which = `${route.methods.join('|')} ${redactor.path(route.path, route.path)}${route.routeName ? ` (${route.routeName})` : ''}`;
  const message =
    problem.kind === 'undecided'
      ? `${which} does not say who may call it — give it an authorize check, or Route.authorize(everyone)`
      : `${which} lets everyone call it and binds \`${problem.param}\` with ${problem.binder}, which finds any ${problem.param} by its key`;
  return { severity: 'error', message, ...placeOf(route.site, root), code: 'H3', docs: 'docs/authorization.md#every-route-decides' };
}
