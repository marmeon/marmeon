import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { tempDir } from '../../../../scripts/test/temp-dir.js';
import { MakeLintConfigCommand } from '../commands/make-lint-config.ts';
import { lintPresetDrift } from './lint-preset.ts';

function app(serverModules?: unknown, files: Record<string, string> = {}): string {
  const root = tempDir('marmeon-lint-preset-');
  const manifest = { name: 'fixture', private: true, type: 'module', ...(serverModules === undefined ? {} : { marmeon: { serverModules } }) };
  for (const [name, text] of Object.entries({ 'package.json': JSON.stringify(manifest), ...files })) {
    mkdirSync(dirname(join(root, name)), { recursive: true });
    writeFileSync(join(root, name), text);
  }
  return root;
}

function generate(root: string, options: Record<string, unknown> = {}): void {
  const output = { success: () => undefined, error: () => undefined, line: () => undefined };
  const code = new MakeLintConfigCommand().handle({ root, args: [], options, output, spawn: async () => 0 } as never);
  expect(code).toBe(0);
}

const declare = (root: string, serverModules: unknown) => writeFileSync(join(root, 'package.json'), JSON.stringify({ name: 'fixture', marmeon: { serverModules } }));

describe('lintPresetDrift', () => {
  it('is quiet for a preset written for the current declaration, and for none', () => {
    expect(lintPresetDrift(app())).toEqual([]);
    const root = app(['modules/billing/invoices/**']);
    generate(root);
    expect(lintPresetDrift(root)).toEqual([]);
  });

  it('warns when the declaration changed after the preset was written, naming the command', () => {
    const root = app(['modules/billing/invoices/**']);
    generate(root);
    declare(root, ['modules/billing/invoices/**', 'domain/**']);
    const [problem, ...rest] = lintPresetDrift(root);
    expect(rest).toEqual([]);
    expect(problem).toMatchObject({ severity: 'warning', file: '.oxlintrc.json', line: 1, rule: 'marmeon(lint-preset)', fix: 'marmeon make:lint-config --force', docs: 'docs/console.md#lint' });
    expect(problem!.message).toContain('Write it anew: marmeon make:lint-config --force — it replaces your own changes to the file.');
  });

  it('names --boundaries when the preset was written with it', () => {
    const root = app([]);
    generate(root, { boundaries: true });
    declare(root, ['domain/**']);
    expect(lintPresetDrift(root)[0]!.fix).toBe('marmeon make:lint-config --force --boundaries');
  });

  it('warns for a generated preset without the fingerprint line (every app that has one from an older version)', () => {
    const root = app(undefined, { '.oxlintrc.json': '// Generated by `marmeon make:lint-config` — yours to change; --force writes it anew.\n{}\n' });
    expect(lintPresetDrift(root)).toHaveLength(1);
    const boundaries = app(undefined, { '.oxlintrc.json': '// Generated by `marmeon make:lint-config --boundaries` — yours to change.\n{}\n' });
    expect(lintPresetDrift(boundaries)[0]!.fix).toBe('marmeon make:lint-config --force --boundaries');
  });

  it("leaves a preset the app wrote itself alone", () => {
    expect(lintPresetDrift(app(undefined, { '.oxlintrc.json': '{ "rules": {} }\n' }))).toEqual([]);
  });

  it('reports a broken declaration (H14) without a preset and with one of the app\'s own', () => {
    for (const files of [{} as Record<string, string>, { '.oxlintrc.json': '{ "rules": {} }\n' }]) {
      const [problem] = lintPresetDrift(app('modules/x/**', files));
      expect(problem).toMatchObject({ severity: 'error', code: 'H14', file: 'package.json' });
    }
  });

  it('is an error, not a skip, for a broken declaration (H14)', () => {
    const root = app('modules/x/**');
    writeFileSync(join(root, '.oxlintrc.json'), '// Generated by `marmeon make:lint-config` — yours to change.\n{}\n');
    const [problem] = lintPresetDrift(root);
    expect(problem).toMatchObject({ severity: 'error', file: 'package.json', code: 'H14', rule: 'marmeon(server-modules)', docs: 'docs/vite.md#server-folders-of-your-own' });
    expect(problem!.message).toContain('"serverModules" is not a list of globs');
  });
});
