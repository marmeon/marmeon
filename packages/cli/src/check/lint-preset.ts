import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { declaredServerModules } from '@marmeon/core/internal';
import { LINT_CONFIG_FILE, serverModulesFingerprint } from '../commands/make-lint-config.ts';
import type { CheckProblem } from './report.ts';

const GENERATED = '// Generated by `marmeon make:lint-config';
const FINGERPRINT = /^\/\/ marmeon:server-modules ([0-9a-f]{16}) /;

/**
 * Whether a lint preset that `make:lint-config` wrote was written for the server modules the app has now: the conventions of
 * `marmeon()` and the folders of package.json's `"marmeon"."serverModules"`. A preset the app wrote itself (no generated header),
 * or none, is the app's business (only the declaration is checked). A generated preset without the fingerprint line is older than it: it misses the newer
 * conventions, so it warns too. A broken declaration (H14) is an error whenever the lint runs, preset or not. See docs/check.md#the-checks.
 */
export function lintPresetDrift(root: string): CheckProblem[] {
  // First, whatever the preset is: a broken declaration is an error in every lint run, never skipped.
  let declared: readonly string[];
  try {
    declared = declaredServerModules(root);
  } catch (error) {
    return [{ severity: 'error', message: (error as Error).message.replace(/^\[marmeon:H14\] /, ''), file: 'package.json', code: 'H14', rule: 'marmeon(server-modules)', docs: 'docs/vite.md#server-folders-of-your-own' }];
  }
  let lines: string[];
  try {
    lines = readFileSync(join(root, LINT_CONFIG_FILE), 'utf8').split('\n');
  } catch {
    return [];
  }
  if (!lines[0]?.startsWith(GENERATED)) return [];
  const written = lines.slice(0, 20).map((line) => FINGERPRINT.exec(line)?.[1]).find((hash) => hash !== undefined);
  if (written === serverModulesFingerprint(declared)) return [];
  const command = `marmeon make:lint-config --force${lines[0].includes('--boundaries') ? ' --boundaries' : ''}`;
  return [
    {
      severity: 'warning',
      message: `The lint preset was written for another list of server modules than package.json declares now, so the editor misses value imports from the folders added since. The build still refuses them. Write it anew: ${command} — it replaces your own changes to the file.`,
      file: LINT_CONFIG_FILE,
      line: 1,
      rule: 'marmeon(lint-preset)',
      fix: command,
      docs: 'docs/console.md#lint',
    },
  ];
}
