import { softAuthenticator, twoFactorCode } from '@marmeon/auth';
import { Connections } from '@marmeon/database';
import { createTestApp, type TestApp } from '@marmeon/testing';
import { beforeEach, describe, expect, it, vi } from 'vitest';
import application from '../../bootstrap/app.ts';
import { ResetTwoFactorCommand } from './commands/ResetTwoFactorCommand.ts';
import { UserFactory } from './factories/UserFactory.ts';
import { NotifyAboutFailedPasskeySignIn } from './listeners/NotifyAboutFailedPasskeySignIn.ts';
import { TwoFactorMail } from './mail/TwoFactorMail.ts';
import { PasskeyMail } from './mail/PasskeyMail.ts';
import { ResetPasswordMail } from './mail/ResetPasswordMail.ts';
import { PasskeyNotices } from './passkey-notices.ts';
import type { User } from './users.ts';

// Generated by `marmeon make:auth` — passkeys: signing in with one alone, as the second step after the password, managing them, and the
// mails about them. A software authenticator stands in for the browser. Runs on SQLite and Postgres.

let app: TestApp;
// Every test boots the app on a refreshed database — seconds on a busy machine, so its hook and tests get 30 s.
beforeEach(async () => {
  app = await createTestApp(application, { database: 'refresh' });
}, 30_000);

const SESSION = 'marmeon_session';
// The tests' APP_URL is http://localhost: that is the relying party.
const device = () => softAuthenticator({ origin: 'http://localhost', rpId: 'localhost' });
const credentialsOf = (user: User) => ({ form: { email: user.email, password: 'password' } });
const json = { accept: 'application/json' };

/** A signed-in browser that adds `authenticator` as a passkey, as the settings page does. */
async function enrol(user: User, { authenticator = device(), name = 'Laptop' } = {}) {
  const login = await app.post('/login', credentialsOf(user)).assertRedirect('/dashboard');
  const cookie = login.cookie(SESSION)!;
  const options = await app.withCookie(SESSION, cookie).post('/settings/passkeys/options', { json: {} }).assertOk();
  const registered = await app
    .withCookie(SESSION, cookie)
    .post('/settings/passkeys', { json: { response: authenticator.register(options.json() as never), name, password: 'password' } })
    .assertOk();
  return { cookie, authenticator, recoveryCodes: (registered.json() as { recoveryCodes: string[] }).recoveryCodes };
}

/** A guest's passwordless sign-in: the options open the session's one challenge, the answer spends it. */
async function signInWith(authenticator: ReturnType<typeof device>, overrides: Parameters<ReturnType<typeof device>['authenticate']>[1] = {}) {
  const options = await app.post('/passkeys/sign-in/options', { json: {} }).assertOk();
  const guest = options.cookie(SESSION)!;
  return { guest, answer: app.withCookie(SESSION, guest).post('/passkeys/sign-in', { json: { response: authenticator.authenticate(options.json() as never, overrides) } }) };
}

const passkeyIdOf = async () => ((await app.make(Connections).get<any>().selectFrom('passkeys').select('id').execute()) as [{ id: number }])[0].id;

describe('passkeys', { timeout: 30_000 }, () => {
  it('adds a passkey, signs out, and signs in without a password', async () => {
    const ada = await app.factory(UserFactory).create();
    const { authenticator, recoveryCodes } = await enrol(ada);
    expect(recoveryCodes).toHaveLength(10);
    await app.assertDatabaseCount('passkeys', 1);

    const { guest, answer } = await signInWith(authenticator);
    const signedIn = await answer.assertRedirect('/dashboard');
    await app.withCookie(SESSION, signedIn.cookie(SESSION) ?? guest).get('/dashboard').assertAuthenticated(ada);
  });

  it('after the password, a passkey finishes the sign-in', async () => {
    const ada = await app.factory(UserFactory).create();
    const { authenticator } = await enrol(ada);
    const login = await app.post('/login', credentialsOf(ada)).assertRedirect('/two-factor-challenge').assertGuest();
    const cookie = login.cookie(SESSION)!;
    await app.withCookie(SESSION, cookie).navigating().get('/two-factor-challenge').assertPage('auth/TwoFactorChallenge', { passkey: true, totp: false });
    const options = await app.withCookie(SESSION, cookie).post('/two-factor-challenge/passkey/options', { json: {} }).assertOk();
    const done = await app
      .withCookie(SESSION, cookie)
      .post('/two-factor-challenge/passkey', { json: { response: authenticator.authenticate(options.json() as never) } })
      .assertRedirect('/dashboard');
    await app.withCookie(SESSION, done.cookie(SESSION) ?? cookie).get('/dashboard').assertAuthenticated(ada);
  });

  it('refuses a response from another origin, and says nothing about why', async () => {
    const ada = await app.factory(UserFactory).create();
    const { authenticator } = await enrol(ada);
    const { answer } = await signInWith(authenticator, { origin: 'https://evil.example' });
    const refused = await answer.assertStatus(422);
    expect(refused.json()).toEqual({ error: 'That passkey did not work.' });
  });

  it('asks for the password with every passkey', async () => {
    const ada = await app.factory(UserFactory).create();
    const { cookie } = await enrol(ada);
    const options = await app.withCookie(SESSION, cookie).post('/settings/passkeys/options', { json: {} }).assertOk();
    const response = device().register(options.json() as never);
    const refused = await app.withCookie(SESSION, cookie).post('/settings/passkeys', { json: { response, name: 'Phone', password: 'wrong' } }).assertStatus(422);
    expect(refused.json()).toMatchObject({ field: 'password' });
    await app.assertDatabaseCount('passkeys', 1);
  });

  it('turning the first one on signs out the other devices', async () => {
    const ada = await app.factory(UserFactory).create();
    const other = (await app.post('/login', credentialsOf(ada)).assertRedirect('/dashboard')).cookie(SESSION)!;
    await enrol(ada);
    await app.withCookie(SESSION, other).get('/dashboard').assertRedirect('/login');
  });

  it('proves the factor again with a passkey in a signed-in session; a wrong response ends nothing', async () => {
    const ada = await app.factory(UserFactory).create();
    const { cookie, authenticator } = await enrol(ada);
    const as = () => app.withCookie(SESSION, cookie);
    await as().navigating().get('/settings/two-factor/verify').assertPage('auth/TwoFactorVerify', { passkey: true, totp: false });
    const refused = await as().post('/settings/two-factor/verify/passkey/options', { json: {} }).assertOk();
    await as().post('/settings/two-factor/verify/passkey', { json: { response: authenticator.authenticate(refused.json() as never, { origin: 'https://evil.example' }) } }).assertStatus(422);
    await as().get('/dashboard').assertAuthenticated(ada);
    const options = await as().post('/settings/two-factor/verify/passkey/options', { json: {} }).assertOk();
    await as().post('/settings/two-factor/verify/passkey', { json: { response: authenticator.authenticate(options.json() as never) } }).assertRedirect('/dashboard');
  });

  it('shows an account with only passkeys its recovery codes, and makes new ones', async () => {
    const ada = await app.factory(UserFactory).create();
    const { cookie } = await enrol(ada);
    const as = () => app.withCookie(SESSION, cookie);
    await as().navigating().get('/settings/two-factor').assertPage('auth/TwoFactor', { enabled: false, secured: true, recoveryCodesLeft: 10 });
    const made = await as().layering().post('/settings/two-factor/recovery-codes').assertLayer('auth/RecoveryCodes');
    expect(made.page()!.props.codes).toHaveLength(10);
  });

  it('renames a passkey, and only the owner can', async () => {
    const ada = await app.factory(UserFactory).create();
    const grace = await app.factory(UserFactory).create();
    const { cookie } = await enrol(ada);
    const id = await passkeyIdOf();
    await app.withCookie(SESSION, cookie).put(`/settings/passkeys/${id}`, { json: { name: 'Work laptop' } }).assertOk();
    await app.withCookie(SESSION, cookie).navigating().get('/settings/passkeys').assertPage('auth/Passkeys', { passkeys: [{ name: 'Work laptop' }] });
    const intruder = (await app.post('/login', credentialsOf(grace))).cookie(SESSION)!;
    await app.withCookie(SESSION, intruder).put(`/settings/passkeys/${id}`, { json: { name: 'Mine' } }).assertNotFound();
  });

  it('removing the last factor needs the password and takes the recovery codes along', async () => {
    const ada = await app.factory(UserFactory).create();
    const { cookie } = await enrol(ada);
    await app.assertDatabaseCount('two_factor_recovery_codes', 10);
    const id = await passkeyIdOf();
    await app.withCookie(SESSION, cookie).post(`/settings/passkeys/${id}/remove`, { json: {} }).assertStatus(422);
    await app.assertDatabaseCount('passkeys', 1);
    await app.withCookie(SESSION, cookie).post(`/settings/passkeys/${id}/remove`, { json: { password: 'password' } }).assertOk();
    await app.assertDatabaseCount('passkeys', 0);
    await app.assertDatabaseCount('two_factor_recovery_codes', 0);
  });

  it('shows the list on the settings page, but only within the password confirmation', async () => {
    const ada = await app.factory(UserFactory).create();
    const { cookie } = await enrol(ada);
    await app.withCookie(SESSION, cookie).navigating().get('/settings/passkeys').assertPage('auth/Passkeys', { lastFactor: true, passkeys: [{ name: 'Laptop', suspended: false }] });
    // A session that did not type the password recently is sent to confirm it.
    await app.actingAs(ada).get('/settings/passkeys', { headers: { accept: 'text/html' } }).assertRedirect('/confirm-password');
  });

  it('answers 423 to the JSON calls of a session without a fresh password', async () => {
    const ada = await app.factory(UserFactory).create();
    await app.actingAs(ada).post('/settings/passkeys/options', { json: {}, headers: json }).assertStatus(423);
    await app.actingAs(ada).post('/settings/passkeys', { json: { response: {}, name: 'x', password: 'password' }, headers: json }).assertStatus(423);
    await app.assertDatabaseCount('passkeys', 0);
  });

  it('keeps a signed-in session out of the guest routes', async () => {
    const ada = await app.factory(UserFactory).create();
    for (const path of ['/passkeys/sign-in/options', '/passkeys/sign-in', '/two-factor-challenge/passkey/options', '/two-factor-challenge/passkey']) {
      await app.actingAs(ada).post(path, { json: {} }).assertRedirect('/dashboard');
    }
  });

  it('shows the recovery codes in an answer nothing stores', async () => {
    const ada = await app.factory(UserFactory).create();
    const login = await app.post('/login', credentialsOf(ada)).assertRedirect('/dashboard');
    const cookie = login.cookie(SESSION)!;
    const options = await app.withCookie(SESSION, cookie).post('/settings/passkeys/options', { json: {} }).assertOk();
    await app
      .withCookie(SESSION, cookie)
      .post('/settings/passkeys', { json: { response: device().register(options.json() as never), name: 'Laptop', password: 'password' } })
      .assertOk()
      .assertHeader('cache-control', 'no-store, private');
  });

  it('a passkey whose counter went backwards is suspended, and is released only with the right password', async () => {
    const ada = await app.factory(UserFactory).create();
    const { cookie, authenticator } = await enrol(ada);
    await (await signInWith(authenticator)).answer.assertRedirect('/dashboard');
    // A counter that does not move forward suspends the passkey.
    await (await signInWith(authenticator, { signCount: 1 })).answer.assertStatus(422);
    const id = await passkeyIdOf();
    const page = () => app.withCookie(SESSION, cookie).navigating().get('/settings/passkeys');
    await page().assertPage('auth/Passkeys', { passkeys: [{ suspended: true }] });

    const release = (body: Record<string, unknown>) => app.withCookie(SESSION, cookie).post(`/settings/passkeys/${id}/release`, { json: body, headers: json });
    await release({}).assertStatus(422);
    expect((await release({ password: 'wrong' }).assertStatus(422)).json()).toMatchObject({ field: 'password' });
    await release({ password: 'password' }).assertOk();
    await page().assertPage('auth/Passkeys', { passkeys: [{ suspended: false }] });
  });
});

describe('the mails about passkeys', { timeout: 30_000 }, () => {
  /** Runs the queued listeners, which queue the mails. */
  const sent = async () => {
    await app.queue.work();
    return app.mail.queued(PasskeyMail).map((mail) => mail.message);
  };

  it('tells the owner when a passkey is added and when it is removed', async () => {
    const ada = await app.factory(UserFactory).create();
    const { cookie } = await enrol(ada);
    const added = (await sent()).at(-1)!;
    expect(added.subject).toBe('A passkey was added');
    expect(added.text).toContain('“Laptop”');
    const id = await passkeyIdOf();
    await app.withCookie(SESSION, cookie).post(`/settings/passkeys/${id}/remove`, { json: { password: 'password' } }).assertOk();
    expect((await sent()).at(-1)!.subject).toBe('A passkey was removed');
  });

  it('tells the owner which passkey was suspended', async () => {
    const ada = await app.factory(UserFactory).create();
    const { authenticator } = await enrol(ada, { name: 'Work laptop' });
    await (await signInWith(authenticator)).answer.assertRedirect('/dashboard');
    await (await signInWith(authenticator, { signCount: 1 })).answer.assertStatus(422);
    const suspended = (await sent()).at(-1)!;
    expect(suspended.subject).toBe('A passkey was suspended');
    expect(suspended.text).toContain('“Work laptop”');
  });

  it('after a password reset, lists the passkeys that still sign in', async () => {
    const ada = await app.factory(UserFactory).create();
    const { cookie } = await enrol(ada, { name: 'Laptop' });
    const options = await app.withCookie(SESSION, cookie).post('/settings/passkeys/options', { json: {} }).assertOk();
    await app
      .withCookie(SESSION, cookie)
      .post('/settings/passkeys', { json: { response: device().register(options.json() as never), name: '<b>Phone</b>', password: 'password' } })
      .assertOk();
    await app.post('/forgot-password', { form: { email: ada.email } });
    await app.queue.work();
    const sentLink = app.mail.queued(ResetPasswordMail).at(-1)!;
    const link = new URL(/https?:\/\/\S+\/reset-password\S*(?=\))/.exec(sentLink.message.text)![0]);
    const opened = await app.get(link.pathname + link.search).assertRedirect('/reset-password');
    await app.withCookie('password_reset', opened.cookie('password_reset')!).post('/reset-password', { form: { password: 'a new password', password_confirmation: 'a new password' } }).assertRedirect('/login');

    const mail = app.mail.queued(PasskeyMail).map((queued) => queued.message).find((message) => message.subject.startsWith('Your password was reset'))!;
    expect(mail.subject).toBe('Your password was reset — these passkeys still sign in');
    expect(mail.text).toContain('Laptop');
    expect(mail.html).not.toContain('<b>Phone');
  });

  it('after a password reset, says nothing to an account without passkeys', async () => {
    const ada = await app.factory(UserFactory).create();
    await app.post('/forgot-password', { form: { email: ada.email } });
    await app.queue.work();
    const link = new URL(/https?:\/\/\S+\/reset-password\S*(?=\))/.exec(app.mail.queued(ResetPasswordMail).at(-1)!.message.text)![0]);
    const opened = await app.get(link.pathname + link.search).assertRedirect('/reset-password');
    await app.withCookie('password_reset', opened.cookie('password_reset')!).post('/reset-password', { form: { password: 'a new password', password_confirmation: 'a new password' } }).assertRedirect('/login');
    await app.queue.work();
    expect(app.mail.queued(PasskeyMail)).toHaveLength(0);
  });

  it('is written in the language of the account', async () => {
    const ada = await app.factory(UserFactory).create({ locale: 'de' });
    await enrol(ada);
    const mail = (await sent()).at(-1)!;
    expect(mail.subject).toBe('Ein Passkey wurde hinzugefügt');
    expect(mail.text).toContain('Hallo');
  });

  describe('about a failed sign-in', () => {
    const failed = (userId: number, ip: string | null = '203.0.113.7') => ({ userId, ip, userAgent: null });

    it('is sent at most once an hour for an account', async () => {
      const ada = await app.factory(UserFactory).create();
      await app.make(NotifyAboutFailedPasskeySignIn).handle(failed(ada.id));
      await app.make(NotifyAboutFailedPasskeySignIn).handle(failed(ada.id)); // within the hour: no second mail
      const mails = app.mail.queued(PasskeyMail);
      expect(mails).toHaveLength(1);
      expect(mails[0]!.message.subject).toBe('A passkey sign-in failed');
      expect(mails[0]!.message.text).toContain('from 203.0.113.7');
    });

    it('leaves out where it came from when the address is unknown', async () => {
      const ada = await app.factory(UserFactory).create();
      await app.make(NotifyAboutFailedPasskeySignIn).handle(failed(ada.id, null));
      expect(app.mail.queued(PasskeyMail).at(-1)!.message.text).not.toMatch(/\bfrom\b/);
    });

    it('gives the hour back when the mail could not be queued, so the retry of the queue sends it', async () => {
      const ada = await app.factory(UserFactory).create();
      const send = vi.spyOn(PasskeyNotices.prototype, 'send').mockRejectedValueOnce(new Error('queue is down'));
      try {
        await expect(app.make(NotifyAboutFailedPasskeySignIn).handle(failed(ada.id))).rejects.toThrow('queue is down');
        expect(app.mail.queued(PasskeyMail)).toHaveLength(0);
        await app.make(NotifyAboutFailedPasskeySignIn).handle(failed(ada.id)); // the retry
        expect(app.mail.queued(PasskeyMail)).toHaveLength(1);
      } finally {
        send.mockRestore();
      }
    });
  });
});

describe('marmeon auth:reset-two-factor and passkeys', { timeout: 30_000 }, () => {
  it('removes the passkeys and the recovery codes of an owner who lost every device, and lets the password alone sign in', async () => {
    const ada = await app.factory(UserFactory).create();
    await enrol(ada);
    const lines: string[] = [];
    const output = { success: (line: string) => lines.push(line), error: (line: string) => lines.push(line) };
    const code = await app.make(ResetTwoFactorCommand).handle({ args: [ada.email], options: { force: true }, output } as never);
    expect({ code, lines }).toEqual({ code: 0, lines: [`Removed the authenticator app, the passkeys and the recovery codes of ${ada.email}.`] });
    await app.assertDatabaseCount('passkeys', 0);
    await app.assertDatabaseCount('two_factor_recovery_codes', 0);
    await app.post('/login', credentialsOf(ada)).assertRedirect('/dashboard').assertAuthenticated(ada);
  });

  it('changes nothing without --force: the passkeys and the recovery codes stay', async () => {
    const ada = await app.factory(UserFactory).create();
    await enrol(ada);
    const lines: string[] = [];
    const output = { success: (line: string) => lines.push(line), error: (line: string) => lines.push(line) };
    const code = await app.make(ResetTwoFactorCommand).handle({ args: [ada.email], options: {}, output } as never);
    expect(code).toBe(1);
    expect(lines[0]).toContain('pass --force');
    await app.assertDatabaseCount('passkeys', 1);
    await app.assertDatabaseCount('two_factor_recovery_codes', 10);
  });
});

describe('an account with the authenticator app and a passkey', { timeout: 30_000 }, () => {
  it('removing the app leaves the passkeys: the page, the toast and the mail say so', async () => {
    const ada = await app.factory(UserFactory).create();
    const { cookie } = await enrol(ada);
    const as = () => app.withCookie(SESSION, cookie);
    await as().post('/settings/two-factor/setup');
    const setup = (await as().navigating().get('/settings/two-factor')).page()!.props.setup as { secret: string };
    await as().layering().post('/settings/two-factor/confirm', { form: { code: twoFactorCode(setup.secret), password: 'password' } });
    await as().navigating().get('/settings/two-factor').assertPage('auth/TwoFactor', { enabled: true, passkey: true });
    const done = await as().post('/settings/two-factor/disable', { form: { password: 'password' } }).assertRedirect('/settings/two-factor');
    expect(done.flashed().map((message) => JSON.stringify(message.data))).toEqual([expect.stringContaining('Your passkeys still protect the account')]);
    await as().navigating().get('/settings/two-factor').assertPage('auth/TwoFactor', { enabled: false, secured: true, passkey: true });
    await app.queue.work();
    expect(app.mail.queued(TwoFactorMail).at(-1)!.message.subject).toBe('The authenticator app was removed');
  });
});
