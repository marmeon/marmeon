/** A signed-in browser that adds `authenticator` as a passkey, as the settings page does. */
async function enrol(user: User, { authenticator = device(), name = 'Laptop' } = {}) {
  const login = await app.post('/login', credentialsOf(user)).assertRedirect('/dashboard');
  const cookie = login.cookie(SESSION)!;
  const options = await app.withCookie(SESSION, cookie).post('/settings/passkeys/options', { json: {} }).assertOk();
  const registered = await app
    .withCookie(SESSION, cookie)
    .post('/settings/passkeys', { json: { response: authenticator.register(options.json() as never), name, password: 'password' } })
    .assertOk();
  return { cookie, authenticator, recoveryCodes: (registered.json() as { recoveryCodes: string[] }).recoveryCodes };
}

/** A guest's passwordless sign-in: the options open the session's one challenge, the answer spends it. */
async function signInWith(authenticator: ReturnType<typeof device>, overrides: Parameters<ReturnType<typeof device>['authenticate']>[1] = {}) {
  const options = await app.post('/passkeys/sign-in/options', { json: {} }).assertOk();
  const guest = options.cookie(SESSION)!;
  return { guest, answer: app.withCookie(SESSION, guest).post('/passkeys/sign-in', { json: { response: authenticator.authenticate(options.json() as never, overrides) } }) };
}

