describe('the mails about the second factor', { timeout: 30_000 }, () => {
  /** Runs the queued listeners, which queue the mails. */
  const sent = async () => {
    await app.queue.work();
    return app.mail.queued(TwoFactorMail).map((mail) => mail.message);
  };

  it('tells the owner when it is turned on, when it is turned off, and when a recovery code signed in', async () => {
    const ada = await app.factory(UserFactory).create();
    const { cookie, recoveryCodes } = await enable(ada);
    expect((await sent()).map((message) => message.subject)).toEqual(['Two-factor authentication is on']);
    await app.withCookie(SESSION, await waiting(ada)).post('/two-factor-challenge', { form: { recovery_code: recoveryCodes[0]! } }).assertAuthenticated(ada);
    const used = (await sent()).at(-1)!;
    expect(used.subject).toBe('A recovery code was used');
    expect(used.text).toContain('9 codes are left');
    await app.withCookie(SESSION, cookie).post('/settings/two-factor/disable', { form: { password: 'password' } });
    expect((await sent()).at(-1)!.subject).toBe('Two-factor authentication was turned off');
  });

  it('tells the owner that somebody knows the password — at most once an hour', async () => {
    const ada = await app.factory(UserFactory).create();
    await enable(ada);
    await sent();
    const before = (await sent()).length;
    for (let tries = 0; tries < 2; tries++) {
      await app.withCookie(SESSION, await waiting(ada)).post('/two-factor-challenge', { form: { code: '000000' }, headers: { referer: 'http://localhost/two-factor-challenge' } });
    }
    const after = await sent();
    expect(after).toHaveLength(before + 1);
    expect(after.at(-1)!.subject).toBe('Someone knows your password');
  });
});

describe('the mail about a wrong code', { timeout: 30_000 }, () => {
  const failed = (userId: number, ip: string | null = '203.0.113.7') => ({ userId, at: new Date().toISOString(), ip, userAgent: null, during: 'sign-in' as const });

  it('is not sent for a wrong code in a session that is already signed in', async () => {
    const ada = await app.factory(UserFactory).create();
    const { cookie } = await enable(ada);
    await app
      .withCookie(SESSION, cookie)
      .post('/settings/two-factor/verify', { form: { code: '000000' }, headers: { referer: 'http://localhost/settings/two-factor/verify' } })
      .assertInvalid({ code: 'That code did not work.' });
    await app.queue.work();
    expect(app.mail.queued(TwoFactorMail).map((mail) => mail.message.subject)).not.toContain('Someone knows your password');
  });

  it('is written in the language of the account', async () => {
    const ada = await app.factory(UserFactory).create({ locale: 'de' });
    await enable(ada);
    await app.withCookie(SESSION, await waiting(ada)).post('/two-factor-challenge', { form: { code: '000000' }, headers: { referer: 'http://localhost/two-factor-challenge' } });
    await app.queue.work();
    const mail = app.mail.queued(TwoFactorMail).at(-1)!.message;
    expect(mail.subject).toBe('Jemand kennt dein Passwort');
    expect(mail.text).toContain('Hallo');
  });

  it('leaves out where it came from when the address is unknown', async () => {
    const ada = await app.factory(UserFactory).create({ locale: 'de' });
    await app.make(NotifyAboutFailedTwoFactor).handle(failed(ada.id, null));
    const text = app.mail.queued(TwoFactorMail).at(-1)!.message.text;
    expect(text).not.toContain(' von ');
    expect(text).not.toContain('unknown');
    await app.make(NotifyAboutFailedTwoFactor).handle(failed(ada.id)); // within the hour: no second mail
    expect(app.mail.queued(TwoFactorMail)).toHaveLength(1);
  });

  it('gives the hour back when the mail could not be queued, so the retry of the queue sends it', async () => {
    const ada = await app.factory(UserFactory).create();
    const send = vi.spyOn(TwoFactorNotices.prototype, 'send').mockRejectedValueOnce(new Error('queue is down'));
    try {
      await expect(app.make(NotifyAboutFailedTwoFactor).handle(failed(ada.id))).rejects.toThrow('queue is down');
      expect(app.mail.queued(TwoFactorMail)).toHaveLength(0);
      await app.make(NotifyAboutFailedTwoFactor).handle(failed(ada.id)); // the retry
      expect(app.mail.queued(TwoFactorMail)).toHaveLength(1);
    } finally {
      send.mockRestore();
    }
  });
});

describe('marmeon auth:reset-two-factor', { timeout: 30_000 }, () => {
  const reset = async (args: string[], options: Record<string, boolean> = { force: true }) => {
    const lines: string[] = [];
    const output = { success: (line: string) => lines.push(line), error: (line: string) => lines.push(line) };
    const code = await app.make(ResetTwoFactorCommand).handle({ args, options, output } as never);
    return { code, lines };
  };

  it('removes the factor and the codes, lets the password alone sign in, and tells the owner', async () => {
    const ada = await app.factory(UserFactory).create();
    await enable(ada);
    const info = vi.spyOn(app.make(Logger), 'info');
    expect(await reset([ada.email.toUpperCase()])).toEqual({ code: 0, lines: [`Removed the authenticator app, the passkeys and the recovery codes of ${ada.email}, and ended its sessions.`] });
    expect(info).toHaveBeenCalledWith(expect.stringContaining('second factor'), { userId: ada.id });
    await app.assertDatabaseCount('two_factor_authentications', 0);
    await app.assertDatabaseCount('two_factor_recovery_codes', 0);
    await app.post('/login', credentialsOf(ada)).assertRedirect('/dashboard').assertAuthenticated(ada);
    await app.queue.work();
    expect(app.mail.queued(TwoFactorMail).map((mail) => mail.message.subject)).toContain('Two-factor authentication was reset');
  });

  it('ends every session and remember-me cookie of the account, so none of them can enrol a first factor afterwards', async () => {
    const ada = await app.factory(UserFactory).create();
    const { cookie, secret } = await enable(ada);
    const challenge = await app.post('/login', credentialsOf(ada, { remember: 'on' })).assertRedirect('/two-factor-challenge');
    const phone = await app.withCookie(SESSION, challenge.cookie(SESSION)!).post('/two-factor-challenge', { form: { code: twoFactorCode(secret, inSeconds(30)) } }).assertAuthenticated(ada);
    const remember = phone.cookie('remember_web')!;
    expect(remember).toBeDefined();
    const other = await app.factory(UserFactory).create();
    const otherCookie = (await app.post('/login', credentialsOf(other)).assertRedirect('/dashboard')).cookie(SESSION)!;
    await app.withCookie(SESSION, cookie).expectingJson().get('/dashboard').assertOk();
    // The sign-in rotates the cookie: the reset must refuse the rotated one, which is the valid one.
    const rotated = (await app.withCookie('remember_web', remember).expectingJson().get('/dashboard').assertOk()).cookie('remember_web') ?? remember;
    expect((await reset([ada.email])).code).toBe(0);
    await app.withCookie(SESSION, cookie).expectingJson().get('/dashboard').assertUnauthorized();
    await app.withCookie(SESSION, cookie).post('/settings/two-factor/setup').assertRedirect('/login');
    await app.withCookie(SESSION, otherCookie).expectingJson().get('/dashboard').assertOk();
    await app.withCookie('remember_web', rotated).expectingJson().get('/dashboard').assertUnauthorized();
  });

  it('exits 1 and says so when a factor was enrolled while it ran', async () => {
    const ada = await app.factory(UserFactory).create();
    await enable(ada);
    const real = TwoFactorStore.prototype.factors;
    const factors = vi.spyOn(TwoFactorStore.prototype, 'factors');
    factors.mockImplementationOnce(real).mockImplementationOnce(() => Promise.resolve([{}] as never));
    try {
      expect(await reset([ada.email])).toEqual({ code: 1, lines: [`A second factor was enrolled for ${ada.email} while the command ran. Run it again.`] });
    } finally {
      factors.mockRestore();
    }
  });

  it('changes nothing without --force, and says so for an unknown address or an account without a factor', async () => {
    const ada = await app.factory(UserFactory).create();
    const { cookie } = await enable(ada);
    const refused = await reset([ada.email], {});
    expect(refused.code).toBe(1);
    expect(refused.lines[0]).toContain('pass --force');
    await app.withCookie(SESSION, cookie).expectingJson().get('/dashboard').assertOk();
    await app.assertDatabaseCount('two_factor_authentications', 1);
    expect(await reset(['nobody@example.com'])).toEqual({ code: 1, lines: ['No account has the address nobody@example.com.'] });
    expect((await reset([])).code).toBe(1);
    const grace = await app.factory(UserFactory).create();
    expect(await reset([grace.email])).toEqual({ code: 0, lines: [`${grace.email} has no second factor.`] });
  });
});

describe('changing the factors of an account that has one', { timeout: 30_000 }, () => {
  /** The settings routes 15 minutes later: the password typed again opens sudo mode, but the factor proven when it was turned on is too old. */
  async function later(run: (as: () => ReturnType<typeof app.withCookie>, secret: string, cookie: string) => Promise<void>) {
    const ada = await app.factory(UserFactory).create();
    const { cookie, secret } = await enable(ada);
    vi.useFakeTimers({ toFake: ['Date'], now: Date.now() + 1800_000 });
    try {
      const as = () => app.withCookie(SESSION, cookie);
      await as().post('/confirm-password', { form: { password: 'password' } });
      await run(as, secret, cookie);
    } finally {
      vi.useRealTimers();
    }
  }

  it('sends such a session to the verify page, for the page and for every change, and changes nothing', async () => {
    await later(async (as) => {
      await as().get('/settings/two-factor').assertRedirect('/settings/two-factor/verify');
      await as().post('/settings/two-factor/setup').assertRedirect('/settings/two-factor/verify');
      await as().post('/settings/two-factor/recovery-codes').assertRedirect('/settings/two-factor/verify');
      await as().post('/settings/two-factor/disable', { form: { password: 'password' } }).assertRedirect('/settings/two-factor/verify');
      await as().withHeaders({ accept: 'application/json' }).post('/settings/two-factor/disable', { form: { password: 'password' } }).assertForbidden().assertJson({ error: 'two_factor_unverified' });
      await app.assertDatabaseCount('two_factor_authentications', 1);
      await app.assertDatabaseCount('two_factor_recovery_codes', 10);
    });
  });

  it('keeps the address and the API tokens out of reach of such a session, too', async () => {
    await later(async (as) => {
      await as().put('/settings/email', { form: { current_password: 'password', email: 'thief@example.com' } }).assertRedirect('/settings/two-factor/verify');
      await as().withHeaders({ accept: 'application/json' }).post('/settings/tokens', { form: { current_password: 'password', name: 'CI', abilities: 'users:read' } }).assertForbidden().assertJson({ error: 'two_factor_unverified' });
      await app.assertDatabaseCount('personal_access_tokens', 0);
    });
  });

  it('lets the same session in once it proved the factor again', async () => {
    await later(async (as, secret, cookie) => {
      const done = await as().post('/settings/two-factor/verify', { form: { code: twoFactorCode(secret) } }).assertRedirect();
      await app.withCookie(SESSION, done.cookie(SESSION) ?? cookie).navigating().get('/settings/two-factor').assertPage('auth/TwoFactor');
      await app.withCookie(SESSION, done.cookie(SESSION) ?? cookie).put('/settings/email', { form: { current_password: 'password', email: 'new@example.com' } }).assertRedirect();
      await app.assertDatabaseHas('users', { pending_email: 'new@example.com' });
    });
  });
});

describe('a session that ends while the authenticator is set up', () => {
  /** The moment after the other devices are signed out, an operator ends the account's sessions. */
  function endSessionsAfterSignOut() {
    const write = UserRepository.prototype.updatePasswordHash;
    return vi.spyOn(UserRepository.prototype, 'updatePasswordHash').mockImplementation(async function (this: UserRepository, id, hash) {
      await write.call(this, id, hash);
      await this.updateSessionKey(id, 'e'.repeat(40), undefined);
    });
  }

  async function begin(user: User) {
    const login = await app.post('/login', credentialsOf(user)).assertRedirect('/dashboard');
    const cookie = login.cookie(SESSION)!;
    await app.withCookie(SESSION, cookie).post('/settings/two-factor/setup').assertRedirect('/settings/two-factor');
    const page = await app.withCookie(SESSION, cookie).navigating().get('/settings/two-factor').assertPage('auth/TwoFactor');
    return { cookie, secret: (page.page()!.props.setup as { secret: string }).secret };
  }

  it('stores no factor and sends the user to the sign-in', async () => {
    const ada = await app.factory(UserFactory).create();
    const { cookie, secret } = await begin(ada);
    const spy = endSessionsAfterSignOut();
    try {
      await app.withCookie(SESSION, cookie).post('/settings/two-factor/confirm', { form: { code: twoFactorCode(secret), password: 'password' } }).assertRedirect('/login');
    } finally {
      spy.mockRestore();
    }
    await app.assertDatabaseCount('two_factor_recovery_codes', 0);
    expect(await app.make(TwoFactorStore).factors(ada.id)).toEqual([]);
  });

  it('holds the account\'s row on a real session_key and keeps the key', async () => {
    const ada = await app.factory(UserFactory).create();
    const key = 'k'.repeat(43);
    await app.make(UserRepository).updateSessionKey(ada.id, key, null);
    const { cookie, secret } = await begin(ada);
    await app.withCookie(SESSION, cookie).layering().post('/settings/two-factor/confirm', { form: { code: twoFactorCode(secret), password: 'password' } }).assertLayer('auth/RecoveryCodes');
    expect(await app.make(TwoFactorStore).factors(ada.id)).toEqual(['totp']);
    expect((await app.make(UserRepository).findById(ada.id))?.sessionKey).toBe(key);
  });

  it('stops at the lock when a real session_key was replaced meanwhile', async () => {
    const ada = await app.factory(UserFactory).create();
    await app.make(UserRepository).updateSessionKey(ada.id, 'k'.repeat(43), null);
    const { cookie, secret } = await begin(ada);
    const spy = endSessionsAfterSignOut();
    try {
      await app.withCookie(SESSION, cookie).post('/settings/two-factor/confirm', { form: { code: twoFactorCode(secret), password: 'password' } }).assertRedirect('/login');
    } finally {
      spy.mockRestore();
    }
    expect(await app.make(TwoFactorStore).factors(ada.id)).toEqual([]);
  });
});
