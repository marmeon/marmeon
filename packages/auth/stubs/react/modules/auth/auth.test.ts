const credentials = (user: User, password = 'password') => ({ form: { email: user.email, password } });
/** A request that keeps the session of `response`. */
const continuing = (response: { cookie(name: string): string | undefined }) => app.withCookie(SESSION, response.cookie(SESSION)!);
/** The link in the last queued mail of a class — path and query. Mails are composed now and sent by a worker. */
const linkIn = <M extends Mailable>(Mail: abstract new (...args: any[]) => M, path: string) => {
  const sent = app.mail.queued(Mail).at(-1)!;
  const url = new URL(new RegExp(`https?://\\S+${path}\\S*(?=\\))`).exec(sent.message.text)![0]);
  return url.pathname + url.search;
};

describe('signing in and out', { timeout: 30_000 }, () => {
  it('signs in with e-mail and password in a new session', async () => {
    const ada = await app.factory(UserFactory).create();
    // A guest's login page keeps no session; a failed sign-in does — its errors wait for the page.
    expect((await app.get('/login')).headers.getSetCookie()).toEqual([]);
    const planted = await app.post('/login', credentials(ada, 'wrong'));
    const login = await app.withCookie(SESSION, planted.cookie(SESSION)!).post('/login', credentials(ada)).assertRedirect('/dashboard').assertAuthenticated(ada);
    expect(login.cookie(SESSION)).not.toBe(planted.cookie(SESSION)); // session fixation
    await continuing(login).navigating().get('/dashboard').assertPage('auth/Dashboard', { name: ada.name });
  });

  it('answers an unknown e-mail exactly like a wrong password', async () => {
    const ada = await app.factory(UserFactory).create();
    const wrong = await app.post('/login', credentials(ada, 'wrong'));
    const unknown = await app.post('/login', { form: { email: 'nobody@example.com', password: 'wrong' } });
    expect([unknown.status, unknown.session().errors]).toEqual([wrong.status, wrong.session().errors]);
    expect(JSON.stringify(wrong.session())).not.toContain('"wrong"'); // the password is never flashed
  });

  it('throttles failed sign-ins per e-mail and address', async () => {
    const ada = await app.factory(UserFactory).create();
    for (let attempt = 0; attempt < 5; attempt++) await app.post('/login', credentials(ada, 'wrong'));
    await app.post('/login', credentials(ada)).assertInvalid({ email: /^Too many login attempts/ }).assertGuest();
  });

  describe('a sign-in limit counts a client, not an address', () => {
    /** A JSON sign-in as it arrives from `remote` (the connection's peer; no proxy is trusted, so X-Forwarded-For counts for nothing). */
    const signInFrom = async (remote: string, email: string, headers: Record<string, string> = {}) => {
      const response = await createHttpKernel(app.application).request(
        '/login',
        { method: 'POST', headers: { accept: 'application/json', 'content-type': 'application/json', ...headers }, body: JSON.stringify({ email, password: 'wrong' }) },
        { remoteAddress: remote },
      );
      const errors = response.status === 422 ? ((await response.json()) as { errors: { email: string[] } }).errors.email[0]! : '';
      return { status: response.status, throttled: errors.startsWith('Too many login attempts') };
    };

    it('six wrong passwords from addresses of one IPv6 /64 are throttled at the sixth', async () => {
      const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
      const answers = [];
      for (let i = 1; i <= 6; i++) answers.push(await signInFrom(`2001:db8::${i}`, ada.email));
      expect(answers.map((answer) => answer.throttled)).toEqual([false, false, false, false, false, true]);
    });

    it('treats an IPv4-mapped peer as its IPv4 address, and another /64 as another client', async () => {
      const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
      for (const remote of ['203.0.113.9', '::ffff:203.0.113.9', '203.0.113.9', '::ffff:203.0.113.9', '203.0.113.9']) expect((await signInFrom(remote, ada.email)).throttled).toBe(false);
      expect((await signInFrom('::ffff:203.0.113.9', ada.email)).throttled).toBe(true);
      expect((await signInFrom('2001:db8:0:1::1', ada.email)).throttled).toBe(false);
    });

    it('does not let X-Forwarded-For open a budget when no proxy is trusted', async () => {
      const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
      const answers = [];
      for (let i = 1; i <= 6; i++) answers.push(await signInFrom('203.0.113.9', ada.email, { 'x-forwarded-for': `2001:db8:${i}::1` }));
      expect(answers.map((answer) => answer.throttled)).toEqual([false, false, false, false, false, true]);
    });

    it('stops a client at 30 sign-ins a minute whatever e-mail addresses it names', async () => {
      const statuses = [];
      for (let i = 1; i <= 31; i++) statuses.push((await signInFrom(`2001:db8:5:5::${i.toString(16)}`, `nobody${i}@example.com`)).status);
      expect(statuses.slice(0, 30).every((status) => status === 422)).toBe(true);
      expect(statuses[30]).toBe(429);
      // Another client is not held up by it.
      expect((await signInFrom('2001:db8:6:6::1', 'nobody@example.com')).status).toBe(422);
    });
  });

  it('signs out', async () => {
    const ada = await app.factory(UserFactory).create();
    await app.actingAs(ada).post('/logout').assertRedirect('/login').assertGuest();
    await app.expectingJson().get('/dashboard').assertUnauthorized();
  });

  it('leaves nothing for "Back" after signing out: full page load, no-store, Clear-Site-Data', async () => {
    const ada = await app.factory(UserFactory).create();
    await app.actingAs(ada).get('/dashboard').assertOk().assertHeader('cache-control', 'no-store, private');
    // A client-side visit gets 409 + x-marmeon-location: the browser loads the login page fully, the pages it kept in memory are gone.
    const visit = await app.actingAs(ada).navigating().post('/logout').assertStatus(409).assertHeader('x-marmeon-location', '/login').assertGuest();
    expect(visit.headers.get('clear-site-data')).toBe('"storage"'); // not "cache": Chrome would scan its whole disk cache first
  });

  it('keeps signing in by the "keep me signed in" cookie', async () => {
    const ada = await app.factory(UserFactory).create();
    const login = await app.post('/login', { form: { ...credentials(ada).form, remember: 'on' } });
    await app.withCookie(REMEMBER, login.cookie(REMEMBER)!).get('/dashboard').assertOk().assertAuthenticated(ada);
  });
});

