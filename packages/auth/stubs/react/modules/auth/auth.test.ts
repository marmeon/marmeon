describe('password reset', { timeout: 30_000 }, () => {
  it('mails a link that sets a new password once — the same answer for unknown addresses', async () => {
    const ada = await app.factory(UserFactory).create();
    const known = await app.post('/forgot-password', { form: { email: ada.email } });
    const unknown = await app.post('/forgot-password', { form: { email: 'nobody@example.com' } });
    // The same toast either way — waiting for the page the redirect leads to.
    expect(unknown.flashed().map((message) => message.data)).toEqual(known.flashed().map((message) => message.data));
    expect(known.flashed()).toHaveLength(1);
    // The request only queues a job, whatever the address; the job makes the token and queues the mail.
    app.queue.assertDispatchedTimes(SendPasswordResetLinkJob, 2);
    await app.queue.work();
    app.mail.assertQueuedCount(ResetPasswordMail, 1);

    const opened = await app.get(linkIn(ResetPasswordMail, '/reset-password')).assertRedirect('/reset-password');
    const cookie = opened.cookie('password_reset')!;
    const reset = () => app.withCookie('password_reset', cookie).post('/reset-password', { form: { password: 'a new password', password_confirmation: 'a new password' } });
    await reset().assertRedirect('/login');
    await reset().assertInvalid({ password: /invalid or has expired/ }); // used up
    await app.post('/login', credentials(ada, 'a new password')).assertAuthenticated(ada);
  });
});

