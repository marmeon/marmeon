/** A route that ends the other sessions of the signed-in account through `auth.updateSessionKey()`. */
class EndOtherSessionsController extends Controller {
  readonly #auth: Auth;
  constructor(auth: Auth) {
    super();
    this.#auth = auth;
  }
  async handle() {
    await this.#auth.updateSessionKey();
    return { done: true };
  }
}

