import { Registered } from '@bespokecore/auth';
import type { Mailable } from '@bespokecore/mail';
import { createTestApp, type TestApp } from '@bespokecore/testing';
import { beforeEach, describe, expect, it } from 'vitest';
import application from '../../bootstrap/app.ts';
import { UserFactory } from './factories/UserFactory.ts';
import { SendAccountExistsMailJob } from './jobs/SendAccountExistsMailJob.ts';
import { SendEmailVerification } from './listeners/SendEmailVerification.ts';
import { AccountExistsMail } from './mail/AccountExistsMail.ts';
import { VerifyEmailMail } from './mail/VerifyEmailMail.ts';

// Generated by `bespoke make:auth` — registration. Private by default (E146): it never tells whether an address has an account —
// the same answer in the same time, a note to the owner instead, and a confirmed address before the app opens. With
// AUTH_PRIVATE_REGISTRATION=false (E193) like Laravel Breeze: signed in at once, a taken address said (throttled — E100).
// Runs on SQLite and Postgres.

let app: TestApp;
beforeEach(async () => {
  app = await createTestApp(application, { database: 'refresh' });
});

const form = (email: string, password = 'orbital mechanics') => ({ form: { name: 'Katherine Johnson', email, password, password_confirmation: password } });
const register = (email = 'kj@example.com') => app.post('/register', form(email));
/** What a response says, without what differs per request anyway: the time, its id, the sign-ups this client has left. */
const answer = (response: { status: number; headers: Headers; body: string }) => ({
  status: response.status,
  headers: [...response.headers].filter(([name]) => !['date', 'x-request-id', 'x-ratelimit-remaining'].includes(name)),
  body: response.body,
});
/** The link in the last queued mail of a class — path and query. */
const linkIn = <M extends Mailable>(Mail: abstract new (...args: any[]) => M, path: string) => {
  const sent = app.mail.queued(Mail).at(-1)!;
  const url = new URL(new RegExp(`https?://\\S+${path}\\S*(?=\\))`).exec(sent.message.text)![0]);
  return url.pathname + url.search;
};

describe('private registration (E146) — the default', () => {
  it('answers a new and a known address byte for byte alike — no session, nobody signed in', async () => {
    await app.factory(UserFactory).create({ email: 'ada@example.com' });
    const fresh = await register('kj@example.com').assertRedirect('/register/sent');
    const known = await register('ADA@example.com').assertRedirect('/register/sent');
    expect(answer(known)).toEqual(answer(fresh));
    expect(fresh.headers.getSetCookie()).toEqual([]);
    await app.navigating().get('/register/sent').assertPage('auth/RegistrationSent');
  });

  it('mails the new account its verification link — and the owner of a known address a note instead (composed by a worker)', async () => {
    const ada = await app.factory(UserFactory).create({ email: 'ada@example.com', name: 'Ada Lovelace' });
    await register('kj@example.com');
    app.events.assertDispatched(Registered);
    app.queue.assertListenerQueued(SendEmailVerification);
    await register('ada@example.com');
    app.queue.assertDispatched(SendAccountExistsMailJob, { email: 'ada@example.com' });
    app.mail.assertNothingQueued(); // nothing rendered in the request: the time would show it
    await app.queue.work();
    app.mail.assertQueued(VerifyEmailMail, (_mail, message) => message.to[0]!.address === 'kj@example.com');
    app.mail.assertQueued(AccountExistsMail, (_mail, message) => message.to[0]!.address === ada.email && message.text.includes('/forgot-password'));
    app.mail.assertNotQueued(VerifyEmailMail, (_mail, message) => message.to[0]!.address === ada.email);
  });

  it('takes as long for a known address as for a new one — the password is hashed either way', async () => {
    await app.close();
    // The configured costs (OWASP), not the tests' cheap ones: the hash is what takes the time.
    app = await createTestApp(application, { database: 'refresh', env: { HASH_ARGON_MEMORY: '19456', HASH_ARGON_TIME: '2' } });
    await app.factory(UserFactory).create({ email: 'ada@example.com' });
    // Pairs — a new address and the known one right beside it, the order swapped every pair; twenty-one counted, the first pair
    // warms up. Each known address is compared with the new one beside it and the median of those ratios counts: a busy machine
    // slows both of a pair alike. A minute passes after every ten sign-ups (the throttle allows ten a minute from one address).
    const ratios: number[] = [];
    for (let i = 0; i <= 21; i++) {
      if (i > 0 && i % 5 === 0) app.travel({ seconds: 61 });
      const pair = { fresh: 0, known: 0 };
      for (const kind of i % 2 === 0 ? (['fresh', 'known'] as const) : (['known', 'fresh'] as const)) {
        const started = performance.now();
        await register(kind === 'fresh' ? `person${i}@example.com` : 'ada@example.com').assertRedirect('/register/sent');
        pair[kind] = performance.now() - started;
      }
      if (i > 0) ratios.push(pair.known / pair.fresh);
    }
    const ratio = ratios.toSorted((a, b) => a - b)[10]!;
    expect(ratio).toBeGreaterThan(0.5);
    expect(ratio).toBeLessThan(2);
  }, 30_000); // forty-four sign-ups at the configured hash costs — seconds on a busy machine

  it('checks the form live — but never says whether an address has an account', async () => {
    await app.factory(UserFactory).create({ email: 'ada@example.com' });
    await app.validating('email').post('/register', { json: { email: 'ada@example.com' } }).assertLiveValid('email');
    const invalid = await app.validating('email').post('/register', { json: { email: 'not an address' } }).assertUnprocessable();
    expect(invalid.json<{ errors: unknown }>().errors).toEqual({ email: ['Enter a valid e-mail address.'] });
  });

  it('opens the app only for a confirmed address: signed in, the new account sees the notice until it clicks the link', async () => {
    await register('kj@example.com');
    const login = await app.post('/login', { form: { email: 'kj@example.com', password: 'orbital mechanics' } }).assertRedirect('/dashboard');
    const signedIn = app.withCookie('bespoke_session', login.cookie('bespoke_session')!);
    await signedIn.get('/dashboard').assertRedirect('/email/verify');
    await signedIn.get('/settings/tokens').assertRedirect('/email/verify');
    await app.queue.work();
    await signedIn.get(linkIn(VerifyEmailMail, '/email/verify/')).assertRedirect('/dashboard');
    await signedIn.get('/dashboard').assertOk();
  });

  it('throttles registration: the 11th a minute from one address gets 429', async () => {
    for (let i = 1; i <= 10; i++) await register(`user${i}@example.com`).assertRedirect('/register/sent');
    await register('user11@example.com').assertStatus(429);
  });
});

describe('registration with AUTH_PRIVATE_REGISTRATION=false (E193)', () => {
  beforeEach(async () => {
    await app.close();
    app = await createTestApp(application, { database: 'refresh', env: { AUTH_PRIVATE_REGISTRATION: 'false' } });
  });
  /** A request that keeps the session of `response`. */
  const continuing = (response: { cookie(name: string): string | undefined }) => app.withCookie('bespoke_session', response.cookie('bespoke_session')!);

  it('registers, signs in and mails a signed link that verifies the address', async () => {
    const registered = await register().assertRedirect('/dashboard');
    // A queued listener: the registration queued it (app.queue), a worker composes and queues the mail (app.queue.work()).
    app.events.assertDispatched(Registered);
    app.queue.assertListenerQueued(SendEmailVerification);
    app.mail.assertNothingQueued();
    await continuing(registered).get('/dashboard').assertOk(); // no confirmed address needed
    await app.queue.work();
    app.mail.assertQueued(VerifyEmailMail, (_mail, message) => message.to[0]!.address === 'kj@example.com');
    const link = linkIn(VerifyEmailMail, '/email/verify/');
    const tampered = link.replace(/\/email\/verify\/\d+\//, '/email/verify/999999/');
    await continuing(registered).expectingJson().get(tampered).assertForbidden();
    await continuing(registered).get(link).assertRedirect('/dashboard').assertFlashed('toast', { message: 'Your e-mail address is verified.' });
  });

  it('refuses an address that exists, in any case — on submit and when the field is checked live', async () => {
    await app.factory(UserFactory).create({ email: 'kj@example.com' });
    await register('KJ@example.com').assertInvalid({ email: 'This e-mail address is already registered.' }).assertGuest();
    const live = await app.validating('email').post('/register', { json: { email: 'kj@example.com' } }).assertUnprocessable();
    expect(live.json<{ errors: unknown }>().errors).toEqual({ email: ['This e-mail address is already registered.'] });
    app.queue.assertNotDispatched(SendAccountExistsMailJob);
  });

  it('has no "check your inbox" page', async () => {
    await app.get('/register/sent').assertNotFound();
  });

  it('throttles registration: the 11th a minute from one address gets 429', async () => {
    for (let i = 1; i <= 10; i++) await register(`user${i}@example.com`).assertRedirect('/dashboard');
    await register('user11@example.com').assertStatus(429);
  });
});
