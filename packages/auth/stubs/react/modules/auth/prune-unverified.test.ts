import { AccessTokenStore, PASSWORD_RESET_TABLE, PasswordResetTokenStore, REMEMBER_TABLE, RememberTokenStore } from '@marmeon/auth';
import { Connections } from '@marmeon/database';
import { createTestApp, type TestApp } from '@marmeon/testing';
import { beforeEach, describe, expect, it } from 'vitest';
import application from '../../bootstrap/app.ts';
import { AccountDeletion } from './AccountDeletion.ts';
import { PruneUnverifiedCommand } from './commands/PruneUnverifiedCommand.ts';
import { UserFactory } from './factories/UserFactory.ts';
import { VerifyEmailMail } from './mail/VerifyEmailMail.ts';
import type { User } from './users.ts';
import { UserRepository } from './UserRepository.ts';

// Generated by `marmeon make:auth` — accounts whose address was never confirmed are deleted after AUTH_UNVERIFIED_DAYS (default 7,
// E203): nightly at 03:20, through AccountDeletion — never one that was confirmed once (first_verified_at). Irreversible — so these
// tests say what goes and, above all, what stays. Both behaviours (E193). Runs on SQLite and Postgres.

const DAY = 86_400_000;
let app: TestApp;
beforeEach(async () => {
  app = await createTestApp(application, { database: 'refresh' });
  app.freeze(); // the real time: rows the app writes itself (an update's updated_at) carry it too
});

/** An account made `days` ago (nothing changed since) — confirmed or not. */
const made = (days: number, confirmed: boolean, values: Partial<Record<'email' | 'name', string>> = {}) => {
  const at = new Date(app.clock.now() - days * DAY).toISOString();
  return app.factory(UserFactory).create({ ...values, created_at: at, updated_at: at, email_verified_at: confirmed ? at : null, first_verified_at: confirmed ? at : null }) as Promise<User>;
};
/** The schedule's run in the night `days` from now (03:20 UTC). */
const night = (days: number) => {
  const at = new Date(app.clock.now() + days * DAY);
  at.setUTCHours(3, 20, 0, 0);
  return at.toISOString();
};
const exists = async (user: User) => (await app.make(UserRepository).find(user.id)) !== undefined;
const signIn = async (user: User) => {
  const login = await app.post('/login', { form: { email: user.email, password: 'password' } }).assertRedirect();
  return app.withCookie('marmeon_session', login.cookie('marmeon_session')!);
};
const prune = async () => {
  const lines: string[] = [];
  const code = await app.make(PruneUnverifiedCommand).handle({ options: {}, args: [], output: { success: (line: string) => lines.push(line), error: (line: string) => lines.push(line) } } as never);
  return { code, lines };
};

describe('pruning accounts whose address was never confirmed (E203) — the default', () => {
  it('deletes one older than 7 days at 03:20 — with its tokens, and its session ends; a confirmed one and a younger one stay', async () => {
    const old = await made(8, false, { email: 'old@example.com' });
    const confirmed = await made(30, true, { email: 'confirmed@example.com' });
    const young = await made(5, false, { email: 'young@example.com' });
    const session = await signIn(old); // it may sign in — and sees only the notice (private registration)
    for (const user of [old, confirmed]) {
      await app.make(RememberTokenStore).create(user.id, new Date(app.clock.now() + 30 * DAY));
      await app.make(AccessTokenStore).create(user.id, 'cli', { expiresIn: '365d' });
      await app.make(PasswordResetTokenStore).create(user.email, 0);
    }

    expect(app.schedule.due(night(1))).toContain('auth:prune-unverified');
    const results = await app.schedule.run(night(1));
    expect(results.find((result) => result.task === 'auth:prune-unverified')).toMatchObject({ outcome: 'ran' });

    expect(await exists(old), 'an account unconfirmed for 8 days was kept').toBe(false);
    expect(await exists(confirmed), 'a confirmed account was deleted').toBe(true);
    expect(await exists(young), 'an account unconfirmed for 6 days was deleted').toBe(true);
    const db = app.make(Connections).get<any>();
    expect((await db.selectFrom(REMEMBER_TABLE).select('user_id').execute()).map((row) => Number(row.user_id))).toEqual([confirmed.id]);
    expect((await db.selectFrom(PASSWORD_RESET_TABLE).select('email').execute()).map((row) => row.email)).toEqual([confirmed.email]);
    expect(await app.make(AccessTokenStore).list(old.id)).toEqual([]);
    expect(await app.make(AccessTokenStore).list(confirmed.id)).toHaveLength(1);
    await session.get('/dashboard').assertRedirect('/login'); // nobody is signed in by it any more
  });

  it('counts from the sign-up — a later change does not extend it; an account confirmed once never goes', async () => {
    const at = (days: number) => new Date(app.clock.now() - days * DAY).toISOString();
    const touched = (await app.factory(UserFactory).create({ created_at: at(40), updated_at: at(3), email_verified_at: null, first_verified_at: null })) as User;
    const once = (await app.factory(UserFactory).create({ created_at: at(400), updated_at: at(400), email_verified_at: null, first_verified_at: at(399) })) as User;
    await app.schedule.run(night(1));
    expect(await exists(touched), 'a change extended the days of an account never confirmed').toBe(false);
    await app.schedule.run(night(30));
    expect(await exists(once), 'an account confirmed once was deleted').toBe(true);
  });

  it('keeps a confirmed account with a pending change of address — that change is no unconfirmed account (E146)', async () => {
    const kj = await made(30, true, { email: 'kj@example.com' });
    const session = await signIn(kj);
    await session.put('/settings/email', { form: { email: 'new@example.com' }, headers: { referer: 'http://localhost/settings/security' } }).assertRedirect();
    await app.schedule.run(night(1));
    expect(await app.make(UserRepository).find(kj.id)).toMatchObject({ email: 'kj@example.com', pending_email: 'new@example.com' });
  });

  it('deletes in batches and says how many — one confirmed between the look-up and the delete stays', async () => {
    const many = await Promise.all(Array.from({ length: 150 }, (_, index) => made(10, false, { email: `old${index}@example.com` })));
    // Confirmed a moment ago, after the look-up: the delete decides again.
    const ids = await app.make(UserRepository).unconfirmedSince(new Date(app.clock.now() - 7 * DAY), 200);
    expect(ids).toHaveLength(150);
    await app.make(UserRepository).markEmailVerified(many[0]!.id);
    expect(await app.make(AccountDeletion).delete([many[0]!.id], { unconfirmedSince: new Date(app.clock.now() - 7 * DAY) })).toEqual([]);
    expect(await exists(many[0]!)).toBe(true);

    expect(PruneUnverifiedCommand.batch).toBe(100);
    expect(await prune()).toEqual({ code: 0, lines: ['Deleted 149 accounts whose address was not confirmed within 7 days.'] });
    await app.assertDatabaseCount('users', 1);
    expect(await prune()).toEqual({ code: 0, lines: ['Deleted 0 accounts whose address was not confirmed within 7 days.'] });
  });

  it('AUTH_UNVERIFIED_DAYS sets the days — 0 keeps every account', async () => {
    await app.close();
    app = await createTestApp(application, { database: 'refresh', env: { AUTH_UNVERIFIED_DAYS: '30' } });
    app.freeze();
    const month = await made(20, false);
    expect((await prune()).lines).toEqual(['Deleted 0 accounts whose address was not confirmed within 30 days.']);
    expect(await exists(month)).toBe(true);
    await app.close();
    app = await createTestApp(application, { database: 'refresh', env: { AUTH_UNVERIFIED_DAYS: '0' } });
    app.freeze();
    const ancient = await made(400, false);
    expect(await prune()).toEqual({ code: 0, lines: ['AUTH_UNVERIFIED_DAYS=0: accounts without a confirmed address are kept.'] });
    expect(await exists(ancient)).toBe(true);
  });
});

describe('pruning accounts whose address was never confirmed with AUTH_PRIVATE_REGISTRATION=false (E193)', () => {
  beforeEach(async () => {
    await app.close();
    app = await createTestApp(application, { database: 'refresh', env: { AUTH_PRIVATE_REGISTRATION: 'false' } });
    app.freeze();
  });

  it('a sign-up that used the app but never confirmed its address goes after 7 days — and is signed out', async () => {
    const register = await app
      .post('/register', { form: { name: 'Ada', email: 'ada@example.com', password: 'correct horse battery', password_confirmation: 'correct horse battery' } })
      .assertRedirect('/dashboard');
    const session = app.withCookie('marmeon_session', register.cookie('marmeon_session')!);
    await session.get('/dashboard').assertOk(); // signed in at once, unconfirmed
    const ada = (await app.make(UserRepository).findByEmail('ada@example.com'))!;
    await app.schedule.run(night(6));
    expect(await exists(ada), 'deleted before its 7 days').toBe(true);
    await app.schedule.run(night(8));
    expect(await exists(ada)).toBe(false);
    await session.get('/dashboard').assertRedirect('/login');
  });

  it('an account confirmed by its link keeps that for good — an unconfirmed change of address never makes it prunable (Max, 07.10.)', async () => {
    const registered = await app
      .post('/register', { form: { name: 'Katherine', email: 'kj@example.com', password: 'orbital mechanics', password_confirmation: 'orbital mechanics' } })
      .assertRedirect('/dashboard');
    const session = app.withCookie('marmeon_session', registered.cookie('marmeon_session')!);
    await app.queue.work();
    const sent = app.mail.queued(VerifyEmailMail).at(-1)!;
    const link = new URL(/https?:\/\/\S+\/email\/verify\/\S+(?=\))/.exec(sent.message.text)![0]);
    await session.get(link.pathname + link.search).assertRedirect('/dashboard');
    // Changing the address asks for the password (sudo mode) — a sign-up signed in without typing it again.
    await session.post('/confirm-password', { form: { password: 'orbital mechanics' } }).assertRedirect();
    await session.put('/settings/email', { form: { email: 'katherine@nasa.example' }, headers: { referer: 'http://localhost/settings/security' } }).assertRedirect();
    const kj = await app.make(UserRepository).findByEmail('katherine@nasa.example');
    if (!kj) throw new Error('the address did not change');
    expect(kj).toMatchObject({ email_verified_at: null });
    expect(kj.first_verified_at, 'the first confirmation was not kept').not.toBeNull();
    await app.schedule.run(night(30));
    expect(await exists(kj), 'an account confirmed once was deleted').toBe(true);
    // A sign-up that never confirmed goes, in this behaviour too (the test above).
  });
});
