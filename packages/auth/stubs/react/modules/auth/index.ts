import { EmailChanged, SignInLockedOut, PasskeyCloneSuspected, PasskeyRegistered, PasskeyRemoved, PasskeySignInFailed, PasswordReset, RecoveryCodeUsed, Registered, RememberTokenReused, TwoFactorChallengeFailed, TwoFactorDisabled, TwoFactorEnabled } from '@marmeon/auth';
import { PasskeyServiceProvider } from '@marmeon/auth/passkeys';
import { defineModule, listen } from '@marmeon/core';
import { NotifyAboutEmailChange } from './listeners/NotifyAboutEmailChange.ts';
import { NotifyAboutFailedPasskeySignIn } from './listeners/NotifyAboutFailedPasskeySignIn.ts';
import { NotifyAboutFailedTwoFactor } from './listeners/NotifyAboutFailedTwoFactor.ts';
import { NotifyAboutPasskeyCloneSuspected } from './listeners/NotifyAboutPasskeyCloneSuspected.ts';
import { NotifyAboutPasskeyRegistered } from './listeners/NotifyAboutPasskeyRegistered.ts';
import { NotifyAboutPasskeyRemoved } from './listeners/NotifyAboutPasskeyRemoved.ts';
import { NotifyAboutPasskeysAfterReset } from './listeners/NotifyAboutPasskeysAfterReset.ts';
import { NotifyAboutRecoveryCodeUsed } from './listeners/NotifyAboutRecoveryCodeUsed.ts';
import { QueueLockoutMail } from './listeners/QueueLockoutMail.ts';
import { NotifyAboutRememberTokenReused } from './listeners/NotifyAboutRememberTokenReused.ts';
import { NotifyAboutTwoFactorDisabled } from './listeners/NotifyAboutTwoFactorDisabled.ts';
import { NotifyAboutTwoFactorEnabled } from './listeners/NotifyAboutTwoFactorEnabled.ts';
import { SendEmailVerification } from './listeners/SendEmailVerification.ts';
import { SendAccountExistsMailJob } from './jobs/SendAccountExistsMailJob.ts';
import { SendLockoutMailJob } from './jobs/SendLockoutMailJob.ts';
import { SendEmailChangeMailJob } from './jobs/SendEmailChangeMailJob.ts';
import { SendPasswordResetLinkJob } from './jobs/SendPasswordResetLinkJob.ts';
import { AuthServiceProvider } from './AuthServiceProvider.ts';
import { PruneUnverifiedCommand } from './commands/PruneUnverifiedCommand.ts';
import apiRoutes from './api-routes.ts';
import routes from './routes.ts';
import { schedule } from './schedule.ts';
import { UserSeeder } from './seeders/UserSeeder.ts';

// The auth module — generated by `marmeon make:auth`, yours to change: the code is the app's own.
// Other modules import from here, never from internals.
export { AccountDeleted, AccountDeletion } from './AccountDeletion.ts';
export { UserFactory } from './factories/UserFactory.ts';
export { UserRepository } from './UserRepository.ts';
export type { User } from './users.ts';

export default defineModule({
  name: 'auth',
  // PasskeyServiceProvider switches passkeys on. To switch them off, remove it, `PasskeyStore` from `combineFactors` in AuthServiceProvider, and
  // both imports of '@marmeon/auth/passkeys': the WebAuthn library is loaded only by code that imports that subpath.
  providers: [AuthServiceProvider, PasskeyServiceProvider],
  // Queued listeners (static queue): a worker sends the verification mail once the registration committed, and the owner's mails
  // about the second factor: turned on or off, a recovery code used, and (at most once an hour) a wrong code after the right password —
  // and about passkeys: added, removed, suspended as a possible clone, and (at most once an hour) a failed passkey sign-in —
  // and about a copied "keep me signed in" cookie that was used — and an account past its daily ceiling of password sign-ins.
  listeners: [
    listen(Registered, SendEmailVerification),
    listen(TwoFactorEnabled, NotifyAboutTwoFactorEnabled),
    listen(TwoFactorDisabled, NotifyAboutTwoFactorDisabled),
    listen(RecoveryCodeUsed, NotifyAboutRecoveryCodeUsed),
    listen(TwoFactorChallengeFailed, NotifyAboutFailedTwoFactor),
    listen(PasskeyRegistered, NotifyAboutPasskeyRegistered),
    listen(PasskeyRemoved, NotifyAboutPasskeyRemoved),
    listen(PasskeyCloneSuspected, NotifyAboutPasskeyCloneSuspected),
    listen(PasskeySignInFailed, NotifyAboutFailedPasskeySignIn),
    listen(RememberTokenReused, NotifyAboutRememberTokenReused),
    // Not queued (it wants the request's language): it queues the mail to the owner of an account that stopped taking passwords.
    listen(SignInLockedOut, QueueLockoutMail),
    // Not queued (the event cannot be): it queues the mail that lists the passkeys a password reset left standing.
    listen(PasswordReset, NotifyAboutPasskeysAfterReset),
    // Not queued (the language is the account's, read when it runs): it queues the note to the old address once an address changed.
    listen(EmailChanged, NotifyAboutEmailChange),
  ],
  // Queued work — a worker (`marmeon queue:work`, started by `marmeon dev`) runs only registered jobs.
  // Private registration: the note to an account's owner that someone signed up with its address; the link to a new
  // address, or the note to the owner of a taken one.
  jobs: [SendPasswordResetLinkJob, SendAccountExistsMailJob, SendEmailChangeMailJob, SendLockoutMailJob],
  migrations: new URL('./migrations/', import.meta.url),
  // Other modules may read and join `users` — writing goes through the UserRepository.
  exposes: ['users'],
  seeders: [UserSeeder],
  routes,
  apiRoutes,
  // Scheduled work: the nightly prune of tokens and expired changes of address (`auth:prune-tokens`) — and of unconfirmed accounts once you turn its
  // line on in schedule.ts (marmeon schedule:work).
  schedule,
  // marmeon auth:prune-unverified — the accounts whose address was not confirmed in time (by hand, or by the schedule once turned on).
  // marmeon auth:reset-two-factor and auth:end-sessions come with @marmeon/auth.
  commands: [PruneUnverifiedCommand],
});
