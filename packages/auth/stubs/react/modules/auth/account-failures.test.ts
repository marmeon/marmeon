import { TwoFactorState } from '@marmeon/auth';
import { softAuthenticator, cookieNames } from '@marmeon/auth/testing';
import { RateLimiter } from '@marmeon/cache';
import { createHttpKernel } from '@marmeon/server';
import { createTestApp, type TestApp } from '@marmeon/testing';
import { beforeEach, describe, expect, it } from 'vitest';
import application from '../../bootstrap/app.ts';
import { ACCOUNT_SIGN_INS, ACCOUNT_WINDOW_SECONDS, accountKey } from './account-failures.ts';
import { UserFactory } from './factories/UserFactory.ts';
import { SendLockoutMailJob } from './jobs/SendLockoutMailJob.ts';
import { LockoutMail } from './mail/LockoutMail.ts';
import { ResetPasswordMail } from './mail/ResetPasswordMail.ts';

// Generated by `marmeon make:auth` — the daily ceiling on failed password sign-ins of an account. Runs on SQLite and Postgres.

let app: TestApp;
let SESSION: string;
// Every test boots the app on a refreshed database — seconds on a busy machine, so its hook and tests get 30 s.
beforeEach(async () => {
  app = await createTestApp(application, { database: 'refresh' });
  ({ session: SESSION } = cookieNames(app));
}, 30_000);

const LOCKED = 'Too many failed sign-ins for this account. Reset your password or sign in with a passkey.';

/** A JSON sign-in as it arrives from `remote` — each /64 is a client of its own, so no per-client limit is in the way. */
async function signInFrom(remote: string, email: string, password = 'wrong') {
  const response = await createHttpKernel(app.application).request(
    '/login',
    { method: 'POST', headers: { accept: 'application/json', 'content-type': 'application/json' }, body: JSON.stringify({ email, password }) },
    { remoteAddress: remote },
  );
  const body = response.status === 422 ? ((await response.json()) as { errors: { email: string[] } }) : undefined;
  return { status: response.status, message: body?.errors.email[0] };
}

/** Counts `n` failed sign-ins against the account directly, as if they had come from `n` clients. */
async function fail(email: string, n: number) {
  const limiter = app.make(RateLimiter);
  for (let i = 0; i < n; i++) await limiter.hit(accountKey(email), ACCOUNT_WINDOW_SECONDS);
}

describe('the failure ceiling of an account', { timeout: 60_000 }, () => {
  it('refuses the 101st password sign-in of a day, from any client, with the right password too', async () => {
    const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
    for (let i = 1; i <= ACCOUNT_SIGN_INS; i++) {
      const answer = await signInFrom(`2001:db8:${i.toString(16)}::1`, ada.email);
      expect(answer.message).toBe('These credentials do not match our records.');
    }
    const locked = await signInFrom('2001:db8:ffff::1', ada.email);
    expect(locked).toEqual({ status: 422, message: LOCKED });
    // The right password does not get in, from yet another client …
    expect((await signInFrom('2001:db8:fffe::1', ada.email, 'password')).message).toBe(LOCKED);
    await app.post('/login', { form: { email: ada.email, password: 'password' } }).assertInvalid({ email: LOCKED }).assertGuest();
    // … and the address written another way is the same account.
    expect((await signInFrom('2001:db8:fffd::1', ' ADA@Example.com ')).message).toBe(LOCKED);
  });

  it('answers an address without an account exactly like one with an account, and mails only the account', async () => {
    const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
    await fail(ada.email, ACCOUNT_SIGN_INS);
    await fail('nobody@example.com', ACCOUNT_SIGN_INS);
    const known = await signInFrom('2001:db8:1::1', ada.email);
    const unknown = await signInFrom('2001:db8:2::1', 'nobody@example.com');
    expect(unknown).toEqual(known);
    expect(known).toEqual({ status: 422, message: LOCKED });
    // Both requests queued the same job; the worker finds one account.
    app.queue.assertDispatchedTimes(SendLockoutMailJob, 2);
    await app.queue.work();
    app.mail.assertQueuedCount(LockoutMail, 1).assertQueued(LockoutMail, (_mail, message) => message.to[0]!.address === ada.email);
  });

  it('counts failures of an address without an account, so the ceiling reveals nothing', async () => {
    for (let i = 1; i <= ACCOUNT_SIGN_INS; i++) expect((await signInFrom(`2001:db8:${i.toString(16)}::1`, 'nobody@example.com')).message).toBe('These credentials do not match our records.');
    expect((await signInFrom('2001:db8:ffff::1', 'nobody@example.com')).message).toBe(LOCKED);
  });

  it('tells the owner once a lockout, in their language, and says how to get in', async () => {
    const ada = await app.factory(UserFactory).create({ email: 'ada@example.com', locale: 'de' });
    await fail(ada.email, ACCOUNT_SIGN_INS);
    for (let i = 1; i <= 3; i++) await signInFrom(`2001:db8:${i}::1`, ada.email);
    await app.queue.work();
    app.mail.assertQueuedCount(LockoutMail, 1);
    const { subject, text } = app.mail.queued(LockoutMail)[0]!.message;
    expect(subject).toBe('Dein Konto nimmt keine Passwörter mehr an');
    expect(text).toContain('http://localhost/forgot-password');
    expect(text).toContain('Passkey');
  });

  it('keys on a hash of the address', () => {
    expect(accountKey('ada@example.com')).not.toContain('ada');
    expect(accountKey(' ADA@example.com')).toBe(accountKey('ada@example.com'));
    expect(accountKey('ada@example.com')).not.toBe(accountKey('alan@example.com'));
  });

  it('starts over after a successful sign-in', async () => {
    const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
    await fail(ada.email, ACCOUNT_SIGN_INS - 1);
    expect((await signInFrom('2001:db8:1::1', ada.email, 'password')).status).toBe(303);
    expect(await app.make(RateLimiter).attempts(accountKey(ada.email))).toBe(0);
    await fail(ada.email, ACCOUNT_SIGN_INS);
    expect((await signInFrom('2001:db8:2::1', ada.email)).message).toBe(LOCKED);
  });

  it('keeps one account from using the budget of another', async () => {
    const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
    const alan = await app.factory(UserFactory).create({ email: 'alan@example.com' });
    await fail(ada.email, ACCOUNT_SIGN_INS);
    expect((await signInFrom('2001:db8:1::1', ada.email)).message).toBe(LOCKED);
    await app.post('/login', { form: { email: alan.email, password: 'password' } }).assertAuthenticated(alan);
  });

  it('lets a password reset end it, and the new password sign in', async () => {
    const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
    await fail(ada.email, ACCOUNT_SIGN_INS);
    expect((await signInFrom('2001:db8:1::1', ada.email, 'password')).message).toBe(LOCKED);

    await app.post('/forgot-password', { form: { email: ada.email }, headers: { referer: 'http://localhost/forgot-password' } });
    await app.queue.work();
    const [sent] = app.mail.queued(ResetPasswordMail).slice(-1);
    const url = new URL(/https?:\/\/\S+\/reset-password\?\S+(?=\))/.exec(sent!.message.text)![0]);
    const cookie = (await app.get(url.pathname + url.search).assertRedirect('/reset-password')).cookie('password_reset')!;
    await app
      .withCookie('password_reset', cookie)
      .post('/reset-password', { form: { password: 'brand new password', password_confirmation: 'brand new password' }, headers: { referer: 'http://localhost/reset-password' } })
      .assertRedirect('/login');

    await app.post('/login', { form: { email: ada.email, password: 'brand new password' } }).assertAuthenticated(ada);
  });

  it('stays open for a passkey', async () => {
    const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
    const authenticator = softAuthenticator({ origin: 'http://localhost', rpId: 'localhost' });
    const login = await app.post('/login', { form: { email: ada.email, password: 'password' } }).assertRedirect('/dashboard');
    const cookie = login.cookie(SESSION)!;
    const registration = await app.withCookie(SESSION, cookie).post('/settings/passkeys/options', { json: {} }).assertOk();
    await app.withCookie(SESSION, cookie).post('/settings/passkeys', { json: { response: authenticator.register(registration.json() as never), name: 'Laptop', password: 'password' } }).assertOk();

    await fail(ada.email, ACCOUNT_SIGN_INS + 5);
    expect((await signInFrom('2001:db8:1::1', ada.email, 'password')).message).toBe(LOCKED);

    const options = await app.post('/passkeys/sign-in/options', { json: {} }).assertOk();
    const guest = options.cookie(SESSION)!;
    expect(await app.make(RateLimiter).attempts(accountKey(ada.email))).toBeGreaterThan(ACCOUNT_SIGN_INS);
    await app.withCookie(SESSION, guest).post('/passkeys/sign-in', { json: { response: authenticator.authenticate(options.json() as never) } }).assertRedirect('/dashboard');
    expect(await app.make(RateLimiter).attempts(accountKey(ada.email))).toBe(0);
  });

  it('leads the right password of an account with a second factor to the challenge, and starts the count over', async () => {
    let withFactor: unknown;
    class OneFactor extends TwoFactorState {
      async factors(id: unknown) {
        return id === withFactor ? (['totp'] as const) : [];
      }
      async enabledSince() {
        return undefined;
      }
      async removeAll() {}
    }
    await app.close(); // one database app per test
    app = await createTestApp(application, {
      database: 'refresh',
      override: (c) => c.instance(TwoFactorState, new OneFactor()),
    });
    ({ session: SESSION } = cookieNames(app));
    const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
    withFactor = ada.id;
    await fail(ada.email, ACCOUNT_SIGN_INS - 1);
    await app.post('/login', { form: { email: ada.email, password: 'password' } }).assertRedirect('/two-factor-challenge').assertGuest();
    expect(await app.make(RateLimiter).attempts(accountKey(ada.email))).toBe(0);
  });
});
