import { TwoFactorState } from '@marmeon/auth';
import { softAuthenticator, cookieNames, twoFactorCode } from '@marmeon/auth/testing';
import { createHttpKernel } from '@marmeon/server';
import { createTestApp, type TestApp } from '@marmeon/testing';
import { beforeEach, describe, expect, it } from 'vitest';
import application from '../../bootstrap/app.ts';
import { UserFactory } from './factories/UserFactory.ts';
import { SendLockoutMailJob } from './jobs/SendLockoutMailJob.ts';
import { LockoutMail } from './mail/LockoutMail.ts';
import { ResetPasswordMail } from './mail/ResetPasswordMail.ts';

// Generated by `marmeon make:auth` — the daily ceiling on password sign-ins of an account, which `auth.attempt()` keeps. Runs on SQLite and Postgres.

/** The test app's ceiling: the lowest the setting allows, so the tests do not sign in a hundred times. */
const CEILING = 10;

let app: TestApp;
let SESSION: string;
// Every test boots the app on a refreshed database — seconds on a busy machine, so its hook and tests get 30 s.
beforeEach(async () => {
  app = await createTestApp(application, { database: 'refresh', env: { AUTH_ACCOUNT_SIGN_INS_PER_DAY: String(CEILING) } });
  ({ session: SESSION } = cookieNames(app));
}, 30_000);

/** The device cookie's name (the app runs on HTTP in tests: no `__Host-` prefix). */
const DEVICE = 'marmeon_device';

const LOCKED = 'Too many failed sign-ins for this account. Reset your password or sign in with a passkey.';

/** A JSON sign-in as it arrives from `remote` — each /64 is a client of its own, so no per-client limit is in the way. */
async function signInFrom(remote: string, email: string, password = 'wrong') {
  const response = await createHttpKernel(app.application).request(
    '/login',
    { method: 'POST', headers: { accept: 'application/json', 'content-type': 'application/json' }, body: JSON.stringify({ email, password }) },
    { remoteAddress: remote },
  );
  const body = response.status === 422 ? ((await response.json()) as { errors: { email: string[] } }) : undefined;
  return { status: response.status, message: body?.errors.email[0] };
}

let clients = 0;
/** Another client every time (its own /64), so the sign-ins of a test never meet the per-client limit. */
const nextClient = () => `2001:db8:${(0x1000 + ++clients).toString(16)}::1`;

/** Counts `n` wrong password sign-ins against the account, as if they had come from `n` clients. */
async function fail(email: string, n: number) {
  for (let i = 0; i < n; i++) await signInFrom(nextClient(), email);
}

describe('the ceiling on the password sign-ins of an account', { timeout: 60_000 }, () => {
  it('refuses the sign-in after the ceiling, from any client, with the right password too', async () => {
    const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
    for (let i = 1; i <= CEILING; i++) expect((await signInFrom(nextClient(), ada.email)).message).toBe('These credentials do not match our records.');
    expect(await signInFrom(nextClient(), ada.email)).toEqual({ status: 422, message: LOCKED });
    // The right password does not get in, from yet another client …
    expect((await signInFrom(nextClient(), ada.email, 'password')).message).toBe(LOCKED);
    await app.post('/login', { form: { email: ada.email, password: 'password' } }).assertInvalid({ email: LOCKED }).assertGuest();
    // … and the address written another way is the same account.
    expect((await signInFrom(nextClient(), ' ADA@Example.com ')).message).toBe(LOCKED);
  });

  it('answers an address without an account exactly like one with an account, and mails only the account', async () => {
    const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
    await fail(ada.email, CEILING);
    await fail('nobody@example.com', CEILING);
    const known = await signInFrom(nextClient(), ada.email);
    const unknown = await signInFrom(nextClient(), 'nobody@example.com');
    expect(unknown).toEqual(known);
    expect(known).toEqual({ status: 422, message: LOCKED });
    // Both requests queued the same job; the worker finds one account.
    app.queue.assertDispatchedTimes(SendLockoutMailJob, 2);
    await app.queue.work();
    app.mail.assertQueuedCount(LockoutMail, 1).assertQueued(LockoutMail, (_mail, message) => message.to[0]!.address === ada.email);
  });

  it('counts the sign-ins of an address without an account, so the ceiling reveals nothing', async () => {
    for (let i = 1; i <= CEILING; i++) expect((await signInFrom(nextClient(), 'nobody@example.com')).message).toBe('These credentials do not match our records.');
    expect((await signInFrom(nextClient(), 'nobody@example.com')).message).toBe(LOCKED);
  });

  it('tells the owner once a lockout, in their language, and says how to get in', async () => {
    const ada = await app.factory(UserFactory).create({ email: 'ada@example.com', locale: 'de' });
    await fail(ada.email, CEILING);
    for (let i = 1; i <= 3; i++) await signInFrom(nextClient(), ada.email);
    await app.queue.work();
    app.mail.assertQueuedCount(LockoutMail, 1);
    const { subject, text } = app.mail.queued(LockoutMail)[0]!.message;
    expect(subject).toBe('Dein Konto nimmt keine Passwörter mehr an');
    expect(text).toContain('http://localhost/forgot-password');
    expect(text).toContain('Passkey');
  });

  it('turns one client away after five a minute and says how long to wait, without mailing the owner', async () => {
    const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
    const client = nextClient();
    for (let i = 1; i <= 5; i++) await signInFrom(client, ada.email);
    expect((await signInFrom(client, ada.email, 'password')).message).toMatch(/^Too many login attempts/);
    app.queue.assertNotDispatched(SendLockoutMailJob);
  });

  it('starts over after a successful sign-in', async () => {
    const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
    await fail(ada.email, CEILING - 1);
    expect((await signInFrom(nextClient(), ada.email, 'password')).status).toBe(303);
    await fail(ada.email, CEILING);
    expect((await signInFrom(nextClient(), ada.email)).message).toBe(LOCKED);
  });

  it('keeps one account from using the budget of another', async () => {
    const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
    const alan = await app.factory(UserFactory).create({ email: 'alan@example.com' });
    await fail(ada.email, CEILING);
    expect((await signInFrom(nextClient(), ada.email)).message).toBe(LOCKED);
    await app.post('/login', { form: { email: alan.email, password: 'password' } }).assertAuthenticated(alan);
  });

  it('lets a password reset end it, and the new password sign in', async () => {
    const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
    await fail(ada.email, CEILING);
    expect((await signInFrom(nextClient(), ada.email, 'password')).message).toBe(LOCKED);

    await app.post('/forgot-password', { form: { email: ada.email }, headers: { referer: 'http://localhost/forgot-password' } });
    await app.queue.work();
    const [sent] = app.mail.queued(ResetPasswordMail).slice(-1);
    const url = new URL(/https?:\/\/\S+\/reset-password\?\S+(?=\))/.exec(sent!.message.text)![0]);
    const cookie = (await app.get(url.pathname + url.search).assertRedirect('/reset-password')).cookie('password_reset')!;
    await app
      .withCookie('password_reset', cookie)
      .post('/reset-password', { form: { password: 'brand new password', password_confirmation: 'brand new password' }, headers: { referer: 'http://localhost/reset-password' } })
      .assertRedirect('/login');

    await app.post('/login', { form: { email: ada.email, password: 'brand new password' } }).assertAuthenticated(ada);
  });

  it('keeps the browser that signed in with the password past the ceiling, which stops a stranger', async () => {
    const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
    const owner = await app.post('/login', { form: { email: ada.email, password: 'password' } }).assertAuthenticated(ada);
    const device = owner.cookie(DEVICE)!;
    expect(device).toBeTruthy();
    await fail(ada.email, CEILING);
    expect((await signInFrom(nextClient(), ada.email, 'password')).message).toBe(LOCKED);
    await app.withCookie(DEVICE, device).post('/login', { form: { email: ada.email, password: 'password' } }).assertAuthenticated(ada);
  });

  it('gives the browser that completes a password reset a device cookie, so the stranger cannot lock it out again', async () => {
    const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
    await fail(ada.email, CEILING);
    await app.post('/forgot-password', { form: { email: ada.email }, headers: { referer: 'http://localhost/forgot-password' } });
    await app.queue.work();
    const [sent] = app.mail.queued(ResetPasswordMail).slice(-1);
    const url = new URL(/https?:\/\/\S+\/reset-password\?\S+(?=\))/.exec(sent!.message.text)![0]);
    const cookie = (await app.get(url.pathname + url.search).assertRedirect('/reset-password')).cookie('password_reset')!;
    const done = await app
      .withCookie('password_reset', cookie)
      .post('/reset-password', { form: { password: 'brand new password', password_confirmation: 'brand new password' }, headers: { referer: 'http://localhost/reset-password' } })
      .assertRedirect('/login');
    const device = done.cookie(DEVICE)!;
    expect(device).toBeTruthy();
    await fail(ada.email, CEILING);
    expect((await signInFrom(nextClient(), ada.email, 'brand new password')).message).toBe(LOCKED);
    await app.withCookie(DEVICE, device).post('/login', { form: { email: ada.email, password: 'brand new password' } }).assertAuthenticated(ada);
  });

  it('gives the browser that finishes the second factor after the password its device cookie', async () => {
    const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
    const login = await app.post('/login', { form: { email: ada.email, password: 'password' } }).assertRedirect('/dashboard');
    const session = login.cookie(SESSION)!;
    await app.withCookie(SESSION, session).post('/settings/two-factor/setup').assertRedirect('/settings/two-factor');
    const page = await app.withCookie(SESSION, session).navigating().get('/settings/two-factor').assertPage('auth/TwoFactor');
    const { secret } = page.page()!.props.setup as { secret: string };
    await app.withCookie(SESSION, session).layering().post('/settings/two-factor/confirm', { form: { code: twoFactorCode(secret), password: 'password' } }).assertLayer('auth/RecoveryCodes');

    const waiting = await app.post('/login', { form: { email: ada.email, password: 'password' } }).assertRedirect('/two-factor-challenge');
    expect(waiting.cookie(DEVICE), 'nobody is signed in yet: no cookie').toBeUndefined();
    const done = await app.withCookie(SESSION, waiting.cookie(SESSION)!).post('/two-factor-challenge', { form: { code: twoFactorCode(secret, new Date(Date.now() + 30_000)) } }).assertAuthenticated(ada);
    expect(done.cookie(DEVICE)).toBeTruthy();
  });

  it('gives the browser that changes the password a new device cookie, as the new session key ends the old one', async () => {
    const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
    const login = await app.post('/login', { form: { email: ada.email, password: 'password' } }).assertAuthenticated(ada);
    const before = login.cookie(DEVICE)!;
    const changed = await app
      .withCookie(SESSION, login.cookie(SESSION)!)
      .put('/settings/password', { form: { current_password: 'password', password: 'a new password', password_confirmation: 'a new password' } })
      .assertAuthenticated(ada);
    const after = changed.cookie(DEVICE)!;
    expect(after).toBeTruthy();
    await fail(ada.email, CEILING);
    await app.withCookie(DEVICE, before).post('/login', { form: { email: ada.email, password: 'a new password' } }).assertInvalid({ email: LOCKED }).assertGuest();
    await app.withCookie(DEVICE, after).post('/login', { form: { email: ada.email, password: 'a new password' } }).assertAuthenticated(ada);
  });

  it('stays open for a passkey, and a passkey sign-in starts the count over', async () => {
    const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
    const authenticator = softAuthenticator({ origin: 'http://localhost', rpId: 'localhost' });
    const login = await app.post('/login', { form: { email: ada.email, password: 'password' } }).assertRedirect('/dashboard');
    const cookie = login.cookie(SESSION)!;
    const registration = await app.withCookie(SESSION, cookie).post('/settings/passkeys/options', { json: {} }).assertOk();
    await app.withCookie(SESSION, cookie).post('/settings/passkeys', { json: { response: authenticator.register(registration.json() as never), name: 'Laptop', password: 'password' } }).assertOk();

    await fail(ada.email, CEILING + 1);
    expect((await signInFrom(nextClient(), ada.email, 'password')).message).toBe(LOCKED);

    const options = await app.post('/passkeys/sign-in/options', { json: {} }).assertOk();
    const guest = options.cookie(SESSION)!;
    await app.withCookie(SESSION, guest).post('/passkeys/sign-in', { json: { response: authenticator.authenticate(options.json() as never) } }).assertRedirect('/dashboard');
    expect((await signInFrom(nextClient(), ada.email, 'password')).status).toBe(303);
  });

  it('leads the right password of an account with a second factor to the challenge, and starts the count over', async () => {
    let withFactor: unknown;
    class OneFactor extends TwoFactorState {
      async factors(id: unknown) {
        return id === withFactor ? (['totp'] as const) : [];
      }
      async enabledSince() {
        return undefined;
      }
      async removeAll() {}
    }
    await app.close(); // one database app per test
    app = await createTestApp(application, {
      database: 'refresh',
      env: { AUTH_ACCOUNT_SIGN_INS_PER_DAY: String(CEILING) },
      override: (c) => c.instance(TwoFactorState, new OneFactor()),
    });
    ({ session: SESSION } = cookieNames(app));
    const ada = await app.factory(UserFactory).create({ email: 'ada@example.com' });
    withFactor = ada.id;
    await fail(ada.email, CEILING - 1);
    await app.post('/login', { form: { email: ada.email, password: 'password' } }).assertRedirect('/two-factor-challenge').assertGuest();
    // Had the count not started over, these would take it past the ceiling and lock the right password out.
    await fail(ada.email, CEILING - 1);
    await app.post('/login', { form: { email: ada.email, password: 'password' } }).assertRedirect('/two-factor-challenge');
  });
});
