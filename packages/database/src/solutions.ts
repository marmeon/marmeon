import { defineSolutions } from '@marmeon/core';
import { DatabaseConnectionError } from './driver.ts';
import { missingTable } from './errors.ts';
import { MigrationStateError } from './migration-state.ts';
import { MigrationLockTimeoutError } from './migrations/lock.ts';
import { Migrator } from './migrations/migrator.ts';

/**
 * Solutions for database errors: a missing table — with the migrations that have not run yet (`migrate:status`) — and migrations
 * that are not what the code expects.
 * Text only: the error page shows the command, it never runs it.
 */
export const databaseSolutions = defineSolutions([
  {
    for: Error,
    code: 'D9',
    solve: () => ({
      title: 'Name the columns and read a secret one with secret()',
      text:
        'A secret column never leaves the database by accident. Select the columns the query needs, and read a secret one with ' +
        'secret(eb, …) in a query of its own — a relation never loads one.',
      docs: 'docs/migrations.md#secret-columns',
    }),
  },
  {
    for: DatabaseConnectionError,
    code: 'D11',
    solve: () => ({
      title: 'Check the connection and start the database',
      text:
        'The app has no connection to the database. Start the database, check DB_URL (or the DB_* variables) and the connection\'s name, ' +
        'and for SQLite that the directory of the file exists.',
      docs: 'docs/database.md#configuration',
    }),
  },
  {
    for: Error,
    code: 'D6',
    solve: () => ({
      title: "Copy the migrations of your packages into the app",
      text: "A table of a package lacks what the installed release needs. The command lists the packages whose migrations your app does not have yet and, at a terminal, asks which to copy; name one (marmeon publish <package>) to copy without asking. Then migrate. It needs no database.",
      command: 'marmeon publish',
      docs: 'docs/migrations.md#publishing-the-migrations-of-a-package',
    }),
  },
  {
    for: Error,
    code: 'D7',
    when: (e) => /newer version of Marmeon/.test(e.message),
    solve: () => ({
      title: 'Update Marmeon',
      text: 'bootstrap/database.d.ts was generated by a newer version of Marmeon, and no command writes over it. Update @marmeon/* to that version.',
      docs: 'docs/queries.md#table-types',
    }),
  },
  {
    for: Error,
    code: 'D7',
    when: (e) => !/newer version of Marmeon/.test(e.message),
    solve: () => ({
      title: 'Write the generated types again',
      text: 'bootstrap/database.d.ts was generated by another version of Marmeon. Run the command and commit the file.',
      command: 'marmeon db:types',
      docs: 'docs/queries.md#table-types',
    }),
  },
  {
    for: MigrationLockTimeoutError,
    code: 'D8',
    solve: () => ({
      title: 'Wait for the other migration',
      text: 'Another process holds the migration lock. Wait for it to finish, or raise --wait=<seconds>. On Postgres the lock is free as soon as the database notices its process is gone; on other databases it counts as abandoned ten minutes after its last sign of life, at once when it ran on this host.',
      docs: 'docs/migrations.md#one-migration-at-a-time',
    }),
  },
  {
    for: Error,
    when: (e) => missingTable(e) !== undefined,
    solve: async (e, { app }) => {
      const table = missingTable(e)!;
      let pending: string[] | undefined;
      try {
        if (app?.container.has(Migrator)) pending = (await app.container.make(Migrator).status()).filter((migration) => migration.batch === undefined).map((migration) => migration.name);
      } catch {
        // No migrations table yet, or the connection is in a failed transaction: say what to run anyway.
      }
      if (pending?.length === 0) {
        return {
          title: `Create the table "${table}" in a migration`,
          text: `Every migration has run, and none creates "${table}". Add one to the module the table belongs to — or check the table's name in the query.`,
          command: `marmeon make:migration create_${table}_table`,
          docs: 'docs/migrations.md#generating-migrations',
        };
      }
      const list = pending ? `${pending.slice(0, 5).join(', ')}${pending.length > 5 ? `, and ${pending.length - 5} more` : ''}` : undefined;
      return {
        title: pending ? `Run the ${pending.length} pending migration${pending.length === 1 ? '' : 's'}` : 'Run the migrations',
        text:
          `The table "${table}" does not exist in the database. ` +
          (list ? `These migrations have not run yet: ${list}. ` : 'Its migration has probably not run yet ("marmeon migrate:status" lists them). ') +
          'In development, "marmeon migrate:fresh --seed" starts over with the seeders.',
        command: 'marmeon migrate',
        docs: 'docs/migrations.md#running-migrations',
      };
    },
  },
  {
    for: MigrationStateError,
    code: 'D2',
    solve: (e) =>
      e.missing.length === 0
        ? {
            title: 'Carry the record of migrations over',
            text:
              `The record of migrations of the connection "${e.connection}" is in the form Marmeon 0.3 wrote, without a checksum per migration, so every query on it is refused. ` +
              'Run the command: it carries the record over, and the app answers again within a second, without a restart.',
            command: 'marmeon migrate',
            docs: 'docs/migrations.md#how-the-migrator-keeps-track',
          }
        : {
            title: `Run the ${e.missing.length} pending migration${e.missing.length === 1 ? '' : 's'}`,
            text:
              `The database lacks ${e.missing.slice(0, 5).join(', ')}${e.missing.length > 5 ? `, and ${e.missing.length - 5} more` : ''}, which the code has, so every query on the connection "${e.connection}" is refused. ` +
              'Run the command; the app answers again within a second, without a restart. After a rollback, the same: migrate again, or deploy the code that matches the database.',
            command: 'marmeon migrate',
            docs: 'docs/migrations.md#migrating-a-running-app',
          },
  },
  {
    for: MigrationStateError,
    code: 'D1',
    solve: (e) => ({
      title: e.reason === 'newer' ? 'Update Marmeon' : e.reason === 'unmanaged' ? 'Remove managed: false' : 'Migrate the database, or tell Marmeon another tool manages it',
      text:
        e.reason === 'newer'
          ? 'The record of migrations has columns this release does not read: a newer Marmeon migrated this database. Update @marmeon/* to the release that migrated it. Every query on the connection is refused until then.'
          : e.reason === 'unmanaged'
            ? 'The connection is set to `managed: false`, but the database has the record of migrations Marmeon writes, so Marmeon migrates it. Remove the option (DB_MANAGED=false): with it no secret column and no soft delete would be known.'
            : 'The database has tables and no record of migrations, so Marmeon cannot tell which ran. If Marmeon migrates this database, run the command; if another tool manages it, set `managed: false` on the connection (DB_MANAGED=false). A database with marmeon_ tables was migrated by a build that was never released: start it over with "marmeon migrate:fresh".',
      ...(e.reason === 'unmigrated' ? { command: e.message.includes('marmeon_migrations') ? 'marmeon migrate:fresh' : 'marmeon migrate' } : {}),
      docs: 'docs/migrations.md#how-the-migrator-keeps-track',
    }),
  },
]);
