import { ErrorSolutions } from '@marmeon/core';
import { describe, expect, it } from 'vitest';
import { DatabaseConnectionError } from './driver.ts';
import { MigrationLockTimeoutError } from './migrations/lock.ts';
import { databaseSolutions } from './solutions.ts';

describe('the database solutions tied to an error code', () => {
  const registry = new ErrorSolutions(databaseSolutions);

  it('answer a secret column that would leave the database', async () => {
    const found = await registry.find(new Error('[marmeon:D9] This query selects password, a secret column, without secret()'));
    expect(found.map((solution) => solution.code)).toEqual(['D9']);
    expect(await registry.find(new Error('[marmeon:D10] cannot check'))).toEqual([]);
  });

  it('answer a connection that cannot be made', async () => {
    const found = await registry.find(new DatabaseConnectionError('[marmeon:D11] Could not connect to the database connection "default"'));
    expect(found.map((solution) => solution.code)).toEqual(['D11']);
  });

  it('answer framework tables that need their migrations, generated types of another version and a held migration lock', async () => {
    const tables = await registry.find(new Error('[marmeon:D6] jobs is missing — a migration is missing: marmeon publish writes the ones of your packages, then marmeon migrate'));
    expect(tables.map((solution) => [solution.code, solution.command])).toEqual([['D6', 'marmeon publish']]);
    const types = await registry.find(new Error('[marmeon:D7] bootstrap/database.d.ts was generated by another version of Marmeon'));
    expect(types.map((solution) => [solution.code, solution.command])).toEqual([['D7', 'marmeon db:types']]);
    const newer = await registry.find(new Error('[marmeon:D7] bootstrap/database.d.ts was generated by a newer version of Marmeon — update @marmeon/* and is left unchanged'));
    expect(newer.map((solution) => [solution.code, solution.command])).toEqual([['D7', undefined]]);
    const lock = await registry.find(new MigrationLockTimeoutError({ owner: 'web-1:4242' } as never));
    expect(lock.map((solution) => solution.code)).toEqual(['D8']);
  });
});
