import { relative } from 'node:path';
import { Application, environment, Redactor } from '@marmeon/core';
import type { AppCheck, AppCheckContext, AppCheckResult } from 'marmeon';
import { TypeGenerator } from './types-gen/generator.ts';

/**
 * `bootstrap/database.d.ts` matches the migrations. Runs the migrations on a scratch database, so it needs the booted app. On
 * Postgres that is a temporary database (`<db>_types_<id>`) created and dropped on the server, so there it runs in development and test only.
 * See docs/check.md#the-checks.
 */
export class DbTypesCheck implements AppCheck {
  static check = 'db-types';
  static phase = 'run' as const;

  readonly #generator: TypeGenerator;
  readonly #app: Application;

  constructor(generator: TypeGenerator, app: Application) {
    this.#generator = generator;
    this.#app = app;
  }

  async handle({ signal }: Partial<AppCheckContext> = {}): Promise<AppCheckResult> {
    const file = relative(this.#app.root, this.#generator.path).split('\\').join('/');
    const format = this.#generator.fileFormat();
    if (format === undefined) return [{ severity: 'error', message: `${file} does not exist`, file, fix: 'marmeon db:types' }];
    if (format === 'newer') return [{ severity: 'error', message: `${file} was generated by a newer version of Marmeon — update @marmeon/*`, file }];
    if (format === 'other') return [{ severity: 'error', message: `${file} was generated by another version of Marmeon`, file, fix: 'marmeon db:types' }];
    if (this.#generator.createsDatabase() && !environment.isDevelopment() && !environment.isTest()) {
      return { skipped: 'it creates a temporary database on the database server; it runs in development and test only' };
    }
    try {
      return (await this.#generator.isCurrent(signal)) ? [] : [{ severity: 'error', message: `${file} is out of date`, file, fix: 'marmeon db:types' }];
    } catch (error) {
      // The migrations do not run on a scratch database: the check cannot say, which is not the same as the types being stale.
      const redactor = this.#app.container.has(Redactor) ? this.#app.container.make(Redactor) : new Redactor();
      throw new Error(`the migrations did not run on a scratch database: ${redactor.text(error instanceof Error ? error.message : String(error))}`);
    }
  }
}
