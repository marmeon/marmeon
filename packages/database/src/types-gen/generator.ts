import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { Application } from '@marmeon/core';
import { withCode } from '@marmeon/core/internal';
import { Connections } from '../connections.ts';
import { deriveRelations, relationProblemsMessage } from '../introspection.ts';
import { Migrator } from '../migrations/migrator.ts';
import { factsOf } from '../schema/projection.ts';
import { renderTypes, TYPES_FORMAT, TYPES_FORMAT_MARK, type Rendered, type SchemaSnapshot } from './render.ts';

declare module '@marmeon/core' {
  interface ModuleDefinition {
    /**
     * Own tables other modules may read and join (never write):
     * `defineModule({ name: 'auth', exposes: ['users'] })`. Everything else stays private to the module.
     */
    readonly exposes?: readonly string[];
  }
}

/** Where the generated types live, relative to the app root. Committed, so type checks need no database. */
export const TYPES_FILE = 'bootstrap/database.d.ts';

/**
 * Generates the table types **from the migrations**: their plans are projected without running anything, so no database is
 * needed and the result never depends on the state of the development database. Raw SQL is not looked into.
 */
export class TypeGenerator {
  readonly #app: Application;
  readonly #connections: Connections;
  readonly #migrator: Migrator;

  constructor(app: Application, connections: Connections, migrator: Migrator) {
    this.#app = app;
    this.#connections = connections;
    this.#migrator = migrator;
  }

  get path(): string {
    return join(this.#app.root, TYPES_FILE);
  }

  async render(signal?: AbortSignal): Promise<Rendered> {
    return renderTypes(await this.#snapshot(signal));
  }

  /** Writes the file; returns whether it changed. */
  async write(): Promise<{ changed: boolean; warnings: string[] }> {
    this.#refuseNewer();
    const { source, warnings } = await this.render();
    const changed = !existsSync(this.path) || readFileSync(this.path, 'utf8') !== source;
    if (changed) {
      mkdirSync(dirname(this.path), { recursive: true });
      writeFileSync(this.path, source);
    }
    return { changed, warnings };
  }

  /**
   * @internal For the commands of this package.
   * How the committed file relates to this version's format: `undefined` without a file, `'current'`, `'newer'` (a process of a
   * newer Marmeon wrote it: never touched) or `'other'` (no mark or an older one: regenerating is the fix).
   */
  fileFormat(): 'current' | 'newer' | 'other' | undefined {
    if (!existsSync(this.path)) return undefined;
    const lines = readFileSync(this.path, 'utf8').split(/\r?\n/).slice(0, 5);
    if (lines.includes(TYPES_FORMAT_MARK)) return 'current';
    const found = lines.map((line) => /^\/\/ @marmeon-format (\d+)$/.exec(line)?.[1]).find((n) => n !== undefined);
    return found !== undefined && Number(found) > TYPES_FORMAT ? 'newer' : 'other';
  }

  /** Throws when the committed file is of a newer format: such a file is never written over. */
  #refuseNewer(): void {
    if (this.fileFormat() === 'newer') throw new Error(withCode('D7', `${relative(this.#app.root, this.path)} was generated by a newer version of Marmeon — update @marmeon/* and is left unchanged`));
  }

  /** Whether the committed file matches the migrations. */
  async isCurrent(signal?: AbortSignal): Promise<boolean> {
    return existsSync(this.path) && readFileSync(this.path, 'utf8') === (await this.render(signal)).source;
  }

  /**
   * @internal For the commands: the D26 message when the foreign keys of the migrations give relations that clash, `undefined` when
   * they do not. Read from the migration files, so it holds before a migration ran.
   */
  async relationsRefusal(): Promise<string | undefined> {
    const projection = await this.#migrator.projection();
    return relationProblemsMessage(deriveRelations(factsOf(projection, this.#connections.options().driver)).problems);
  }

  async #snapshot(signal?: AbortSignal): Promise<SchemaSnapshot> {
    if (signal?.aborted) throw signal.reason;
    const projection = await this.#migrator.projection();
    const driver = this.#connections.options().driver;
    // The same derivation the connection uses at runtime, so the generated names are the names that work.
    const derived = deriveRelations(factsOf(projection, driver));
    const problems = relationProblemsMessage(derived.problems);
    if (problems) throw new Error(problems);
    return {
      driver,
      projection,
      relations: derived.relations,
      modules: this.#app.modules.map((module) => module.name),
      exposes: new Map(this.#app.modules.filter((m) => m.exposes?.length).map((m) => [m.name, m.exposes!])),
    };
  }
}
